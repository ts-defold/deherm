const root = new URL("../", import.meta.url);
const urls = {
  ir: new URL("packages/bindings/generated/defold-script-api-ir.json", root),
  patterns: new URL("packages/bindings/generated/defold-script-binding-patterns.json", root),
  override: new URL("packages/bindings/overrides/script-url-address-classification.json", root),
  output: new URL("packages/bindings/generated/defold-script-url-address-classification.json", root),
  facts: new URL("packages/bindings/generated/defold-script-url-binding-recipe-facts.json", root),
  header: new URL("defold/defold_hermes/include/defold_hermes/generated_script_url_bindings.hpp", root),
  source: new URL("defold/defold_hermes/src/generated_script_url_bindings.cpp", root),
  target: new URL("packages/sdk/src/generated/script/url-target-support.ts", root),
};

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

function parse(text, label) {
  try {
    return JSON.parse(text);
  } catch (error) {
    throw new Error(`${label} is not valid JSON: ${error.message}`);
  }
}

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function compare(left, right) {
  return left < right ? -1 : left > right ? 1 : 0;
}

function uniqueMap(rows, label) {
  const result = new Map();
  for (const row of rows) {
    assert(typeof row.id === "string" && row.id.length > 0, `${label} contains a row without an id`);
    assert(!result.has(row.id), `${label} contains duplicate id '${row.id}'`);
    result.set(row.id, row);
  }
  return result;
}

function countBy(values, select) {
  const counts = {};
  for (const value of values) {
    const key = select(value);
    counts[key] = (counts[key] ?? 0) + 1;
  }
  return Object.fromEntries(Object.entries(counts).sort(([a], [b]) => compare(a, b)));
}

function allTypes(fn) {
  return [...fn.parameters.map(({ rawType }) => rawType), ...fn.returns];
}

function formsFor(rawType) {
  if (rawType === "string|hash|url") return ["string-shorthand", "hash-shorthand", "full-url"];
  if (rawType === "url|number|nil") return ["full-url", "numeric-camera-id", "nil-default"];
  throw new Error(`unreviewed URL parameter type '${rawType}'`);
}

function split(rawType) {
  return rawType
    .split("|")
    .map((part) => part.trim())
    .filter(Boolean);
}

const TYPE_CODECS = new Map([
  ["nil", "Nil"],
  ["boolean", "Boolean"],
  ["integer", "Integer"],
  ["number", "Number"],
  ["string", "String"],
  ["hash", "Hash"],
  ["url", "Url"],
  ["vector3", "Vector3"],
  ["vector4", "Vector4"],
  ["quaternion", "Quaternion"],
]);

function codecsFor(rawType, optional, id) {
  const codecs = split(rawType).map(
    (type) => TYPE_CODECS.get(type) ?? (/^[A-Za-z_][A-Za-z0-9_.]*$/.test(type) ? "Integer" : null),
  );
  assert(codecs.every(Boolean), `${id}: unsupported generated URL argument type '${rawType}'`);
  if (optional && !codecs.includes("Nil")) codecs.push("Nil");
  return [...new Set(codecs)];
}

function resultCodecFor(returns, id) {
  assert(returns.length <= 1, `${id}: URL dispatcher requires a scalar or void result`);
  if (returns.length === 0) return "None";
  const rawType = returns[0];
  if (rawType === "hash|nil") return "HashOrNil";
  const codecs = codecsFor(rawType, false, id);
  assert(codecs.length === 1, `${id}: unsupported generated URL result union '${rawType}'`);
  const codec = codecs[0];
  if (codec === "Nil" || codec === "Url") return codec;
  return codec === "Integer" ? "Integer" : codec;
}

export function scriptUrlBindingRecipeFacts(report) {
  return {
    schemaVersion: 1,
    optimizedRouteCount: report.optimizedRouteCount,
    universalFallbackRouteCount: report.universalFallbackRouteCount,
    operations: [...report.rows]
      .sort((left, right) => left.stableId - right.stableId)
      .map(
        ({
          id,
          stableId,
          modulePath,
          member,
          argumentCodecs,
          requiredArgumentCount,
          maximumArgumentCount,
          resultCodec,
        }) => ({
          id,
          stableId,
          module: modulePath.join("."),
          member,
          argumentCodecs,
          requiredArgumentCount,
          maximumArgumentCount,
          resultCodec,
        }),
      ),
  };
}

export function renderScriptUrlAddressRuntime(report) {
  const facts = scriptUrlBindingRecipeFacts(report);
  return {
    ...renderScriptUrlNativeOutputs(facts),
    target: `// Generated by scripts/generate-script-url-address-classification.mjs. Do not edit.\nexport const scriptUrlTargetSupport = ${JSON.stringify(report.targetSupport, null, 2)} as const;\nexport const scriptUrlExecutableRouteCount = ${report.optimizedRouteCount} as const;\nexport const scriptUrlUniversalFallbackRouteCount = ${report.universalFallbackRouteCount} as const;\n`,
  };
}

// The cited sources are OBSERVED while loading, where a moved hash becomes an
// audit line and a lost anchor withdraws that citation for this revision. Route
// discovery still comes from this revision's own IR and binding patterns. A
// withdrawn source fact preserves the descriptor but removes its replay
// optimization, so the generated dispatcher reaches the universal fallback.
function validateSources(override, sourceTexts, withdrawnSources) {
  const evidenceById = uniqueMap(override.sourceEvidence, "URL source evidence");
  for (const evidence of override.sourceEvidence) {
    if (withdrawnSources.has(evidence.source)) continue;
    assert(typeof sourceTexts.get(evidence.source) === "string", `${evidence.id}: source was not loaded`);
  }
  const required = override.optimizationEvidence?.requiredSourceEvidence;
  assert(Array.isArray(required) && required.length > 0, "URL optimization evidence has no required sources");
  assert(new Set(required).size === required.length, "URL optimization evidence repeats a required source");
  for (const id of required) assert(evidenceById.has(id), `URL optimization requires unknown evidence '${id}'`);
  return evidenceById;
}

// A reviewed count map. Fatal in an ordinary generation, reported per key in a
// declared derivation of another revision, so the report names WHICH module
// moved instead of dumping two objects at a reader.
function compareCounts(actual, expected, label) {
  if (JSON.stringify(actual) === JSON.stringify(expected)) return;
  for (const key of [...new Set([...Object.keys(expected), ...Object.keys(actual)])].sort(compare)) {
    expectReviewedCount({
      input: "packages/bindings/overrides/script-url-address-classification.json",
      label: `${label}:${key}`,
      expected: expected[key] ?? 0,
      observed: actual[key] ?? 0,
    });
  }
}

export function generateScriptUrlAddressClassification(inputs) {
  const ir = parse(inputs.irText, "script API IR");
  const patterns = parse(inputs.patternsText, "script binding patterns");
  const override = parse(inputs.overrideText, "URL classification override");
  assert(override.schemaVersion === 2, "URL classification override has an unsupported schema");
  assert(ir.defoldRevision === patterns.defoldRevision, "URL classification inputs use different Defold revisions");
  // Reviewed evidence, compared against the revision being generated.
  // `validateSources` immediately re-reads every cited Defold source at that
  // revision and checks its SHA-256 and anchors, which is the check that
  // actually establishes whether the review still holds.
  assertReviewedRevision({
    input: "packages/bindings/overrides/script-url-address-classification.json",
    reviewed: override.defoldRevision,
    derived: ir.defoldRevision,
    detail: "the reviewed URL/address value shapes",
  });
  const withdrawnSources = inputs.withdrawnSources ?? new Set();
  const evidenceById = validateSources(override, inputs.sourceTexts, withdrawnSources);
  const requiredSourceEvidence = [...override.optimizationEvidence.requiredSourceEvidence];
  const missingSourceEvidence = requiredSourceEvidence.filter((id) =>
    withdrawnSources.has(evidenceById.get(id).source),
  );
  const optimizationProven = missingSourceEvidence.length === 0;
  const targetSupport = structuredClone(override.targetSupport);
  if (!optimizationProven) {
    targetSupport.nativeDynamicHermes = {
      status: "universal-fallback-missing-proof",
      requiredRoute: `Restore structural URL replay evidence: ${missingSourceEvidence.join(", ")}`,
    };
  }

  const irById = uniqueMap(ir.functions, "script API IR");
  uniqueMap(patterns.bindings, "script binding patterns");
  const classified = patterns.bindings.filter((row) => row.loweringFamily === "defold-value");
  expectReviewedCount({
    input: "packages/bindings/overrides/script-url-address-classification.json",
    label: "classified defold-value census",
    expected: override.expectedCounts.classifiedDefoldValue,
    observed: classified.length,
  });
  const matrixIds = new Set();
  const urlIds = new Set();
  const urlCandidateIds = new Set();
  const remainderIds = new Set();
  const excludedUrlIds = new Set(override.excludedPreexistingUrlIds);
  expectReviewedCount({
    input: "packages/bindings/overrides/script-url-address-classification.json",
    label: "excluded pre-existing URL route census",
    expected: override.expectedCounts.excludedPreexistingUrl,
    observed: excludedUrlIds.size,
  });
  for (const pattern of classified) {
    const fn = irById.get(pattern.id);
    assert(fn, `${pattern.id}: pattern row is absent from pinned IR`);
    assert(
      JSON.stringify(pattern.parameterCodecs.map(({ rawType }) => rawType)) ===
        JSON.stringify(fn.parameters.map(({ rawType }) => rawType)) &&
        JSON.stringify(pattern.returnCodecs.map(({ rawType }) => rawType)) === JSON.stringify(fn.returns),
      `${pattern.id}: binding-pattern shapes differ from pinned IR`,
    );
    const types = allTypes(fn);
    if (types.some((type) => type.includes("matrix4"))) matrixIds.add(pattern.id);
    else if (types.some((type) => type.includes("url"))) {
      urlCandidateIds.add(pattern.id);
      if (!excludedUrlIds.has(pattern.id)) urlIds.add(pattern.id);
    } else remainderIds.add(pattern.id);
  }
  expectReviewedCount({
    input: "packages/bindings/overrides/script-url-address-classification.json",
    label: "matrix4 disjoint census",
    expected: override.expectedCounts.matrix4Disjoint,
    observed: matrixIds.size,
  });
  expectReviewedCount({
    input: "packages/bindings/overrides/script-url-address-classification.json",
    label: "URL/address route count",
    expected: override.expectedCounts.total,
    observed: urlIds.size,
  });
  expectReviewedCount({
    input: "packages/bindings/overrides/script-url-address-classification.json",
    label: "URL/address candidate count",
    expected: override.expectedCounts.urlCandidates,
    observed: urlCandidateIds.size,
  });
  for (const id of excludedUrlIds)
    assert(urlCandidateIds.has(id), `${id}: pinned URL exclusion left the candidate set`);
  expectReviewedCount({
    input: "packages/bindings/overrides/script-url-address-classification.json",
    label: "non-matrix/non-URL defold-value census",
    expected: override.expectedCounts.nonMatrixNonUrl,
    observed: remainderIds.size,
  });
  const binaryIds = new Set(override.binaryStringRemainderIds);
  // The reviewed list against its own recorded size is internal consistency and
  // stays exact; whether each reviewed route is still in this revision's
  // remainder is a census.
  assert(
    binaryIds.size === override.expectedCounts.binaryStringRemainder,
    "binary-string reviewed remainder count drifted",
  );
  expectReviewedCount({
    input: "packages/bindings/overrides/script-url-address-classification.json",
    label: "binary-string remainder membership",
    expected: binaryIds.size,
    observed: [...binaryIds].filter((id) => remainderIds.has(id)).length,
  });
  const rows = [...urlIds].sort(compare).map((id) => {
    const fn = irById.get(id);
    const urlParameters = fn.parameters.flatMap((parameter, index) =>
      parameter.rawType.includes("url")
        ? [
            {
              index,
              name: parameter.rawName,
              rawType: parameter.rawType,
              forms: formsFor(parameter.rawType),
            },
          ]
        : [],
    );
    assert(urlParameters.length > 0, `${id}: selected URL route has no URL parameter`);
    assert(
      fn.returns.every((type) => !type.includes("url")),
      `${id}: URL result requires copy-before-pop routing not enabled by this planned classifier`,
    );
    const lastRequiredIndex = fn.parameters.reduce(
      (result, parameter, index) => (parameter.optional ? result : index),
      -1,
    );
    const requiredArgumentCount = lastRequiredIndex + 1;
    const argumentCodecs = fn.parameters.map(({ rawType, optional }) => codecsFor(rawType, optional, id));
    const resultCodec = resultCodecFor(fn.returns, id);
    return {
      id,
      stableId: stableBindingId(id),
      rawName: fn.rawName,
      modulePath: fn.modulePath,
      member: fn.member,
      source: fn.source,
      line: fn.line,
      requiredArgumentCount,
      maximumArgumentCount: fn.parameters.length,
      argumentCodecs,
      resultCodec,
      urlParameters,
      urlResults: [],
      routing: {
        status: optimizationProven ? "generated-native-dynamic" : "universal-fallback-missing-proof",
        blockers: missingSourceEvidence,
        fullUrl: "ScriptUrlArena token -> exact dmMessage::URL -> dmScript::PushURL",
        stringShorthand: "push unchanged Lua string; callee applies captured-instance address defaults",
        hashShorthand: "push unchanged Lua hash; callee applies its default-socket address semantics",
        result: "copy dmMessage::URL into ScriptUrlArena before restoring/popping Lua stack",
      },
      optimizationProven,
      targetSupport,
    };
  });
  assert(
    new Set(rows.map(({ stableId }) => stableId)).size === rows.length,
    "URL/address route stable-ID collision detected",
  );
  const moduleCounts = countBy(rows, ({ modulePath }) => modulePath.join("."));
  compareCounts(moduleCounts, override.expectedCounts.modules, "URL/address module census");
  const urlParameters = rows.flatMap(({ urlParameters }) => urlParameters);
  expectReviewedCount({
    input: "packages/bindings/overrides/script-url-address-classification.json",
    label: "URL parameter count",
    expected: override.expectedCounts.urlParameters,
    observed: urlParameters.length,
  });
  const rawUrlParameterTypeCounts = countBy(urlParameters, ({ rawType }) => rawType);
  compareCounts(rawUrlParameterTypeCounts, override.expectedCounts.rawUrlParameterTypes, "URL parameter type census");

  const inputEvidence = {
    scriptIrSha256: sha256(inputs.irText),
    bindingPatternsSha256: sha256(inputs.patternsText),
    classificationOverrideSha256: sha256(inputs.overrideText),
    defoldSources: [...override.sourceEvidence]
      .filter(({ source }) => !withdrawnSources.has(source))
      .sort((a, b) => compare(a.source, b.source))
      .map(({ id, source, sha256 }) => ({
        id,
        path: `upstream/defold/${source}`,
        sha256,
      })),
  };
  inputEvidence.aggregateInputSha256 = sha256(
    [
      inputEvidence.scriptIrSha256,
      inputEvidence.bindingPatternsSha256,
      inputEvidence.classificationOverrideSha256,
      ...inputEvidence.defoldSources.map(({ path, sha256 }) => `${path}\0${sha256}`),
    ].join("\0"),
  );

  return {
    schemaVersion: 1,
    defoldRevision: ir.defoldRevision,
    scope: "The exact non-Matrix4 defold-value routes whose pinned IR contains a URL/address parameter",
    coverageClaim: override.coverageClaim,
    allocationClaim: override.allocationClaim,
    routeCount: rows.length,
    optimizedRouteCount: optimizationProven ? rows.length : 0,
    universalFallbackRouteCount: optimizationProven ? 0 : rows.length,
    urlParameterCount: urlParameters.length,
    moduleCounts,
    rawUrlParameterTypeCounts,
    disjointCensus: {
      classifiedDefoldValue: classified.length,
      matrix4Disjoint: matrixIds.size,
      urlCandidates: urlCandidateIds.size,
      excludedPreexistingUrl: excludedUrlIds.size,
      urlAddressRoutes: rows.length,
      nonMatrixNonUrl: remainderIds.size,
      binaryStringRemainder: binaryIds.size,
      otherNonMatrixNonUrl: remainderIds.size - binaryIds.size,
    },
    representationPolicy: {
      fullUrl: "four exact uint64 lanes (socket, reserved, path, fragment) in a generation-checked ScriptUrlArena slot",
      stringShorthand: "distinct string value resolved by Defold against captured Lua caller context",
      hashShorthand: "distinct hash value resolved by Defold as default-socket path with zero fragment",
      collapsedLegacyUrl: "fail-closed: ScriptHandleKind::kUrl with no sidecar slot is never interpreted as a full URL",
    },
    optimizationEvidence: {
      requiredSourceEvidence,
      availableSourceEvidence: requiredSourceEvidence.filter((id) => !missingSourceEvidence.includes(id)),
      missingSourceEvidence,
      executionContext: override.optimizationEvidence.executionContext,
      codecProof: override.optimizationEvidence.codecProof,
      ownership: override.optimizationEvidence.ownership,
    },
    targetSupport,
    inputEvidence,
    rows,
  };
}

export async function loadScriptUrlAddressInputs() {
  const [irText, patternsText, overrideText] = await Promise.all([
    readFile(urls.ir, "utf8"),
    readFile(urls.patterns, "utf8"),
    readFile(urls.override, "utf8"),
  ]);
  const override = parse(overrideText, "URL classification override");
  const loaded = await loadReviewedSources({
    input: "packages/bindings/overrides/script-url-address-classification.json",
    defoldRoot: fileURLToPath(new URL("upstream/defold", root)),
    evidence: override.sourceEvidence.map(({ source, sha256, anchors }) => ({ path: source, sha256, anchors })),
    derived: parse(irText, "script API IR").defoldRevision,
  });
  return {
    irText,
    patternsText,
    overrideText,
    sourceTexts: loaded.texts,
    withdrawnSources: loaded.withdrawn,
  };
}

async function main(argv = process.argv.slice(2)) {
  const outputIndex = argv.indexOf("--output");
  const outputPath = outputIndex >= 0 ? argv[outputIndex + 1] : null;
  const consumed = new Set(outputIndex >= 0 ? [outputIndex, outputIndex + 1] : []);
  const unknown = argv.filter((argument, index) => argument !== "--check" && !consumed.has(index));
  if (unknown.length) throw new Error(`Unknown argument: ${unknown[0]}`);
  if (outputIndex >= 0 && (!outputPath || outputPath.startsWith("--"))) {
    throw new Error("--output requires a file path");
  }
  const check = argv.includes("--check");
  if (check && outputPath) throw new Error("--check and --output are mutually exclusive");
  const report = generateScriptUrlAddressClassification(await loadScriptUrlAddressInputs());
  const generated = `${JSON.stringify(report, null, 2)}\n`;
  const runtime = renderScriptUrlAddressRuntime(report);
  const facts = `${JSON.stringify(scriptUrlBindingRecipeFacts(report), null, 2)}\n`;
  if (check) {
    const current = await Promise.all([
      readFile(urls.output, "utf8"),
      readFile(urls.header, "utf8"),
      readFile(urls.source, "utf8"),
      readFile(urls.target, "utf8"),
      readFile(urls.facts, "utf8"),
    ]);
    const expected = [generated, runtime.header, runtime.source, runtime.target, facts];
    const labels = [
      urls.output.pathname,
      urls.header.pathname,
      urls.source.pathname,
      urls.target.pathname,
      urls.facts.pathname,
    ];
    for (let index = 0; index < current.length; ++index) {
      if (current[index] !== expected[index])
        throw new Error(`${labels[index]} is stale; regenerate URL/address bindings`);
    }
  } else {
    if (outputPath) await writeFile(outputPath, generated);
    else
      await Promise.all([
        writeFile(urls.output, generated),
        writeFile(urls.header, runtime.header),
        writeFile(urls.source, runtime.source),
        writeFile(urls.target, runtime.target),
        writeFile(urls.facts, facts),
      ]);
  }
  console.log(
    `${check ? "Verified" : "Generated"} ${report.optimizedRouteCount} native-dynamic URL/address routes and ${report.universalFallbackRouteCount} universal fallbacks with exact composite sidecars; Static/Wasm and HTML5 full URLs fail closed.`,
  );
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) await main();
