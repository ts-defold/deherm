#!/usr/bin/env node

// Generates the headless Defold conformance harness from the pinned binding IR.
//
// Two kinds of output:
//   * the durable contract plan in packages/bindings/generated, which records
//     every contract as either a reachable fixture or an explicit blocker; and
//   * a disposable Defold project under build/conformance/headless/project,
//     holding one minimal collection, game object and script per reachable
//     contract plus the generated TypeScript that exercises it.
//
// Per-contract content selection follows Defold's own engine harness in
// engine/engine/src/test/test_engine.cpp: the driver picks a case with
// `--config=bootstrap.main_collection=...` and the content signals the verdict
// through the engine exit code.
//
// The shape of a case's collection is chosen by its contract's fixture
// profile, never by its identity: a profile says which components the single
// generated game object carries and which engine configuration the driver
// passes, so the physics profiles produce a collection that owns a real
// physics world and real collision objects.

import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import {
  FIXTURE_PROFILES,
  SCRATCH_REUSE_REPETITIONS,
  buildHeadlessConformancePlan,
  loadHeadlessConformanceInputs
} from "./lib/headless-conformance-plan.mjs";

const root = new URL("../", import.meta.url);
const repoRoot = fileURLToPath(root);
const planPath = "packages/bindings/generated/defold-headless-conformance-plan.json";
// Generated TypeScript lives beside the other generated binding artifacts so it
// is type-checked against the real SDK surface; the Defold project content is
// disposable build output.
const typescriptDirectory = "packages/bindings/generated/headless-conformance";
const projectDirectory = "build/conformance/headless/project";

const GENERATED_BANNER = "// Generated by scripts/generate-headless-conformance.mjs. Do not edit.";
const GENERATED_LUA_BANNER = "-- Generated by scripts/generate-headless-conformance.mjs. Do not edit.";

/** Component id of the déherm script on every fixture game object. */
const SCRIPT_COMPONENT = "deherm";
/** Component id of the collision object a physics profile carries. */
const PHYSICS_COMPONENT = "physics";
/** Instance id of the second physics probe, so a route needing two distinct engine objects gets two. */
const SECOND_PROBE = "probe_b";
const PRIMARY_PROBE = "probe";

// Which déherm update the contract runs on.
//
// Defold updates script components (priority 200) before collision objects
// (priority 400), so on the first update no component world has stepped yet
// and engine state a real game would always see - broad-phase proxies, for one
// - does not exist. Running on the second update means every contract is
// exercised against a fully stepped frame, which is the state a shipped game
// calls these routes from.
const CONTRACT_RUN_TICK = 2;
const FIXTURE_EXIT_TICK = CONTRACT_RUN_TICK + 1;

const profileById = new Map(FIXTURE_PROFILES.map((profile) => [profile.id, profile]));

function literal(value) {
  return JSON.stringify(value);
}

