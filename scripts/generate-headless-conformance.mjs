function collectionProxy(slug) {
  return `collection: "/conformance/${slug}.collection"\nexclude: false\n`;
}

function harnessModule() {
  return `${GENERATED_BANNER}
//
// Generic contract properties. Each property is decided by the contract record
// in the canonical lowering plan, never by per-route knowledge, so the same
// three checks apply to every contract the harness can reach.

export type Report = (line: string) => void;

/** A provider produces one live borrowed handle from the running engine. */
export type Provider = (ordinal: number) => unknown;

/**
 * How one argument is obtained. A literal is a synthesized inhabitant; a
 * handle is produced by running that handle kind's producer chain against the
 * same engine instance the exercise runs in.
 */
export type ArgumentSpec =
  | { readonly kind: "literal"; readonly value: unknown }
  | { readonly kind: "handle"; readonly handleKind: string; readonly ordinal: number };

export interface Exercise {
  readonly contract: string;
  readonly route: string;
  readonly arity: string;
  readonly call: (...args: readonly unknown[]) => unknown;
  readonly args: readonly ArgumentSpec[];
  readonly providers: Readonly<Record<string, Provider>>;
  readonly minimumResultCount: number;
  readonly maximumResultCount: number;
  readonly resultCodec: string | null;
  readonly resultNullable: boolean;
  readonly minimumArgumentCount: number;
  /**
   * False when the route destroys the engine object it was given. A second
   * invocation would then be addressing something that no longer exists, so
   * the repetition-based properties observe the harness rather than the
   * contract and are recorded as not applicable instead.
   */
  readonly repeatable: boolean;
  readonly scratchReuse: boolean;
  readonly errorModel: boolean;
}

const MARKER = "deherm-headless-conformance";
const SCRATCH_REPETITIONS = ${SCRATCH_REUSE_REPETITIONS};

function detail(value: unknown): string {
  const text = value instanceof Error ? value.message : String(value);
  return text.replace(/[\\t\\r\\n]+/g, " ").slice(0, 200);
}

function emit(report: Report, exercise: Exercise, property: string, disposition: string, note: string): boolean {
  report(\`\${MARKER}\\t\${exercise.contract}\\t\${exercise.route}#\${exercise.arity}\\t\${property}\\t\${disposition}\\t\${note}\`);
  return disposition !== "mismatched";
}

function arityHolds(exercise: Exercise, value: unknown): boolean {
  if (exercise.maximumResultCount === 0) return value === undefined;
  if (exercise.minimumResultCount >= 1) return value !== undefined;
  return true;
}

function codecHolds(exercise: Exercise, value: unknown): boolean {
  const codec = exercise.resultCodec;
  if (codec === null) return true;
  if (value === null || value === undefined) return exercise.resultNullable || codec === "None";
  if (codec === "None") return false;
  if (codec === "Boolean") return typeof value === "boolean";
  if (codec === "String") return typeof value === "string";
  if (codec === "Integer" || codec === "Number") return typeof value === "number";
  return true;
}

function invoke(call: (...args: readonly unknown[]) => unknown, args: readonly unknown[]):
  { thrown: false; value: unknown } | { thrown: true; error: unknown } {
  try {
    return { thrown: false, value: call(...args) };
  } catch (error) {
    return { thrown: true, error };
  }
}

/**
 * Resolve the argument list, running each handle kind's producer chain against
 * the live engine. A producer that cannot deliver is reported as an explicit
 * blocker rather than a mismatch: it is evidence about handle provenance, not
 * about this route's contract.
 */
function resolveArguments(report: Report, exercise: Exercise): readonly unknown[] | null {
  const resolved: unknown[] = [];
  for (const spec of exercise.args) {
    if (spec.kind === "literal") {
      resolved.push(spec.value);
      continue;
    }
    const provider = exercise.providers[spec.handleKind];
    if (provider === undefined) {
      emit(report, exercise, "handle-provenance", "blocked-no-provider", spec.handleKind);
      return null;
    }
    let produced: unknown;
    try {
      produced = provider(spec.ordinal);
    } catch (error) {
      emit(report, exercise, "handle-provenance", "blocked-producer-raised", \`\${spec.handleKind}: \${detail(error)}\`);
      return null;
    }
    if (produced === undefined || produced === null) {
      emit(report, exercise, "handle-provenance", "blocked-producer-absent", spec.handleKind);
      return null;
    }
    emit(report, exercise, "handle-provenance", "observed", \`\${spec.handleKind}#\${spec.ordinal}\`);
    resolved.push(produced);
  }
  return resolved;
}

export function runExercise(report: Report, exercise: Exercise): boolean {
  let ok = true;

  const args = resolveArguments(report, exercise);
  if (args === null) {
    // The contract keeps its blocker; nothing was observed and nothing is
    // claimed. A separate exercise of the same contract may still succeed.
    return true;
  }

  // result-arity: the boundary either produced a value consistent with the
  // declared marshalling program, or refused the synthesized argument through
  // the declared error model. Both are honest observations; only a shape the
  // plan forbids is a mismatch.
  const first = invoke(exercise.call, args);
  if (first.thrown) {
    ok = emit(report, exercise, "result-arity", "observed-as-target-exception", detail(first.error)) && ok;
  } else if (!arityHolds(exercise, first.value)) {
    ok = emit(report, exercise, "result-arity", "mismatched",
      \`expected \${exercise.minimumResultCount}..\${exercise.maximumResultCount} results, received \${typeof first.value}\`) && ok;
  } else if (!codecHolds(exercise, first.value)) {
    ok = emit(report, exercise, "result-arity", "mismatched",
      \`expected \${String(exercise.resultCodec)} result, received \${typeof first.value}\`) && ok;
  } else {
    ok = emit(report, exercise, "result-arity", "observed", typeof first.value) && ok;
  }

  // scratch-reuse: the declared scratch contract is caller-owned, bounded and
  // reentrant. Repeated invocation must therefore keep producing the same
  // disposition; a leaking or exhausting arena diverges here.
  if (exercise.scratchReuse && !exercise.repeatable) {
    ok = emit(report, exercise, "scratch-reuse", "not-applicable",
      "route destroys its engine object, so repetition would not address the same object") && ok;
  } else if (exercise.scratchReuse) {
    let diverged = "";
    for (let index = 0; index < SCRATCH_REPETITIONS && diverged === ""; index += 1) {
      const repeat = invoke(exercise.call, args);
      if (repeat.thrown !== first.thrown) {
        diverged = \`repetition \${index} changed disposition\`;
      } else if (!repeat.thrown && !arityHolds(exercise, repeat.value)) {
        diverged = \`repetition \${index} violated result arity\`;
      }
    }
    ok = diverged === ""
      ? emit(report, exercise, "scratch-reuse", "observed", \`\${SCRATCH_REPETITIONS} repetitions\`) && ok
      : emit(report, exercise, "scratch-reuse", "mismatched", diverged) && ok;
  }

  // error-model: the declared model is a status return plus a target
  // exception. Removing the required arguments must raise into the target
  // language and must leave the boundary usable.
  if (exercise.errorModel && exercise.minimumArgumentCount >= 1) {
    let raised = false;
    try {
      exercise.call();
    } catch {
      raised = true;
    }
    if (!raised) {
      ok = emit(report, exercise, "error-model", "mismatched", "under-supplied call did not raise") && ok;
    } else if (!exercise.repeatable) {
      // The raise is observed; re-invoking to prove the boundary stayed usable
      // would destroy a second engine object, so it is deliberately withheld.
      ok = emit(report, exercise, "error-model", "observed-raise-only",
        "raised; boundary re-invocation withheld for a destructive route") && ok;
    } else {
      const after = invoke(exercise.call, args);
      ok = after.thrown === first.thrown
        ? emit(report, exercise, "error-model", "observed", "raised and boundary remained usable") && ok
        : emit(report, exercise, "error-model", "mismatched", "boundary disposition changed after a raised call") && ok;
    }
  } else if (exercise.errorModel) {
    ok = emit(report, exercise, "error-model", "not-applicable", "route has no required argument to withhold") && ok;
  }

  return ok;
}
`;
}

function providerModuleName(profileId) {
  return `providers/${profileId}`;
}

function renderArgument(spec, { ordinalExpression }) {
  if (spec.kind === "literal") return literal(spec.value);
  if (spec.kind === "address") return `address(${ordinalExpression(spec.ordinal)})`;
  return `resolve(${literal(spec.handleKind)}, ${ordinalExpression(spec.ordinal)})`;
}

// One providers module per fixture profile. A provider is the generated
// producer chain for one borrowed handle kind, so a consumer route never needs
// a hand-authored scenario to obtain a live engine object.
function providersModule(profile, providers) {
  const roots = [...new Set(providers.flatMap((provider) => provider.accessor[0]))].sort();
  const addresses = profile.componentAddresses;
  const lines = [
    GENERATED_BANNER,
    `// Handle provenance for fixture profile ${literal(profile.id)}.`,
    roots.length > 0 ? `import { ${roots.join(", ")} } from "@deherm/sdk";` : "",
    'import type { Provider } from "../harness";',
    "",
    `const ADDRESSES: readonly string[] = ${literal([...addresses])};`,
    "",
    "function address(ordinal: number): string {",
    "  return ADDRESSES.length === 0 ? \"\" : (ADDRESSES[ordinal % ADDRESSES.length] as string);",
    "}",
    "",
    "function resolve(handleKind: string, ordinal: number): unknown {",
    "  const provider = providers[handleKind];",
    "  if (provider === undefined) return undefined;",
    "  try {",
    "    const value = provider(ordinal);",
    "    return value === null ? undefined : value;",
    "  } catch {",
    "    return undefined;",
    "  }",
    "}",
    "",
    "export const providers: Readonly<Record<string, Provider>> = {"
  ].filter((line) => line !== "");

  for (const provider of providers) {
    const accessor = provider.accessor.join(".");
    const ordinalExpression = (offset) => (offset === 0 ? "ordinal" : `ordinal + ${offset}`);
    lines.push(`  ${literal(provider.handleKind)}: (ordinal: number): unknown => {`);
    const names = [];
    provider.arguments.forEach((spec, index) => {
      const name = `argument${index}`;
      names.push(name);
      lines.push(`    const ${name}: unknown = ${renderArgument(spec, { ordinalExpression })};`);
      if (spec.kind === "handle") lines.push(`    if (${name} === undefined) return undefined;`);
    });
    lines.push(`    return (${accessor} as unknown as (...args: readonly unknown[]) => unknown)(${names.join(", ")});`);
    lines.push("  },");
  }
  lines.push("};");
  lines.push("");
  return lines.join("\n");
}

function contractModule(contract) {
  const addresses = profileById.get(contract.profile).componentAddresses;
  const roots = [...new Set(contract.exercises.map((exercise) => exercise.accessor[0]))].sort();
  const lines = [
    GENERATED_BANNER,
    `// Contract ${contract.id}: ${contract.routeCount} routes intern to this contract,`,
    `// ${contract.eligibleRouteCount} of which are reachable fixtures; ${contract.exercises.length} are exercised.`,
    `// Fixture profile: ${contract.profile}.`,
    `import { ${roots.join(", ")} } from "@deherm/sdk";`,
    'import { runExercise, type Report } from "../harness";',
    `import { providers } from "../${providerModuleName(contract.profile)}";`,
    "",
    "export function runContract(report: Report): boolean {",
    "  let ok = true;"
  ];
  for (const exercise of contract.exercises) {
    const accessor = exercise.accessor.join(".");
    // An exercise is the root of its own call, so an address ordinal resolves
    // to one of the profile's published addresses at generation time.
    const args = exercise.arguments.map((spec) => spec.kind === "address"
      ? { kind: "literal", value: addresses[spec.ordinal % addresses.length] ?? "" }
      : spec);
    lines.push("  ok = runExercise(report, {");
    lines.push(`    contract: ${literal(contract.id)},`);
    lines.push(`    route: ${literal(exercise.routeId)},`);
    lines.push(`    arity: ${literal(exercise.arity)},`);
    lines.push(`    call: ${accessor} as unknown as (...args: readonly unknown[]) => unknown,`);
    lines.push(`    args: ${literal(args)},`);
    lines.push("    providers,");
    lines.push(`    minimumResultCount: ${exercise.minimumResultCount},`);
    lines.push(`    maximumResultCount: ${exercise.maximumResultCount},`);
    lines.push(`    resultCodec: ${literal(exercise.resultCodec)},`);
    lines.push(`    resultNullable: ${Boolean(exercise.resultNullable)},`);
    lines.push(`    minimumArgumentCount: ${exercise.minimumArgumentCount},`);
    lines.push(`    repeatable: ${!exercise.destructive},`);
    lines.push(`    scratchReuse: ${contract.properties.includes("scratch-reuse")},`);
    lines.push(`    errorModel: ${contract.properties.includes("error-model")}`);
    lines.push("  }) && ok;");
  }
  lines.push("  return ok;");
  lines.push("}");
  lines.push("");
  return lines.join("\n");
}

function registryModule(fixtures) {
  const lines = [GENERATED_BANNER];
  for (const fixture of fixtures) {
    lines.push(`import { runContract as ${fixture.id} } from "./contracts/${fixture.id}";`);
  }
  lines.push('import type { Report } from "./harness";');
  lines.push("");
  lines.push("export const contracts: Readonly<Record<string, (report: Report) => boolean>> = {");
  for (const fixture of fixtures) lines.push(`  ${literal(fixture.id)}: ${fixture.id},`);
  lines.push("};");
  lines.push("");
  return lines.join("\n");
}

function mainModule(plan) {
  return `${GENERATED_BANNER}
import { defineDefoldApp, sys } from "@deherm/sdk";

import { contracts } from "./registry";

const MARKER = "deherm-headless-conformance";
const RUN_TICK = ${CONTRACT_RUN_TICK};
const readCase = sys.getConfigString as unknown as (key: string) => unknown;

defineDefoldApp((host) => {
  const report = (line: string): void => host.log("info", line);
  let selected = "";
  let run: ((report: (line: string) => void) => boolean) | undefined;
  let tick = 0;

  return {
    init() {
      report(\`\${MARKER}:harness:\${${literal(plan.contractCount)}}:\${${literal(plan.reachableContractCount)}}\`);
      selected = String(readCase("deherm_conformance.case") ?? "");
      if (selected === "" || selected === "none") {
        report(\`\${MARKER}:case-unselected\`);
        throw new Error("no headless conformance case was selected");
      }
      run = contracts[selected];
      if (run === undefined) {
        report(\`\${MARKER}:case-unknown:\${selected}\`);
        throw new Error(\`unknown headless conformance case: \${selected}\`);
      }
    },
    // The contract runs from update, not init, so every route is exercised
    // against an engine frame that has already stepped its component worlds.
    update() {
      tick += 1;
      if (tick !== RUN_TICK || run === undefined) return;
      const ok = run(report);
      report(\`\${MARKER}:case-result:\${selected}:\${ok ? "observed" : "mismatched"}\`);
      if (!ok) {
        throw new Error(\`headless conformance contract \${selected} mismatched\`);
      }
    }
  };
});
`;
}

export function harnessFiles(plan) {
  const fixtures = plan.contracts.filter((contract) => contract.disposition === "fixture");
  const typescript = new Map();
  typescript.set("harness.ts", harnessModule());
  typescript.set("registry.ts", registryModule(fixtures));
  typescript.set("main.ts", mainModule(plan));
  for (const profileId of plan.usedProfiles) {
    const profile = profileById.get(profileId);
    const declared = plan.fixtureProfiles.find((item) => item.id === profileId);
    typescript.set(`${providerModuleName(profileId)}.ts`, providersModule(profile, declared.handleProviders));
  }

  const content = new Map();
  content.set("game.project", gameProject(plan));
  content.set("conformance/index.collection", indexCollection());
  content.set("conformance/index.go", indexGameObject(fixtures));
  // Defold requires the configured input binding to exist even with the null
  // HID backend; the harness injects no input, so it is deliberately empty.
  content.set("input/game.input_binding", "");
  const physicsProfiles = plan.usedProfiles.filter((id) => profileById.get(id).components.includes("collisionobject"));
  if (physicsProfiles.length > 0) {
    content.set("conformance/probe.collisionobject", collisionObject());
    content.set(`conformance/${SECOND_PROBE}.go`, secondProbeGameObject());
  }
  for (const fixture of fixtures) {
    content.set(`conformance/${fixture.id}.collection`, collection(fixture));
    content.set(`conformance/${fixture.id}.go`, gameObject(fixture));
    content.set(`conformance/${fixture.id}.script`, contractScript(fixture.id));
    content.set(`conformance/${fixture.id}.collectionproxy`, collectionProxy(fixture.id));
    typescript.set(`contracts/${fixture.id}.ts`, contractModule(fixture));
  }
  return { typescript, content, fixtures };
}

export async function writeHeadlessConformanceHarness(plan) {
  const { typescript, content, fixtures } = harnessFiles(plan);

  const typescriptBase = path.resolve(repoRoot, typescriptDirectory);
  await rm(typescriptBase, { recursive: true, force: true });
  await mkdir(path.join(typescriptBase, "contracts"), { recursive: true });
  await mkdir(path.join(typescriptBase, "providers"), { recursive: true });
  for (const [relative, contents] of typescript) {
    await writeFile(path.join(typescriptBase, relative), contents);
  }

  // Only the generated source folders are replaced. Bob's output directory
  // lives inside the project and must survive so content builds stay
  // incremental across regeneration.
  const projectBase = path.resolve(repoRoot, projectDirectory);
  for (const owned of ["conformance", "input", "deherm"]) {
    await rm(path.join(projectBase, owned), { recursive: true, force: true });
  }
  await mkdir(path.join(projectBase, "conformance"), { recursive: true });
  await mkdir(path.join(projectBase, "input"), { recursive: true });
  await mkdir(path.join(projectBase, "deherm"), { recursive: true });
  for (const [relative, contents] of content) {
    await writeFile(path.join(projectBase, relative), contents);
  }

  return {
    typescriptDirectory: typescriptBase,
    projectDirectory: projectBase,
    entryPoint: path.join(typescriptBase, "main.ts"),
    fileCount: typescript.size + content.size,
    fixtureCount: fixtures.length
  };
}

async function main(argv = process.argv.slice(2)) {
  const unknown = argv.filter((argument) => argument !== "--check");
  if (unknown.length) throw new Error(`Unknown argument: ${unknown[0]}`);
  const check = argv.includes("--check");

  const documents = await loadHeadlessConformanceInputs(root);
  const plan = buildHeadlessConformancePlan(documents);
  const serialized = `${JSON.stringify(plan, null, 2)}\n`;

  if (check) {
    const actual = await readFile(new URL(planPath, root), "utf8");
    if (actual !== serialized) throw new Error(`${planPath} is stale`);
    const { typescript } = harnessFiles(plan);
    for (const [relative, contents] of typescript) {
      const onDisk = await readFile(path.resolve(repoRoot, typescriptDirectory, relative), "utf8");
      if (onDisk !== contents) throw new Error(`${typescriptDirectory}/${relative} is stale`);
    }
    console.log(
      `Verified headless conformance plan: ${plan.reachableContractCount} reachable and ` +
      `${plan.unreachableContractCount} unreachable of ${plan.contractCount} script contracts.`
    );
    return;
  }

  await writeFile(new URL(planPath, root), serialized);
  const written = await writeHeadlessConformanceHarness(plan);
  console.log(
    `Generated headless conformance harness: ${plan.reachableContractCount} reachable and ` +
    `${plan.unreachableContractCount} unreachable of ${plan.contractCount} script contracts, ` +
    `${plan.exercisedRouteCount} exercised routes in ${plan.exerciseCount} exercises, ` +
    `${written.fileCount} project files.`
  );
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) await main();
