// The déherm runtime attaches to a Defold script instance, which is what gives
// the generated TypeScript a game-object context. Every verdict leaves through
// sys.exit so the in-process driver reads it from dmEngineGetResult.
function contractScript(slug) {
  return [
    GENERATED_LUA_BANNER,
    `-- Conformance fixture for ${slug}.`,
    "function init(self)",
    "    self.ticks = 0",
    "    self.ok = pcall(function() assert(_deherm_.attach(self)) end)",
    "end",
    "",
    "function update(self, dt)",
    "    self.ticks = self.ticks + 1",
    "    if self.ok then",
    "        self.ok = pcall(_deherm_.update, self, dt)",
    "    end",
    `    if self.ticks >= ${FIXTURE_EXIT_TICK} then`,
    "        sys.exit(self.ok and 0 or 1)",
    "    end",
    "end",
    "",
    "function final(self)",
    "    pcall(_deherm_.detach, self)",
    "end",
    ""
  ].join("\n");
}

