import assert from "node:assert/strict";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import {
  projectGeneratedModuleFacts,
  renderGeneratedModuleOutputs,
} from "../packages/compiler/src/generated-module-output-emitter.mjs";

const GENERATED_BANNER = "Generated by scripts/generate-bindings.mjs. Do not edit.";
const identifier = /^[A-Za-z_][A-Za-z0-9_]*$/;

const scalarTypes = {
  bool: { ts: "boolean", c: "uint8_t", sh: "c_u8", size: 1, align: 1, heap: "u8" },
  i32: { ts: "number", c: "int32_t", sh: "c_i32", size: 4, align: 4, heap: "i32" },
  u32: { ts: "number", c: "uint32_t", sh: "c_u32", size: 4, align: 4, heap: "u32" },
  f32: { ts: "number", c: "float", sh: "c_f32", size: 4, align: 4, heap: "f32" },
  f64: { ts: "number", c: "double", sh: "c_f64", size: 8, align: 8, heap: "f64" },
  callback: { ts: "(handle: number, elapsed: number) => void", c: null, sh: null, size: 0, align: 1, heap: null },
  void: { ts: "void", c: "void", sh: "void", size: 0, align: 1, heap: null },
};

function fail(path, message) {
  throw new Error(`${path}: ${message}`);
}

function expectIdentifier(value, path) {
  if (typeof value !== "string" || !identifier.test(value)) {
    fail(path, `expected an identifier, received ${JSON.stringify(value)}`);
  }
}

function expectArray(value, path) {
  if (!Array.isArray(value)) fail(path, "expected an array");
}

function expectUnique(items, select, path) {
  const seen = new Set();
  for (const item of items) {
    const value = select(item);
    if (seen.has(value)) fail(path, `duplicate name ${JSON.stringify(value)}`);
    seen.add(value);
  }
}

function alignTo(value, alignment) {
  return Math.ceil(value / alignment) * alignment;
}

function snake(value) {
  return value
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/[^A-Za-z0-9]+/g, "_")
    .toLowerCase();
}

function cSymbol(module, fn) {
  return fn.symbol ?? `defold_hermes_${snake(module.name)}_${snake(fn.name)}`;
}

function symbolId(module, fn) {
  return `${module.name}.${fn.name}`;
}

function generatedFunctionPath(module, fn) {
  return `packages/sdk/src/generated/functions/${module.name}/${fn.name}.ts`;
}

export function validateSchema(schema) {
  if (!schema || typeof schema !== "object" || Array.isArray(schema)) {
    fail("schema", "expected an object");
  }
  if (schema.schemaVersion !== 1) fail("schemaVersion", "only schema version 1 is supported");
  if (schema.abiVersion !== 1) fail("abiVersion", "only ABI version 1 is supported");
  expectArray(schema.types, "types");
  expectArray(schema.modules, "modules");
  expectUnique(schema.types, (type) => type.name, "types");
  expectUnique(schema.modules, (module) => module.name, "modules");

  for (const [typeIndex, type] of schema.types.entries()) {
    const path = `types[${typeIndex}]`;
    if (type.kind !== "struct") fail(`${path}.kind`, "only fixed-layout structs are supported");
    expectIdentifier(type.name, `${path}.name`);
    expectArray(type.fields, `${path}.fields`);
    expectUnique(type.fields, (field) => field.name, `${path}.fields`);
    if (type.fields.length === 0) fail(`${path}.fields`, "structs must contain at least one field");
    for (const [fieldIndex, field] of type.fields.entries()) {
      const fieldPath = `${path}.fields[${fieldIndex}]`;
      expectIdentifier(field.name, `${fieldPath}.name`);
      if (!scalarTypes[field.type] || field.type === "void" || field.type === "callback") {
        fail(`${fieldPath}.type`, `unsupported fixed-layout field type ${JSON.stringify(field.type)}`);
      }
    }
  }

  const typeNames = new Set(schema.types.map((type) => type.name));
  for (const [moduleIndex, module] of schema.modules.entries()) {
    const path = `modules[${moduleIndex}]`;
    expectIdentifier(module.name, `${path}.name`);
    if (module.verification !== undefined) {
      if (module.verification?.kind !== "timer-lifecycle-v1") {
        fail(`${path}.verification.kind`, "unsupported verification scenario");
      }
      for (const field of ["delay", "elapsed"]) {
        if (!Number.isFinite(module.verification[field]) || module.verification[field] < 0) {
          fail(`${path}.verification.${field}`, "expected a non-negative finite number");
        }
      }
      for (const field of ["firstHandle", "secondHandle"]) {
        const value = module.verification[field];
        if (!Number.isInteger(value) || value < 0 || value > 0xffff_ffff) {
          fail(`${path}.verification.${field}`, "expected a u32");
        }
      }
    }
    expectArray(module.functions, `${path}.functions`);
    expectUnique(module.functions, (fn) => fn.name, `${path}.functions`);
    for (const [functionIndex, fn] of module.functions.entries()) {
      const fnPath = `${path}.functions[${functionIndex}]`;
      expectIdentifier(fn.name, `${fnPath}.name`);
      if (fn.symbol !== undefined) expectIdentifier(fn.symbol, `${fnPath}.symbol`);
      if (
        fn.callbackFailureValue !== undefined &&
        (!Number.isSafeInteger(fn.callbackFailureValue) || fn.callbackFailureValue < 0)
      ) {
        fail(`${fnPath}.callbackFailureValue`, "expected a non-negative safe integer");
      }
      expectArray(fn.parameters, `${fnPath}.parameters`);
      expectUnique(fn.parameters, (parameter) => parameter.name, `${fnPath}.parameters`);
      for (const [parameterIndex, parameter] of fn.parameters.entries()) {
        const parameterPath = `${fnPath}.parameters[${parameterIndex}]`;
        expectIdentifier(parameter.name, `${parameterPath}.name`);
        if (!scalarTypes[parameter.type] || parameter.type === "void") {
          if (typeNames.has(parameter.type)) {
            fail(`${parameterPath}.type`, "struct calls require the planned pointer/out-parameter lowering");
          }
          fail(`${parameterPath}.type`, `unsupported parameter type ${JSON.stringify(parameter.type)}`);
        }
      }
      if (!scalarTypes[fn.returns] || fn.returns === "callback") {
        if (typeNames.has(fn.returns)) {
          fail(`${fnPath}.returns`, "struct returns require the planned out-parameter lowering");
        }
        fail(`${fnPath}.returns`, `unsupported return type ${JSON.stringify(fn.returns)}`);
      }
    }
  }
  return schema;
}

export function filterSchemaForUsage(input, manifest) {
  const schema = validateSchema(structuredClone(input));
  if (!manifest || manifest.schemaVersion !== 1 || !Array.isArray(manifest.symbols)) {
    fail("usage", "expected a version 1 usage manifest with a symbols array");
  }
  if (manifest.dynamicAccess === true) return schema;

  const known = new Set(schema.modules.flatMap((module) => module.functions.map((fn) => symbolId(module, fn))));
  const selected = new Set(manifest.symbols.map((symbol) => (typeof symbol === "string" ? symbol : symbol?.id)));
  for (const id of selected) {
    if (typeof id !== "string" || !known.has(id)) fail("usage.symbols", `unknown symbol ${JSON.stringify(id)}`);
  }

  const modules = schema.modules
    .map((module) => ({
      ...module,
      functions: module.functions.filter((fn) => selected.has(symbolId(module, fn))),
    }))
    .filter((module) => module.functions.length > 0);
  const referencedTypes = new Set(
    modules.flatMap((module) =>
      module.functions.flatMap((fn) => [fn.returns, ...fn.parameters.map((parameter) => parameter.type)]),
    ),
  );
  return { ...schema, types: schema.types.filter((type) => referencedTypes.has(type.name)), modules };
}

export function computeLayouts(schema) {
  return schema.types.map((type) => {
    let offset = 0;
    let alignment = 1;
    const fields = type.fields.map((field) => {
      const scalar = scalarTypes[field.type];
      offset = alignTo(offset, scalar.align);
      const layout = { ...field, offset, size: scalar.size, align: scalar.align, heap: scalar.heap };
      offset += scalar.size;
      alignment = Math.max(alignment, scalar.align);
      return layout;
    });
    return { ...type, fields, size: alignTo(offset, alignment), align: alignment };
  });
}

function generateTypeScript(schema, layouts) {
  const lines = [
    `// ${GENERATED_BANNER}`,
    `export const DEFOLD_HERMES_ABI_VERSION = ${schema.abiVersion} as const;`,
    "",
  ];
  for (const type of layouts) {
    if (type.description) lines.push(`/** ${type.description} */`);
    lines.push(`export interface ${type.name} {`);
    for (const field of type.fields) lines.push(`  ${field.name}: ${scalarTypes[field.type].ts};`);
    lines.push("}", "");
  }
  for (const module of schema.modules) {
    if (module.description) lines.push(`/** ${module.description} */`);
    lines.push(`export interface ${module.name}Spec {`);
    for (const fn of module.functions) {
      if (fn.description) lines.push(`  /** ${fn.description} */`);
      const parameters = fn.parameters
        .map((parameter) => `${parameter.name}: ${scalarTypes[parameter.type].ts}`)
        .join(", ");
      lines.push(`  ${fn.name}(${parameters}): ${scalarTypes[fn.returns].ts};`);
    }
    lines.push("}", "");
  }
  lines.push("export interface DefoldModuleMap {");
  for (const module of schema.modules) lines.push(`  ${module.name}: ${module.name}Spec;`);
  lines.push("}", "");
  return `${lines.join("\n").trimEnd()}\n`;
}

function generateFunctionWrapper(module, fn) {
  const parameters = fn.parameters
    .map((parameter) => `${parameter.name}: ${scalarTypes[parameter.type].ts}`)
    .join(", ");
  const argumentsList = fn.parameters.map((parameter) => parameter.name).join(", ");
  return `// ${GENERATED_BANNER}\nimport type { ${module.name}Spec } from "../../modules";\nimport { requireDefoldModule } from "../../../module-runtime";\n\nlet instance: ${module.name}Spec | undefined;\n\n/** Direct, statically discoverable binding for ${symbolId(module, fn)}. */\nexport function ${fn.name}(${parameters}): ${scalarTypes[fn.returns].ts} {\n  instance ??= requireDefoldModule<${module.name}Spec>("${module.name}");\n  return instance.${fn.name}(${argumentsList});\n}\n`;
}

function generateModuleEntry(module) {
  return `${module.functions
    .map((fn) => `export { ${fn.name} } from "../functions/${module.name}/${fn.name}";`)
    .join("\n")}\n`;
}

function generateSymbolMap(schema) {
  return `${JSON.stringify(
    {
      schemaVersion: 1,
      symbols: schema.modules.flatMap((module) =>
        module.functions.map((fn) => ({
          id: symbolId(module, fn),
          module: module.name,
          function: fn.name,
          cSymbol: cSymbol(module, fn),
          source: generatedFunctionPath(module, fn),
        })),
      ),
    },
    null,
    2,
  )}\n`;
}

export function generateArtifacts(input) {
  const schema = validateSchema(structuredClone(input));
  const layouts = computeLayouts(schema);
  const generatedModuleFacts = projectGeneratedModuleFacts(schema);
  const artifacts = new Map([
    [
      "packages/bindings/generated/defold-generated-module-recipe-facts.json",
      `${JSON.stringify(generatedModuleFacts, null, 2)}\n`,
    ],
    ["packages/sdk/src/generated/modules.ts", generateTypeScript(schema, layouts)],
    ["packages/bindings/generated/symbol-map.json", generateSymbolMap(schema)],
  ]);
  for (const [path, contents] of renderGeneratedModuleOutputs(generatedModuleFacts)) {
    artifacts.set(path, contents);
  }
  for (const module of schema.modules) {
    artifacts.set(`packages/sdk/src/generated/modules/${module.name}.ts`, generateModuleEntry(module));
    for (const fn of module.functions) {
      artifacts.set(generatedFunctionPath(module, fn), generateFunctionWrapper(module, fn));
    }
  }
  return artifacts;
}

async function main() {
  const checkOnly = process.argv.includes("--check");
  const quiet = process.argv.includes("--quiet");
  const valueAfter = (flag) => {
    const index = process.argv.indexOf(flag);
    return index < 0 ? undefined : process.argv[index + 1];
  };
  const root = fileURLToPath(new URL("../", import.meta.url));
  const outputRoot = resolve(root, valueAfter("--output-root") ?? ".");
  const schema = JSON.parse(await readFile(resolve(root, "packages/bindings/modules.json"), "utf8"));
  const usagePath = valueAfter("--usage");
  const selectedSchema = usagePath
    ? filterSchemaForUsage(schema, JSON.parse(await readFile(resolve(root, usagePath), "utf8")))
    : schema;
  for (const [path, contents] of generateArtifacts(selectedSchema)) {
    const output = resolve(outputRoot, path);
    if (checkOnly) {
      assert.equal(await readFile(output, "utf8"), contents, `${path} is stale`);
    } else {
      await mkdir(dirname(output), { recursive: true });
      await writeFile(output, contents);
    }
  }
  if (!quiet) {
    const scope = usagePath ? ` for ${usagePath}` : "";
    console.log(`Binding generation ${checkOnly ? "check passed" : "completed"}${scope}`);
  }
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  await main();
}
