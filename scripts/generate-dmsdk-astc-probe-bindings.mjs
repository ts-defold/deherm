import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { semanticDeclarationId, semanticEntryMap } from "./lib/dmsdk-semantic-id.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const defaults = {
  ir: "packages/bindings/generated/defold-sdk-ir.json",
  shapes: "packages/bindings/generated/defold-dmsdk-abi-shapes.json",
  policy: "packages/bindings/overrides/dmsdk-astc-probe-bindings.json",
};

const sha256 = (value) => createHash("sha256").update(value).digest("hex");
const snake = (value) => value
  .replace(/::/g, "_")
  .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
  .toLowerCase();

function parseArgs(argv) {
  const options = { ...defaults, outRoot: root, check: false };

  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === "--check") {
      options.check = true;
    } else if (["--ir", "--shapes", "--policy", "--out-root"].includes(argument)) {
      const key = argument.slice(2).replace(/-([a-z])/g, (_, character) => character.toUpperCase());
      options[key] = resolve(argv[++index]);
    } else {
      throw new Error(`Unknown argument ${argument}`);
    }
  }

  for (const key of ["ir", "shapes", "policy"]) {
    options[key] = resolve(root, options[key]);
  }

  return options;
}

function selectedCandidates(shapes, selector) {
  return shapes.rows
    .filter((row) => row.tranche === "arena-backed-spans"
      && row.header === selector.header
      && row.symbol.startsWith(selector.symbolPrefix)
      && row.shape === selector.shape)
    .sort((left, right) => left.id.localeCompare(right.id));
}

function renderHeader(entries) {
  const declarations = entries
    .map(({ wrapper }) => `uint8_t ${wrapper}(const uint8_t* input, uint32_t input_length, DehermDmSdkAstcProbeResult* out_result);`)
    .join("\n");

  return `// Generated by scripts/generate-dmsdk-astc-probe-bindings.mjs. Do not edit.\n#ifndef DEFOLD_HERMES_GENERATED_DMSDK_ASTC_PROBE_H\n#define DEFOLD_HERMES_GENERATED_DMSDK_ASTC_PROBE_H\n#include <stdint.h>\ntypedef struct DehermDmSdkAstcProbeResult { uint32_t width; uint32_t height; uint32_t depth; } DehermDmSdkAstcProbeResult;\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n${declarations}\n#ifdef __cplusplus\n}\n#endif\n#endif\n`;
}

function renderSource(entries) {
  const wrappers = entries
    .map(({ wrapper, declaration }) => `uint8_t ${wrapper}(const uint8_t* input,uint32_t input_length,DehermDmSdkAstcProbeResult* out_result)\n{\n  if(input==nullptr||out_result==nullptr||input_length<UINT32_C(16))return UINT8_C(0); uint32_t width=0,height=0,depth=0; const bool valid=${declaration.name}(input,input_length,&width,&height,&depth); if(valid){out_result->width=width;out_result->height=height;out_result->depth=depth;} return valid ? UINT8_C(1) : UINT8_C(0);\n}`)
    .join("\n");

  return `// Generated by scripts/generate-dmsdk-astc-probe-bindings.mjs. Do not edit.\n#include <defold_hermes/generated_dmsdk_astc_probe.h>\n#include <dmsdk/dlib/image.h>\nextern \"C\" {\n${wrappers} }\n`;
}

function renderRuntimeHeader() {
  return `// Generated by scripts/generate-dmsdk-astc-probe-bindings.mjs. Do not edit.\n#ifndef DEFOLD_HERMES_GENERATED_DMSDK_ASTC_PROBE_RUNTIME_H\n#define DEFOLD_HERMES_GENERATED_DMSDK_ASTC_PROBE_RUNTIME_H\n#include <defold_hermes/generated_dmsdk_astc_probe.h>\ntypedef enum DehermDmSdkAstcProbeStatus { DEHERM_DMSDK_ASTC_PROBE_OK=0, DEHERM_DMSDK_ASTC_PROBE_UNKNOWN_ID=1, DEHERM_DMSDK_ASTC_PROBE_NULL_STORAGE=2, DEHERM_DMSDK_ASTC_PROBE_INPUT_TOO_SHORT=3, DEHERM_DMSDK_ASTC_PROBE_NOT_ASTC=4 } DehermDmSdkAstcProbeStatus;\ntypedef struct DehermDmSdkAstcProbeDescriptor { uint16_t id; const char* declaration_id; } DehermDmSdkAstcProbeDescriptor;\n#ifdef __cplusplus\nextern \"C\" {\n#endif\nuint32_t deherm_dmsdk_astc_probe_count(void); const DehermDmSdkAstcProbeDescriptor* deherm_dmsdk_astc_probe_descriptors(void); DehermDmSdkAstcProbeStatus deherm_dmsdk_astc_probe_dispatch(uint16_t id,const uint8_t* input,uint32_t input_length,DehermDmSdkAstcProbeResult* out_result);\n#ifdef __cplusplus\n}\n#endif\n#endif\n`;
}

function renderRuntime(entries) {
  const descriptors = entries
    .map(({ id, declaration }) => `  { UINT16_C(${id}), ${JSON.stringify(declaration.id)} }`)
    .join(",\n");
  const cases = entries
    .map(({ id, wrapper }) => `case ${id}: valid=${wrapper}(input,input_length,out_result);break;`)
    .join("\n    ");

  return `// Generated by scripts/generate-dmsdk-astc-probe-bindings.mjs. Do not edit.\n#include <defold_hermes/generated_dmsdk_astc_probe.h>\n#include <defold_hermes/generated_dmsdk_astc_probe_runtime.h>\nnamespace { const DehermDmSdkAstcProbeDescriptor kDescriptors[]={\n${descriptors}\n}; }\nextern \"C\" { uint32_t deherm_dmsdk_astc_probe_count(void){return UINT32_C(${entries.length});} const DehermDmSdkAstcProbeDescriptor* deherm_dmsdk_astc_probe_descriptors(void){return kDescriptors;} DehermDmSdkAstcProbeStatus deherm_dmsdk_astc_probe_dispatch(uint16_t id,const uint8_t* input,uint32_t input_length,DehermDmSdkAstcProbeResult* out_result){if(id>=deherm_dmsdk_astc_probe_count())return DEHERM_DMSDK_ASTC_PROBE_UNKNOWN_ID;if(out_result==nullptr||(input_length&&input==nullptr))return DEHERM_DMSDK_ASTC_PROBE_NULL_STORAGE;out_result->width=out_result->height=out_result->depth=0;if(input_length<UINT32_C(16))return DEHERM_DMSDK_ASTC_PROBE_INPUT_TOO_SHORT;uint8_t valid=0;switch(id){${cases}default:return DEHERM_DMSDK_ASTC_PROBE_UNKNOWN_ID;}return valid?DEHERM_DMSDK_ASTC_PROBE_OK:DEHERM_DMSDK_ASTC_PROBE_NOT_ASTC;} }\n`;
}

async function build(options) {
  const contents = Object.fromEntries(await Promise.all(
    Object.keys(defaults).map(async (key) => [key, await readFile(options[key], "utf8")]),
  ));
  const ir = JSON.parse(contents.ir);
  const shapes = JSON.parse(contents.shapes);
  const policy = JSON.parse(contents.policy);

  if (ir.defoldRevision !== shapes.defoldRevision) {
    throw new Error("Defold revisions differ between IR and ABI-shape census");
  }
  if (sha256(contents.ir) !== shapes.sourceHashes.ir) {
    throw new Error("IR hash does not match ABI-shape census provenance");
  }

  const declarationsById = new Map(ir.declarations.map((declaration) => [declaration.id, declaration]));
  const candidates = selectedCandidates(shapes, policy.candidateSelector);
  const policiesBySemanticId = semanticEntryMap(policy.entries, "astc-probe policy");

  const evidenceHeaders = new Map();
  const entries = [];
  const blocked = [];
  for (const candidate of candidates) {
    const declaration = declarationsById.get(candidate.id);
    if (!declaration) throw new Error(`ASTC-probe candidate is absent from dmSDK IR: ${candidate.id}`);
    const policyEntry = policiesBySemanticId.get(semanticDeclarationId(candidate.id));
    if (!policyEntry) {
      blocked.push({ ...candidate, emitted: false, blocker: "unreviewed-astc-probe-optimization" });
      continue;
    }
    if (policyEntry.status !== "emit"
      || !["block-size", "dimensions"].includes(policyEntry.mode)
      || !Array.isArray(policyEntry.evidence)) {
      throw new Error(`Invalid astc-probe policy for ${candidate.id}`);
    }

    for (const evidence of policyEntry.evidence) {
      let header = evidenceHeaders.get(evidence.header);
      if (!header) {
        header = await readFile(resolve(root, evidence.header), "utf8");
        evidenceHeaders.set(evidence.header, header);
      }
      const hint = evidence.header === declaration.header ? declaration.line : evidence.line;
      const matches = header.split("\n")
        .map((line, index) => line.trim() === evidence.text.trim() ? index + 1 : 0)
        .filter(Boolean)
        .sort((left, right) => Math.abs(left - hint) - Math.abs(right - hint));
      if (matches.length === 0) {
        blocked.push({ ...candidate, emitted: false, blocker: "astc-probe-evidence-withdrawn" });
        break;
      }
      evidence.line = matches[0];
    }

    if (blocked.at(-1)?.id === candidate.id) continue;

    if (!policyEntry.evidence.some(({ text }) => text.includes("memsize"))
      || !policyEntry.evidence.some(({ text }) => text.includes("memsize < 16"))) {
      throw new Error(`Astc-probe policy lacks bounded-input evidence for ${candidate.id}`);
    }

    entries.push({
      id: entries.length,
      candidate,
      declaration,
      mode: policyEntry.mode,
      evidence: policyEntry.evidence,
      wrapper: `deherm_dmsdk_astc_probe_${snake(declaration.name)}`,
    });
  }

  const artifacts = new Map([
    ["defold/defold_hermes/include/defold_hermes/generated_dmsdk_astc_probe.h", renderHeader(entries)],
    ["defold/defold_hermes/include/defold_hermes/generated_dmsdk_astc_probe_runtime.h", renderRuntimeHeader()],
    ["defold/defold_hermes/src/generated_dmsdk_astc_probe_image.cpp", renderSource(entries)],
    ["defold/defold_hermes/src/generated_dmsdk_astc_probe_runtime.cpp", renderRuntime(entries)],
  ]);
  const report = {
    schemaVersion: 1,
    policyVersion: policy.policyVersion,
    defoldRevision: ir.defoldRevision,
    sources: defaults,
    sourceHashes: {
      ...Object.fromEntries(Object.entries(contents).map(([key, value]) => [key, sha256(value)])),
      headers: Object.fromEntries([...evidenceHeaders].map(([key, value]) => [key, sha256(value)])),
    },
    policy: {
      candidateSelector: policy.candidateSelector,
      cAbi: "bounded uint8_t input span and caller-owned fixed three-u32 result",
      ownership: "input is synchronously borrowed; only scalar results return",
      safety: "generated preflight rejects null input and spans shorter than the pinned native 16-byte ASTC header minimum",
      allocation: "no generated or pinned image parser allocation",
      jsi: "not-generated pending typed-array lifetime and installer policy",
      html5: "not-claimed pending target compile/link matrix",
    },
    coverage: {
      baselineRuntimePending: shapes.coverage.runtimePending,
      discovered: candidates.length,
      emitted: entries.length,
      policyBlocked: blocked.length,
      hostBehaviorVerified: entries.length,
      remainingWithoutGeneratedAdapters: shapes.coverage.runtimePending - 26 - 7 - 4 - 2 - entries.length,
    },
    artifactHashes: Object.fromEntries([...artifacts].map(([key, value]) => [key, sha256(value)])),
    artifacts: [...artifacts.keys()].sort(),
    declarations: [...entries.map((entry) => ({
      ...entry.candidate,
      bindingId: entry.id,
      mode: entry.mode,
      evidence: entry.evidence,
      wrapper: entry.wrapper,
      stages: {
        generated: "complete",
        compiled: "pinned-source-object-test",
        linked: "pinned-source-host-link-test",
        runtime: "pinned-source-host-behavior-test",
        allocation: "100000-warmed-dispatch-zero-cpp-allocations",
      },
    })), ...blocked],
  };

  artifacts.set(
    "packages/bindings/generated/defold-dmsdk-astc-probe-bindings.json",
    `${JSON.stringify(report, null, 2)}\n`,
  );
  return { artifacts, report };
}

async function writeOrCheck(options, relativePath, content) {
  const path = resolve(options.outRoot, relativePath);
  if (options.check) {
    if (await readFile(path, "utf8") !== content) {
      throw new Error(`${relativePath} is stale`);
    }
  } else {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, content);
  }
}

export async function run(argv = process.argv.slice(2)) {
  const options = parseArgs(argv);
  const { artifacts, report } = await build(options);
  for (const [relativePath, content] of artifacts) {
    await writeOrCheck(options, relativePath, content);
  }
  process.stdout.write(`${options.check ? "Verified" : "Generated"} ${report.coverage.emitted}/${report.coverage.discovered} astc-probe dmSDK bindings.\n`);
  return report;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  await run();
}
