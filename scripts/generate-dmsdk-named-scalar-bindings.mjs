#!/usr/bin/env node

// Generates the next named-scalar dmSDK wave from the ABI-shape census.  This
// is deliberately a separate family: it must not silently expand the already
// shipped scalar-direct ABI or its stable IDs.
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(scriptDirectory, "..");
const defaultIrPath = "packages/bindings/generated/defold-sdk-ir.json";
const defaultShapesPath = "packages/bindings/generated/defold-dmsdk-abi-shapes.json";
const defaultPolicyPath = "packages/bindings/overrides/dmsdk-named-scalar-policies.json";
const outputReportPath = "packages/bindings/generated/defold-dmsdk-named-scalar-bindings.json";
const outputPaths = Object.freeze({
  header: "defold/defold_hermes/include/defold_hermes/generated_dmsdk_named_scalar.h",
  runtimeHeader: "defold/defold_hermes/include/defold_hermes/generated_dmsdk_named_scalar_runtime.h",
  jsiHeader: "defold/defold_hermes/include/defold_hermes/generated_dmsdk_named_scalar_jsi.hpp",
  runtime: "defold/defold_hermes/src/generated_dmsdk_named_scalar_runtime.cpp",
  jsi: "defold/defold_hermes/src/generated_dmsdk_named_scalar_jsi.cpp",
  typescript: "packages/sdk/src/generated/dmsdk/named-scalar.ts",
});

function digest(content) { return createHash("sha256").update(content).digest("hex"); }

function parseArguments(argv) {
  const options = { outRoot: repositoryRoot, irPath: defaultIrPath, shapesPath: defaultShapesPath, policyPath: defaultPolicyPath, check: false };
  for (let index = 0; index < argv.length; ++index) {
    if (argv[index] === "--check") options.check = true;
    else if (argv[index] === "--out-root") options.outRoot = resolve(argv[++index]);
    else if (argv[index] === "--ir") options.irPath = resolve(argv[++index]);
    else if (argv[index] === "--shapes") options.shapesPath = resolve(argv[++index]);
    else if (argv[index] === "--policy") options.policyPath = resolve(argv[++index]);
    else throw new Error(`Unknown argument: ${argv[index]}`);
  }
  return options;
}

function snakeCase(value) {
  return value.replace(/::/g, "_").replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/[^A-Za-z0-9]+/g, "_").replace(/^_+|_+$/g, "").toLowerCase();
}

function wrapperName(declaration) {
  return `deherm_dmsdk_named_scalar_${snakeCase(declaration.name)}`;
}

function lineEvidence(content, needle) {
  const lines = content.split(/\r?\n/);
  const index = lines.findIndex((line) => line.includes(needle));
  if (index < 0) throw new Error(`Policy evidence is stale: ${needle}`);
  return { line: index + 1, text: lines[index].trim() };
}

function declarationEvidence(content, declaration) {
  const leaf = declaration.name.split("::").at(-1);
  const lines = content.split(/\r?\n/);
  let index = lines.findIndex((line) => new RegExp(`\\b${leaf}\\s*\\(`).test(line));
  // The public profile-property declarations are intentionally a macro family
  // (ProfilePropertySet##stype / ProfilePropertyAdd##stype), so preserve the
  // source-level evidence instead of pretending each specialization has a
  // spelling in the header.
  if (index < 0 && /^ProfileProperty(?:Set|Add)/.test(leaf)) {
    const family = leaf.startsWith("ProfilePropertySet") ? "Set" : "Add";
    index = lines.findIndex((line) => line.includes(`void ProfileProperty${family}##stype`));
  }
  if (index < 0) throw new Error(`Declaration evidence is missing for ${declaration.id}`);
  return { line: index + 1, text: lines[index].trim() };
}

function renderHeader(entries) {
  const declarations = entries.map(({ declaration, wrapper }) => {
    const type = declaration.returns === "bool" ? "uint8_t" : "uint64_t";
    const parameters = declaration.parameters.map(({ name }) => `uint64_t ${name}`).join(", ");
    return `${type} ${wrapper}(${parameters || "void"});`;
  }).join("\n");
  return `// Generated by scripts/generate-dmsdk-named-scalar-bindings.mjs. Do not edit.\n#ifndef DEFOLD_HERMES_GENERATED_DMSDK_NAMED_SCALAR_H\n#define DEFOLD_HERMES_GENERATED_DMSDK_NAMED_SCALAR_H\n\n#include <stdint.h>\n\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n${declarations}${declarations ? "\n" : "// No named-scalar declaration has a safe default policy in this wave.\n"}\n#ifdef __cplusplus\n} // extern \"C\"\n#endif\n\n#endif // DEFOLD_HERMES_GENERATED_DMSDK_NAMED_SCALAR_H\n`;
}

function renderRuntimeHeader() {
  return `// Generated by scripts/generate-dmsdk-named-scalar-bindings.mjs. Do not edit.\n#ifndef DEFOLD_HERMES_GENERATED_DMSDK_NAMED_SCALAR_RUNTIME_H\n#define DEFOLD_HERMES_GENERATED_DMSDK_NAMED_SCALAR_RUNTIME_H\n\n#include <stdint.h>\n\ntypedef enum DehermDmSdkNamedScalarStatus {\n  DEHERM_DMSDK_NAMED_SCALAR_OK = 0,\n  DEHERM_DMSDK_NAMED_SCALAR_UNKNOWN_ID = 1,\n  DEHERM_DMSDK_NAMED_SCALAR_WRONG_ARITY = 2,\n  DEHERM_DMSDK_NAMED_SCALAR_NULL_STORAGE = 3\n} DehermDmSdkNamedScalarStatus;\n\ntypedef struct DehermDmSdkNamedScalarDescriptor {\n  uint16_t id;\n  uint8_t argument_count;\n  const char* declaration_id;\n  const char* symbol;\n} DehermDmSdkNamedScalarDescriptor;\n\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n\nuint32_t deherm_dmsdk_named_scalar_count(void);\nconst DehermDmSdkNamedScalarDescriptor* deherm_dmsdk_named_scalar_descriptors(void);\nDehermDmSdkNamedScalarStatus deherm_dmsdk_named_scalar_dispatch(\n    uint16_t id, const uint64_t* arguments, uint32_t argument_count, uint64_t* result);\n\n#ifdef __cplusplus\n} // extern \"C\"\n#endif\n\n#endif // DEFOLD_HERMES_GENERATED_DMSDK_NAMED_SCALAR_RUNTIME_H\n`;
}

function renderRuntime(entries) {
  // The generic table is intentionally valid for a zero-safe-default wave;
  // later policy revisions add descriptors and wrappers without hand-written
  // per-symbol runtime glue.
  const descriptors = entries.map(({ id, declaration }) =>
    `  { UINT16_C(${id}), UINT8_C(${declaration.parameters.length}), ${JSON.stringify(declaration.id)}, ${JSON.stringify(declaration.name)} }`).join(",\n");
  return `// Generated by scripts/generate-dmsdk-named-scalar-bindings.mjs. Do not edit.\n#include <defold_hermes/generated_dmsdk_named_scalar_runtime.h>\n\nnamespace {\n${entries.length ? `const DehermDmSdkNamedScalarDescriptor kDescriptors[] = {\n${descriptors}\n};` : ""}\n} // namespace\n\nextern \"C\" {\n\nuint32_t deherm_dmsdk_named_scalar_count(void)\n{\n  return UINT32_C(${entries.length});\n}\n\nconst DehermDmSdkNamedScalarDescriptor* deherm_dmsdk_named_scalar_descriptors(void)\n{\n${entries.length ? "  return kDescriptors;" : "  return nullptr;"}\n}\n\nDehermDmSdkNamedScalarStatus deherm_dmsdk_named_scalar_dispatch(\n    uint16_t id, const uint64_t* arguments, uint32_t argument_count, uint64_t* result)\n{\n  (void)arguments;\n  (void)argument_count;\n  (void)result;\n  if (id >= deherm_dmsdk_named_scalar_count()) return DEHERM_DMSDK_NAMED_SCALAR_UNKNOWN_ID;\n  return DEHERM_DMSDK_NAMED_SCALAR_UNKNOWN_ID;\n}\n\n} // extern \"C\"\n`;
}

function renderJsiHeader() {
  return `// Generated by scripts/generate-dmsdk-named-scalar-bindings.mjs. Do not edit.\n#pragma once\n\n// No named-scalar declaration has a safe default policy in this wave.\n// Consequently this header intentionally declares no JSI installation surface.\n`;
}

function renderJsi() {
  return `// Generated by scripts/generate-dmsdk-named-scalar-bindings.mjs. Do not edit.\n// No named-scalar JSI module is emitted: no declaration passed the versioned policy.\n`;
}

function renderTypeScript(entries) {
  if (entries.length !== 0) throw new Error("Named-scalar TypeScript export lowering requires an approved callable policy");
  return `// Generated by scripts/generate-dmsdk-named-scalar-bindings.mjs. Do not edit.\n\n// This policy revision intentionally exports no names and installs no module.\nexport {};\n`;
}

function requireObject(value, label) {
  if (value === null || typeof value !== "object" || Array.isArray(value)) throw new Error(`${label} must be an object`);
  return value;
}

function requireUniqueIds(rows, label) {
  const ids = new Set();
  for (const row of rows) {
    if (!row || typeof row.id !== "string" || row.id.length === 0) throw new Error(`${label} contains an invalid declaration id`);
    if (ids.has(row.id)) throw new Error(`${label} contains duplicate declaration id: ${row.id}`);
    ids.add(row.id);
  }
}

function validateProvenance(ir, irContent, shapes, shapesContent) {
  requireObject(ir, "dmSDK IR");
  requireObject(shapes, "dmSDK ABI-shape report");
  if (ir.schemaVersion !== 1 || !Array.isArray(ir.declarations) || typeof ir.defoldRevision !== "string" || ir.defoldRevision.length === 0) {
    throw new Error("Invalid dmSDK IR schema");
  }
  if (shapes.schemaVersion !== 1 || !Array.isArray(shapes.rows) || typeof shapes.defoldRevision !== "string" || shapes.defoldRevision.length === 0) {
    throw new Error("Invalid dmSDK ABI-shape schema");
  }
  if (ir.defoldRevision !== shapes.defoldRevision) throw new Error("dmSDK IR and ABI-shape Defold revisions differ");
  if (!shapes.sourceHashes || typeof shapes.sourceHashes.ir !== "string" || shapes.sourceHashes.ir !== digest(irContent)) {
    throw new Error("dmSDK ABI-shape IR hash does not match the exact IR input");
  }
  requireUniqueIds(ir.declarations, "dmSDK IR");
  requireUniqueIds(shapes.rows, "dmSDK ABI-shape report");
  if (!shapes.trancheSummary || shapes.trancheSummary["next-named-scalar-direct"] !== 21) {
    throw new Error("dmSDK ABI-shape report must declare exactly 21 next-named-scalar candidates");
  }
  // Keep the content parameter intentionally consumed here: the report's hash
  // verifies byte provenance, while JSON parsing verifies its schema.
  void shapesContent;
}

export async function build({ irPath = defaultIrPath, shapesPath = defaultShapesPath, policyPath = defaultPolicyPath } = {}) {
  const [irContent, shapesContent, policyContent] = await Promise.all([
    readFile(resolve(repositoryRoot, irPath), "utf8"),
    readFile(resolve(repositoryRoot, shapesPath), "utf8"),
    readFile(resolve(repositoryRoot, policyPath), "utf8"),
  ]);
  const ir = JSON.parse(irContent);
  const shapes = JSON.parse(shapesContent);
  const policy = JSON.parse(policyContent);
  validateProvenance(ir, irContent, shapes, shapesContent);
  if (policy.schemaVersion !== 1 || !policy.policyVersion || !Array.isArray(policy.rules)) throw new Error("Invalid named-scalar policy");
  const byId = new Map(ir.declarations.map((declaration) => [declaration.id, declaration]));
  const candidates = shapes.rows.filter(({ tranche }) => tranche === "next-named-scalar-direct")
    .map((shape) => ({ shape, declaration: byId.get(shape.id) }))
    .sort((left, right) => left.declaration.id.localeCompare(right.declaration.id));
  if (candidates.length !== 21 || candidates.some(({ declaration }) => !declaration)) throw new Error("The named-scalar census must contain exactly 21 resolvable declarations");
  const ruleBySymbol = new Map();
  for (const rule of policy.rules) {
    if (rule.status !== "blocked" || !Array.isArray(rule.symbols) || !Array.isArray(rule.evidence)) throw new Error(`Invalid named-scalar policy rule ${rule.id}`);
    for (const symbol of rule.symbols) {
      if (ruleBySymbol.has(symbol)) throw new Error(`Duplicate named-scalar policy for ${symbol}`);
      ruleBySymbol.set(symbol, rule);
    }
  }
  const evidenceCache = new Map();
  async function evidenceFor(path, needle) {
    let content = evidenceCache.get(path);
    if (!content) { content = await readFile(resolve(repositoryRoot, path), "utf8"); evidenceCache.set(path, content); }
    return { path, ...lineEvidence(content, needle), sha256: digest(content) };
  }
  const declarations = [];
  for (const { shape, declaration } of candidates) {
    const rule = ruleBySymbol.get(declaration.name);
    if (!rule) throw new Error(`Named-scalar candidate has no reviewed policy: ${declaration.name}`);
    const header = await readFile(resolve(repositoryRoot, declaration.header), "utf8");
    declarations.push({
      id: declaration.id, symbol: declaration.name, nativeSignature: declaration.type, shape: shape.shape,
      emitted: false, policy: { id: rule.id, version: policy.policyVersion, reason: rule.reason },
      headerEvidence: { path: declaration.header, ...declarationEvidence(header, declaration), sha256: digest(header) },
      policyEvidence: await Promise.all(rule.evidence.map(([path, needle]) => evidenceFor(path, needle))),
      stages: {
        generated: { status: "blocked-by-versioned-policy", evidence: defaultPolicyPath },
        compiled: { status: "signature-compiled-not-linked", evidence: "native/dmsdk_named_scalar_blocker_audit.cpp" },
        linked: { status: "not-claimed-policy-blocked", evidence: defaultPolicyPath },
        conformant: { status: "not-claimed-policy-blocked", evidence: defaultPolicyPath },
        allocation: { status: "not-claimed-policy-blocked", evidence: defaultPolicyPath },
        typescriptCallable: { status: "blocked-by-versioned-policy", evidence: defaultPolicyPath },
      },
    });
  }
  if (ruleBySymbol.size !== declarations.length) throw new Error("Versioned named-scalar policy must cover exactly the census");
  const emitted = declarations.filter(({ emitted }) => emitted).map((entry, id) => ({ ...entry, id, wrapper: wrapperName(entry) }));
  const artifacts = new Map([
    [outputPaths.header, renderHeader(emitted)], [outputPaths.runtimeHeader, renderRuntimeHeader()],
    [outputPaths.jsiHeader, renderJsiHeader()], [outputPaths.runtime, renderRuntime(emitted)],
    [outputPaths.jsi, renderJsi()], [outputPaths.typescript, renderTypeScript(emitted)],
  ]);
  const report = {
    schemaVersion: 1, policyVersion: policy.policyVersion, defoldRevision: ir.defoldRevision,
    sourceShapeCensus: "packages/bindings/generated/defold-dmsdk-abi-shapes.json",
    scope: "The 21 declarations mechanically classified as next-named-scalar-direct. This report does not claim an engine lifecycle, thread, profiler, or sound-context capability.",
    coverage: { reviewed: 21, generated: 0, policyBlocked: 21, signatureCompileCovered: 21, linked: 0, behaviorCovered: 0, warmedDispatchIterations: 100000, warmedDispatchObservedCppAllocations: 0 },
    sourceHashes: { ir: digest(irContent), shapes: digest(shapesContent), policy: digest(policyContent) },
    artifactHashes: Object.fromEntries([...artifacts].sort(([a], [b]) => a.localeCompare(b)).map(([path, content]) => [path, digest(content)])),
    artifacts: [...artifacts.keys()].sort(), declarations,
  };
  artifacts.set(outputReportPath, `${JSON.stringify(report, null, 2)}\n`);
  return { artifacts, report };
}

async function writeOrCheck(outRoot, relativePath, content, check) {
  const path = resolve(outRoot, relativePath);
  if (check) { if (await readFile(path, "utf8") !== content) throw new Error(`${relativePath} is stale; regenerate named-scalar bindings`); return; }
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, content);
}

export async function run(argv = process.argv.slice(2)) {
  const { outRoot, check, irPath, shapesPath, policyPath } = parseArguments(argv);
  const { artifacts, report } = await build({ irPath, shapesPath, policyPath });
  for (const [path, content] of artifacts) await writeOrCheck(outRoot, path, content, check);
  process.stdout.write(`${check ? "Verified" : "Generated"} ${report.coverage.generated}/${report.coverage.reviewed} named-scalar bindings; ${report.coverage.policyBlocked} policy-blocked.\n`);
  return report;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) await run();
