#!/usr/bin/env node

// Project Defold's own Extender link recipe into the in-process conformance
// driver. This is harness configuration, never a shipped binding or policy.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import YAML from "yaml";

const harnessSubstitutions = new Map([
  ["engine_service", "engine_service_null"],
  ["profile", "profile_null"],
  ["profilerext", "profilerext_null"],
]);
const harnessOmissions = new Set(["profiler_remotery", "glfw3", "dmglfw", "MoltenVK"]);
const harnessSymbolOmissions = new Set(["ProfilerBasic", "ProfilerRemotery"]);
const name = /^[A-Za-z_][A-Za-z0-9_]*$/u;
const libraryName = /^[A-Za-z0-9_.+-]+$/u;

function names(values, label, pattern) {
  if (!Array.isArray(values) || values.some((value) => typeof value !== "string" || !pattern.test(value))) {
    throw new Error(`${label}: expected a list of literal names`);
  }
  return values;
}

function unique(values) {
  return [...new Set(values)];
}

function headlessLibrary(value) {
  if (value === "graphics" || /^graphics_(?!transcoder_|null$)/u.test(value)) return "graphics_null";
  if (value === "platform" || /^platform_(?!null$)/u.test(value)) return "platform_null";
  return harnessSubstitutions.get(value) ?? value;
}

export function deriveHeadlessSdkLinkPlan(build, variant, platform) {
  if (!["linux", "osx"].includes(platform)) throw new Error(`unsupported headless platform ${platform}`);
  const engine = build?.platforms?.[platform]?.context;
  const headless = variant?.platforms?.[platform]?.context;
  const common = variant?.platforms?.common?.context;
  if (!engine || !headless || !common) throw new Error(`${platform}: missing SDK Extender/headless context`);
  const excludedLibraries = new Set(names(headless.excludeLibs, "excludeLibs", libraryName));
  const libraries = unique([
    ...names(engine.engineLibs, "engineLibs", libraryName)
      .filter((value) => !excludedLibraries.has(value) && !harnessOmissions.has(value))
      .map(headlessLibrary),
    ...names(common.libs, "headless common libs", libraryName),
  ]);
  const excludedSymbols = new Set(names(headless.excludeSymbols, "excludeSymbols", name));
  const symbols = unique(
    [
      ...names(build.context?.symbols, "common symbols", name),
      ...names(engine.symbols, "platform symbols", name),
      ...names(headless.symbols, "headless symbols", name),
    ].filter((value) => !excludedSymbols.has(value) && !harnessSymbolOmissions.has(value)),
  );
  if (!libraries.includes("engine") || !symbols.length) throw new Error(`${platform}: incomplete SDK link recipe`);
  return { libraries, symbols };
}

export function renderHeadlessSdkLink(plan) {
  return {
    cmake: `# Generated by scripts/generate-headless-sdk-link.mjs. Do not edit.\nset(DEHERM_HEADLESS_ENGINE_LIBS\n${plan.libraries.map((value) => `  ${value}`).join("\n")}\n)\n`,
    cpp: `// Generated by scripts/generate-headless-sdk-link.mjs. Do not edit.\nextern "C" {\n${[...plan.symbols, "defold_hermes"].map((value) => `void ${value}();`).join("\n")}\nvoid dmExportedSymbols() {\n${[...plan.symbols, "defold_hermes"].map((value) => `  ${value}();`).join("\n")}\n}\n}\n`,
  };
}

async function writeIfChanged(file, value) {
  const current = await readFile(file, "utf8").catch((error) => {
    if (error.code === "ENOENT") return null;
    throw error;
  });
  if (current !== value) await writeFile(file, value);
}

async function main(args) {
  if (args.length !== 4) {
    throw new Error("Usage: generate-headless-sdk-link <defoldsdk> <linux|osx> <output.cmake> <output.cpp>");
  }
  const [sdk, platform, cmakePath, cppPath] = args;
  const build = YAML.parse(await readFile(path.join(sdk, "extender/build.yml"), "utf8"));
  const variant = YAML.parse(await readFile(path.join(sdk, "extender/variants/headless.appmanifest"), "utf8"));
  const output = renderHeadlessSdkLink(deriveHeadlessSdkLinkPlan(build, variant, platform));
  await Promise.all([writeIfChanged(cmakePath, output.cmake), writeIfChanged(cppPath, output.cpp)]);
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) await main(process.argv.slice(2));
