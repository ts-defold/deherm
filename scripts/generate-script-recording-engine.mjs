function renderTables(model, native, shapeRefs) {
  const text = native.entries.map((value) => `  ${cString(value)}`).join(",\n");
  const shapes = model.shapes.map((shape, order) =>
    `  {${shape.code}, ${shape.aux}, ${shape.children.length}, ${shapeRefs.childFirst[order]}, ${native.shapeKeys[order]}}`)
    .join(",\n");
  const refs = shapeRefs.values.length
    ? shapeRefs.values.map((value) => `  ${value}u`).join(",\n")
    : "  0u";
  const routes = model.routes.map((route, order) => {
    const entry = native.routes[order];
    const status = transportOrder.map((transport) =>
      route.transports[transport].status === "skip" ? 1 : 0).join(", ");
    return `  {${route.stableId}u, ${entry.canonical}, ${entry.context}, ${route.contract}, ` +
      `${route.argumentShapes.length}, ${route.resultShapes.length}, ` +
      `${shapeRefs.argumentFirst[order]}, ${shapeRefs.resultFirst[order]}, ` +
      `{${status}}, {${entry.reasons.join(", ")}}, ` +
      `${route.luaAdapter.status === "skip" ? 1 : 0}, ${entry.luaAdapterReason}, ` +
      `${route.luaAdapter.handleCodec === "lua-userdata" ? 1 : route.luaAdapter.handleCodec === "gui-node" ? 2 : 0}, ` +
      `${route.luaAdapter.resultHandleCodec === "lua-userdata" ? 1 : route.luaAdapter.resultHandleCodec === "gui-node" ? 2 : route.luaAdapter.resultHandleCodec === "semantic" ? 3 : 0}, ` +
      `${route.luaAdapter.argumentCount ?? route.arity.minimum}}`;
  }).join(",\n");
  const routeIndex = new Map(model.routes.map((route, order) => [route.id, order]));
  const order = model.order.map((id) => `  ${routeIndex.get(id)}u`).join(",\n");
  const semantic = model.semanticHandleKindNames.map((name) => `  ${cString(name)}`).join(",\n");
  const transports = transportOrder.map((transport) => `  ${cString(transport)}`).join(",\n");
  const seeds = model.handleSeeds.map((seed) =>
    `  {${seed.stableId}u, ${seed.shapeCode}, ${seed.semantic}}`).join(",\n");
  return `${banner}
#include "generated_script_recording_engine.h"

extern "C" {

const char* const kDehermRecordingText[DEHERM_RECORDING_TEXT_COUNT] = {
${text}
};

const DehermRecordingShape kDehermRecordingShapes[DEHERM_RECORDING_SHAPE_COUNT] = {
${shapes}
};

const uint32_t kDehermRecordingShapeRefs[DEHERM_RECORDING_SHAPE_REF_COUNT] = {
${refs}
};

const DehermRecordingRoute kDehermRecordingRoutes[DEHERM_RECORDING_ROUTE_COUNT] = {
${routes}
};

const uint32_t kDehermRecordingOrder[DEHERM_RECORDING_ROUTE_COUNT] = {
${order}
};

const char* const kDehermRecordingSemanticHandleNames[DEHERM_RECORDING_SEMANTIC_HANDLE_COUNT] = {
${semantic}
};

const char* const kDehermRecordingTransportNames[DEHERM_RECORDING_TRANSPORT_COUNT] = {
${transports}
};

const DehermRecordingHandleSeed kDehermRecordingHandleSeeds[DEHERM_RECORDING_HANDLE_SEED_STORAGE_COUNT] = {
${seeds || "  {0u, 0u, 0u}"}
};

}  // extern "C"
`;
}

