function assert(condition, message) {
  if (!condition) throw new Error(message);
}

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function parseArguments(argv) {
  const options = { check: false };
  for (let index = 0; index < argv.length; ++index) {
    const argument = argv[index];
    if (argument === "--check") options.check = true;
    else if (argument === "--output-root") options.outputRoot = path.resolve(argv[++index]);
    else if (argument === "--source-root") options.sourceRoot = path.resolve(argv[++index]);
    else throw new Error(`Unknown argument: ${argument}`);
  }
  return options;
}

async function readInputs(sourceRoot) {
  const read = async (key) => readFile(path.join(sourceRoot, relativePaths[key]), "utf8");
  const [projectionText, universalText, handleLoweringText, tableRecordsText, valueBindingsText, overloadDispatchText, loweringPlanText] = await Promise.all([
    read("projection"), read("universal"), read("handleLowering"), read("tableRecords"), read("valueBindings"), read("overloadDispatch"), read("loweringPlan")
  ]);
  return {
    projection: JSON.parse(projectionText),
    universal: JSON.parse(universalText),
    handleLowering: JSON.parse(handleLoweringText),
    tableRecords: JSON.parse(tableRecordsText),
    valueBindings: JSON.parse(valueBindingsText),
    overloadDispatch: JSON.parse(overloadDispatchText),
    loweringPlan: JSON.parse(loweringPlanText),
    inputHashes: {
      projection: sha256(projectionText),
      universal: sha256(universalText),
      handleLowering: sha256(handleLoweringText),
      tableRecords: sha256(tableRecordsText),
      valueBindings: sha256(valueBindingsText),
      overloadDispatch: sha256(overloadDispatchText),
      loweringPlan: sha256(loweringPlanText)
    }
  };
}

function cString(value) {
  let out = "";
  for (const byte of Buffer.from(value, "utf8")) {
    if (byte === 0x22 || byte === 0x5c) out += `\\${String.fromCharCode(byte)}`;
    else if (byte >= 0x20 && byte < 0x7f) out += String.fromCharCode(byte);
    else out += `\\x${byte.toString(16).padStart(2, "0")}`;
  }
  return `"${out}"`;
}

/** Second-stage interner: shape keys plus every literal the native tables need. */
function buildNativeText(model) {
  const entries = [];
  const index = new Map();
  const intern = (value) => {
    if (typeof value !== "string") return -1;
    const existing = index.get(value);
    if (existing !== undefined) return existing;
    const id = entries.length;
    entries.push(value);
    index.set(value, id);
    return id;
  };
  const shapeKeys = model.shapes.map((shape) => shape.key >= 0 ? intern(model.text[shape.key]) : -1);
  const routes = model.routes.map((route) => ({
    canonical: intern(route.canonical),
    context: intern(route.context),
    reasons: transportOrder.map((transport) => {
      const disposition = route.transports[transport];
      return disposition.status === "skip" ? intern(disposition.reason) : -1;
    }),
    luaAdapterReason: route.luaAdapter.status === "skip" ? intern(route.luaAdapter.reason) : -1
  }));
  return { entries, shapeKeys, routes };
}

