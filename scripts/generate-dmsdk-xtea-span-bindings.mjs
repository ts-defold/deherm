import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const defaults = {
  ir: "bindings/generated/defold-sdk-ir.json",
  shapes: "bindings/generated/defold-dmsdk-abi-shapes.json",
  policy: "bindings/overrides/dmsdk-xtea-span-bindings.json",
};

const sha256 = (value) => createHash("sha256").update(value).digest("hex");
const snake = (value) => value
  .replace(/::/g, "_")
  .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
  .toLowerCase();

function parseArgs(argv) {
  const options = { ...defaults, outRoot: root, check: false };

  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === "--check") {
      options.check = true;
    } else if (["--ir", "--shapes", "--policy", "--out-root"].includes(argument)) {
      const key = argument.slice(2).replace(/-([a-z])/g, (_, character) => character.toUpperCase());
      options[key] = resolve(argv[++index]);
    } else {
      throw new Error(`Unknown argument ${argument}`);
    }
  }

  for (const key of Object.keys(defaults)) {
    options[key] = resolve(root, options[key]);
  }
  return options;
}

function candidates(shapes, selector) {
  return shapes.rows
    .filter((row) => row.tranche === "arena-backed-spans"
      && selector.symbols.includes(row.symbol)
      && row.header === selector.header
      && row.shape === selector.shape)
    .sort((left, right) => left.id.localeCompare(right.id));
}

function renderHeader(entries) {
  const declarations = entries
    .map(({ wrapper }) => `uint8_t ${wrapper}(uint8_t*,uint32_t,const uint8_t*,uint32_t);`)
    .join("\n");

  return `// Generated by scripts/generate-dmsdk-xtea-span-bindings.mjs. Do not edit.\n#ifndef DEFOLD_HERMES_GENERATED_DMSDK_XTEA_SPAN_H\n#define DEFOLD_HERMES_GENERATED_DMSDK_XTEA_SPAN_H\n#include <stdint.h>\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n${declarations}\n#ifdef __cplusplus\n}\n#endif\n#endif\n`;
}

function renderSource(entries) {
  const wrappers = entries
    .map(({ wrapper, declaration }) => `uint8_t ${wrapper}(uint8_t*d,uint32_t n,const uint8_t*k,uint32_t z){if(!d||!k||z>16)return 0;return ${declaration.name}(dmCrypt::ALGORITHM_XTEA,d,n,k,z)==dmCrypt::RESULT_OK;}`)
    .join("");

  return `// Generated by scripts/generate-dmsdk-xtea-span-bindings.mjs. Do not edit.\n#include <defold_hermes/generated_dmsdk_xtea_span.h>\n#include <dmsdk/dlib/crypt.h>\nextern \"C\" {${wrappers} }\n`;
}

function renderRuntimeHeader() {
  return `// Generated by scripts/generate-dmsdk-xtea-span-bindings.mjs. Do not edit.\n#ifndef DEFOLD_HERMES_GENERATED_DMSDK_XTEA_SPAN_RUNTIME_H\n#define DEFOLD_HERMES_GENERATED_DMSDK_XTEA_SPAN_RUNTIME_H\n#include <stdint.h>\ntypedef enum DehermDmSdkXteaSpanStatus{DEHERM_DMSDK_XTEA_SPAN_OK,DEHERM_DMSDK_XTEA_SPAN_UNKNOWN_ID,DEHERM_DMSDK_XTEA_SPAN_NULL_STORAGE,DEHERM_DMSDK_XTEA_SPAN_KEY_TOO_LONG,DEHERM_DMSDK_XTEA_SPAN_NATIVE_FAILURE}DehermDmSdkXteaSpanStatus;\n#ifdef __cplusplus\nextern \"C\" {\n#endif\nuint32_t deherm_dmsdk_xtea_span_count(void);DehermDmSdkXteaSpanStatus deherm_dmsdk_xtea_span_dispatch(uint16_t,uint8_t*,uint32_t,const uint8_t*,uint32_t);\n#ifdef __cplusplus\n}\n#endif\n#endif\n`;
}

function renderRuntime(entries) {
  const cases = entries
    .map(({ id, wrapper }) => `case ${id}:ok=${wrapper}(d,n,k,z);break;`)
    .join("");

  return `// Generated by scripts/generate-dmsdk-xtea-span-bindings.mjs. Do not edit.\n#include <defold_hermes/generated_dmsdk_xtea_span.h>\n#include <defold_hermes/generated_dmsdk_xtea_span_runtime.h>\nextern \"C\" {uint32_t deherm_dmsdk_xtea_span_count(void){return ${entries.length};}DehermDmSdkXteaSpanStatus deherm_dmsdk_xtea_span_dispatch(uint16_t id,uint8_t*d,uint32_t n,const uint8_t*k,uint32_t z){if(id>=${entries.length})return DEHERM_DMSDK_XTEA_SPAN_UNKNOWN_ID;if(!d||!k)return DEHERM_DMSDK_XTEA_SPAN_NULL_STORAGE;if(z>16)return DEHERM_DMSDK_XTEA_SPAN_KEY_TOO_LONG;uint8_t ok=0;switch(id){${cases}default:return DEHERM_DMSDK_XTEA_SPAN_UNKNOWN_ID;}return ok?DEHERM_DMSDK_XTEA_SPAN_OK:DEHERM_DMSDK_XTEA_SPAN_NATIVE_FAILURE;}}\n`;
}

function renderArtifacts(entries) {
  return new Map([
    ["defold/defold_hermes/include/defold_hermes/generated_dmsdk_xtea_span.h", renderHeader(entries)],
    ["defold/defold_hermes/include/defold_hermes/generated_dmsdk_xtea_span_runtime.h", renderRuntimeHeader()],
    ["defold/defold_hermes/src/generated_dmsdk_xtea_span_crypt.cpp", renderSource(entries)],
    ["defold/defold_hermes/src/generated_dmsdk_xtea_span_runtime.cpp", renderRuntime(entries)],
  ]);
}

function validateProvenance(ir, shapes, irText) {
  if (ir.defoldRevision !== shapes.defoldRevision) {
    throw new Error("Defold revisions differ between IR and ABI-shape census");
  }
  if (sha256(irText) !== shapes.sourceHashes.ir) {
    throw new Error("IR hash does not match ABI-shape census provenance");
  }

  const declarationIds = ir.declarations.map(({ id }) => id);
  const shapeIds = shapes.rows.map(({ id }) => id);
  if (new Set(declarationIds).size !== declarationIds.length
      || new Set(shapeIds).size !== shapeIds.length) {
    throw new Error("IR or ABI-shape census contains duplicate declaration ids");
  }
}

function validatePolicyCoverage(selected, policy) {
  const selectedIds = selected.map(({ id }) => id);
  const policyIds = Object.keys(policy.entries).sort();
  if (selected.length !== 2 || JSON.stringify(selectedIds) !== JSON.stringify(policyIds)) {
    throw new Error("xtea policy must exactly cover census candidates");
  }
}

async function validateEvidence(selected, policy) {
  for (const candidate of selected) {
    for (const evidence of policy.entries[candidate.id].evidence) {
      const header = await readFile(resolve(root, evidence.header), "utf8");
      if (header.split("\n")[evidence.line - 1] !== evidence.text) {
        throw new Error(`Xtea evidence drifted for ${candidate.id}`);
      }
    }
  }
}

function createEntries(selected, declarations, policy) {
  return selected.map((candidate, id) => ({
    id,
    declaration: declarations.get(candidate.id),
    candidate,
    wrapper: `deherm_dmsdk_xtea_span_${snake(candidate.symbol)}`,
    evidence: policy.entries[candidate.id].evidence,
  }));
}

function createReport(contents, ir, shapes, policy, entries, artifacts) {
  return {
    schemaVersion: 1,
    policyVersion: policy.policyVersion,
    defoldRevision: ir.defoldRevision,
    sources: defaults,
    sourceHashes: {
      ir: sha256(contents.ir),
      shapes: sha256(contents.shapes),
      policy: sha256(contents.policy),
    },
    policy: {
      algorithm: "ALGORITHM_XTEA only",
      keyLength: "0..16 bytes checked before native assertion",
    },
    coverage: {
      baselineRuntimePending: shapes.coverage.runtimePending,
      discovered: 2,
      emitted: 2,
      policyBlocked: 0,
      hostBehaviorVerified: 2,
      remainingWithoutGeneratedAdapters: 1318,
    },
    artifactHashes: Object.fromEntries(
      [...artifacts].map(([path, content]) => [path, sha256(content)]),
    ),
    artifacts: [...artifacts.keys()].sort(),
    declarations: entries.map(({ id, candidate, wrapper, evidence }) => ({
      ...candidate,
      bindingId: id,
      mode: candidate.symbol.endsWith("Encrypt") ? "encrypt" : "decrypt",
      evidence,
      wrapper,
      stages: {
        generated: "complete",
        compiled: "packaged-sdk-object-test",
        linked: "packaged-sdk-host-link-test",
        runtime: "packaged-sdk-host-behavior-test",
        allocation: "100000-warmed-dispatch-zero-cpp-operator-new",
      },
    })),
  };
}

async function writeOrCheck(options, relative, content) {
  const path = resolve(options.outRoot, relative);
  if (options.check) {
    if (await readFile(path, "utf8") !== content) {
      throw new Error(`${relative} is stale`);
    }
    return;
  }

  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, content);
}

export async function run(argv = process.argv.slice(2)) {
  const options = parseArgs(argv);
  const [irText, shapesText, policyText] = await Promise.all([
    readFile(options.ir, "utf8"),
    readFile(options.shapes, "utf8"),
    readFile(options.policy, "utf8"),
  ]);
  const contents = { ir: irText, shapes: shapesText, policy: policyText };
  const ir = JSON.parse(irText);
  const shapes = JSON.parse(shapesText);
  const policy = JSON.parse(policyText);
  validateProvenance(ir, shapes, irText);

  const declarations = new Map(ir.declarations.map((declaration) => [declaration.id, declaration]));
  const selected = candidates(shapes, policy.candidateSelector);
  validatePolicyCoverage(selected, policy);
  await validateEvidence(selected, policy);

  const entries = createEntries(selected, declarations, policy);
  const artifacts = renderArtifacts(entries);
  const report = createReport(contents, ir, shapes, policy, entries, artifacts);
  artifacts.set(
    "bindings/generated/defold-dmsdk-xtea-span-bindings.json",
    `${JSON.stringify(report, null, 2)}\n`,
  );

  for (const [path, content] of artifacts) {
    await writeOrCheck(options, path, content);
  }
  process.stdout.write(`${options.check ? "Verified" : "Generated"} ${report.coverage.emitted}/${report.coverage.discovered} XTEA-span dmSDK bindings.\n`);
  return report;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  await run();
}
