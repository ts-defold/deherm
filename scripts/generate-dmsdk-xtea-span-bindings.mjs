import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { DMSDK_UNIVERSAL_FALLBACK_PATTERN } from "../packages/compiler/src/dmsdk-pattern-selector.mjs";
import { indexDmSdkBoundedSpanPlan } from "../packages/compiler/src/dmsdk-bounded-span-plan.mjs";
import {
  analyzeXteaSpanRecipe,
  createDmSdkFallbackAudit,
  publicDmSdkHeader,
} from "../packages/compiler/src/dmsdk-bounded-span-recipes.mjs";
import { xteaSpanPattern } from "../packages/compiler/src/dmsdk-pattern-catalog.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const defaults = {
  ir: "packages/bindings/generated/defold-sdk-ir.json",
  shapes: "packages/bindings/generated/defold-dmsdk-abi-shapes.json",
  sourceFacts: "packages/bindings/generated/defold-dmsdk-source-semantic-facts.json",
  plan: "packages/bindings/generated/defold-dmsdk-bounded-span-plan.json",
  policy: "packages/bindings/overrides/dmsdk-xtea-span-bindings.json",
};

const sha256 = (value) => createHash("sha256").update(value).digest("hex");
const snake = (value) =>
  value
    .replace(/::/g, "_")
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .toLowerCase();

function parseArgs(argv) {
  const options = { ...defaults, outRoot: root, check: false };

  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === "--check") {
      options.check = true;
    } else if (["--ir", "--shapes", "--source-facts", "--plan", "--policy", "--out-root"].includes(argument)) {
      const key = argument.slice(2).replace(/-([a-z])/g, (_, character) => character.toUpperCase());
      options[key] = resolve(argv[++index]);
    } else {
      throw new Error(`Unknown argument ${argument}`);
    }
  }

  for (const key of Object.keys(defaults)) {
    options[key] = resolve(root, options[key]);
  }
  return options;
}

export function extractXteaSpanSemantics(declaration, candidate, enumDeclarations, recipe, sourceFacts) {
  return analyzeXteaSpanRecipe(declaration, candidate, enumDeclarations, recipe, sourceFacts).semantics;
}

function renderHeader(entries) {
  const declarations = entries
    .map(({ wrapper }) => `uint8_t ${wrapper}(uint8_t*,uint32_t,const uint8_t*,uint32_t);`)
    .join("\n");

  return `// Generated by scripts/generate-dmsdk-xtea-span-bindings.mjs. Do not edit.\n#ifndef DEFOLD_HERMES_GENERATED_DMSDK_XTEA_SPAN_H\n#define DEFOLD_HERMES_GENERATED_DMSDK_XTEA_SPAN_H\n#include <stdint.h>\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n${declarations}\n#ifdef __cplusplus\n}\n#endif\n#endif\n`;
}

function renderSource(entries, maximumKeyBytes) {
  const includes = [...new Set(entries.map(({ declaration }) => publicDmSdkHeader(declaration.header)))]
    .sort()
    .map((header) => `#include <${header}>`)
    .join("\n");
  const wrappers = entries
    .map(
      ({ wrapper, declaration, algorithmExpression, successExpression }) =>
        `uint8_t ${wrapper}(uint8_t*d,uint32_t n,const uint8_t*k,uint32_t z){if(!d||!k||z>${maximumKeyBytes})return 0;return ${declaration.name}(${algorithmExpression},d,n,k,z)==${successExpression};}`,
    )
    .join("");

  return `// Generated by scripts/generate-dmsdk-xtea-span-bindings.mjs. Do not edit.\n#include <defold_hermes/generated_dmsdk_xtea_span.h>\n${includes}\nextern \"C\" {${wrappers} }\n`;
}

function renderRuntimeHeader() {
  return `// Generated by scripts/generate-dmsdk-xtea-span-bindings.mjs. Do not edit.\n#ifndef DEFOLD_HERMES_GENERATED_DMSDK_XTEA_SPAN_RUNTIME_H\n#define DEFOLD_HERMES_GENERATED_DMSDK_XTEA_SPAN_RUNTIME_H\n#include <stdint.h>\ntypedef enum DehermDmSdkXteaSpanStatus{DEHERM_DMSDK_XTEA_SPAN_OK,DEHERM_DMSDK_XTEA_SPAN_UNKNOWN_ID,DEHERM_DMSDK_XTEA_SPAN_NULL_STORAGE,DEHERM_DMSDK_XTEA_SPAN_KEY_TOO_LONG,DEHERM_DMSDK_XTEA_SPAN_NATIVE_FAILURE}DehermDmSdkXteaSpanStatus;\n#ifdef __cplusplus\nextern \"C\" {\n#endif\nuint32_t deherm_dmsdk_xtea_span_count(void);DehermDmSdkXteaSpanStatus deherm_dmsdk_xtea_span_dispatch(uint16_t,uint8_t*,uint32_t,const uint8_t*,uint32_t);\n#ifdef __cplusplus\n}\n#endif\n#endif\n`;
}

function renderRuntime(entries, maximumKeyBytes) {
  const cases = entries.map(({ id, wrapper }) => `case ${id}:ok=${wrapper}(d,n,k,z);break;`).join("");

  return `// Generated by scripts/generate-dmsdk-xtea-span-bindings.mjs. Do not edit.\n#include <defold_hermes/generated_dmsdk_xtea_span.h>\n#include <defold_hermes/generated_dmsdk_xtea_span_runtime.h>\nextern \"C\" {uint32_t deherm_dmsdk_xtea_span_count(void){return ${entries.length};}DehermDmSdkXteaSpanStatus deherm_dmsdk_xtea_span_dispatch(uint16_t id,uint8_t*d,uint32_t n,const uint8_t*k,uint32_t z){if(id>=${entries.length})return DEHERM_DMSDK_XTEA_SPAN_UNKNOWN_ID;if(!d||!k)return DEHERM_DMSDK_XTEA_SPAN_NULL_STORAGE;if(z>${maximumKeyBytes})return DEHERM_DMSDK_XTEA_SPAN_KEY_TOO_LONG;uint8_t ok=0;switch(id){${cases}default:return DEHERM_DMSDK_XTEA_SPAN_UNKNOWN_ID;}return ok?DEHERM_DMSDK_XTEA_SPAN_OK:DEHERM_DMSDK_XTEA_SPAN_NATIVE_FAILURE;}}\n`;
}

function renderArtifacts(entries, maximumKeyBytes) {
  return new Map([
    ["defold/defold_hermes/include/defold_hermes/generated_dmsdk_xtea_span.h", renderHeader(entries)],
    ["defold/defold_hermes/include/defold_hermes/generated_dmsdk_xtea_span_runtime.h", renderRuntimeHeader()],
    ["defold/defold_hermes/src/generated_dmsdk_xtea_span_crypt.cpp", renderSource(entries, maximumKeyBytes)],
    ["defold/defold_hermes/src/generated_dmsdk_xtea_span_runtime.cpp", renderRuntime(entries, maximumKeyBytes)],
  ]);
}

function validateProvenance(ir, shapes, irText) {
  if (ir.defoldRevision !== shapes.defoldRevision) {
    throw new Error("Defold revisions differ between IR and ABI-shape census");
  }
  if (sha256(irText) !== shapes.sourceHashes.ir) {
    throw new Error("IR hash does not match ABI-shape census provenance");
  }

  const declarationIds = ir.declarations.map(({ id }) => id);
  const shapeIds = shapes.rows.map(({ id }) => id);
  if (new Set(declarationIds).size !== declarationIds.length || new Set(shapeIds).size !== shapeIds.length) {
    throw new Error("IR or ABI-shape census contains duplicate declaration ids");
  }
}

function createEntries(rows, declarations, planById) {
  const patterns = [xteaSpanPattern(), DMSDK_UNIVERSAL_FALLBACK_PATTERN];
  const entries = [];
  const blocked = [];
  let structurallyEligible = 0;
  for (const candidate of [...rows].sort((left, right) => left.id.localeCompare(right.id))) {
    const decision = planById.get(candidate.id);
    if (!decision?.structuralCandidates.includes("span.in-place-keyed-transform")) continue;
    structurallyEligible += 1;
    const declaration = declarations.get(candidate.id);
    if (!declaration) throw new Error(`XTEA-span candidate is absent from dmSDK IR: ${candidate.id}`);
    const semantics = decision.patternId === "span.in-place-keyed-transform" ? decision.semantics : null;
    if (decision.patternId !== "span.in-place-keyed-transform") {
      blocked.push({
        ...candidate,
        emitted: false,
        blocker: "xtea-span-evidence-withdrawn",
        patternDecision: decision.patternId,
        fallbackAudit: createDmSdkFallbackAudit({
          candidate,
          family: "xtea-span",
          patternId: "span.in-place-keyed-transform",
          emitter: "scripts/generate-dmsdk-xtea-span-bindings.mjs",
          missingFacts: decision.missingFacts,
        }),
      });
      continue;
    }
    entries.push({
      id: entries.length,
      declaration,
      candidate,
      wrapper: `deherm_dmsdk_xtea_span_${snake(candidate.symbol)}`,
      mode: semantics.mode,
      algorithmExpression: semantics.algorithmExpression,
      successExpression: semantics.successExpression,
      maximumKeyBytes: semantics.maximumKeyBytes,
      evidence: semantics.evidence,
      patternDecision: decision.patternId,
    });
  }
  return { entries, blocked, structurallyEligible, patterns };
}

function createReport(
  contents,
  ir,
  shapes,
  policy,
  entries,
  blocked,
  structurallyEligible,
  patterns,
  artifacts,
  maximumKeyBytes,
) {
  return {
    schemaVersion: 1,
    policyVersion: policy.policyVersion,
    defoldRevision: ir.defoldRevision,
    sources: defaults,
    sourceHashes: Object.fromEntries(Object.entries(contents).map(([key, value]) => [key, sha256(value)])),
    policy: {
      recipe: policy.recipe,
      patternRegistry: patterns.map(({ id, family, emitter, priority, cost, fallback, when }) => ({
        id,
        family,
        emitter,
        priority,
        cost,
        fallback,
        when,
      })),
      algorithm: "the revision's sole algorithm enum member",
      keyLength: `0..${maximumKeyBytes} bytes checked before the native call`,
    },
    coverage: {
      baselineRuntimePending: shapes.coverage.runtimePending,
      discovered: structurallyEligible,
      structurallyEligible,
      emitted: entries.length,
      policyBlocked: blocked.length,
      hostBehaviorVerified: entries.length,
      remainingWithoutGeneratedAdapters: shapes.coverage.runtimePending - 41 - entries.length,
    },
    artifactHashes: Object.fromEntries([...artifacts].map(([path, content]) => [path, sha256(content)])),
    artifacts: [...artifacts.keys()].sort(),
    fallbackAudit: {
      retainedImplementation: "@deherm/compiler/dmsdk-universal-materializer",
      count: blocked.length,
      entries: blocked.map(({ fallbackAudit }) => fallbackAudit),
    },
    declarations: [
      ...entries.map(({ id, candidate, wrapper, mode, maximumKeyBytes: entryMaximum, evidence, patternDecision }) => ({
        ...candidate,
        bindingId: id,
        mode,
        maximumKeyBytes: entryMaximum,
        evidence,
        patternDecision,
        wrapper,
        stages: {
          generated: "complete",
          compiled: "packaged-sdk-object-test",
          linked: "packaged-sdk-host-link-test",
          runtime: "packaged-sdk-host-behavior-test",
          allocation: "100000-warmed-dispatch-zero-cpp-operator-new",
        },
      })),
      ...blocked,
    ],
  };
}

async function writeOrCheck(options, relative, content) {
  const path = resolve(options.outRoot, relative);
  if (options.check) {
    if ((await readFile(path, "utf8")) !== content) {
      throw new Error(`${relative} is stale`);
    }
    return;
  }

  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, content);
}

export async function run(argv = process.argv.slice(2)) {
  const options = parseArgs(argv);
  const [irText, shapesText, sourceFactsText, planText, policyText] = await Promise.all([
    readFile(options.ir, "utf8"),
    readFile(options.shapes, "utf8"),
    readFile(options.sourceFacts, "utf8"),
    readFile(options.plan, "utf8"),
    readFile(options.policy, "utf8"),
  ]);
  const contents = { ir: irText, shapes: shapesText, sourceFacts: sourceFactsText, plan: planText, policy: policyText };
  const ir = JSON.parse(irText);
  const shapes = JSON.parse(shapesText);
  const plan = JSON.parse(planText);
  const policy = JSON.parse(policyText);
  validateProvenance(ir, shapes, irText);
  const planById = indexDmSdkBoundedSpanPlan(plan, {
    revision: ir.defoldRevision,
    sourceHashes: {
      ir: sha256(irText),
      shapes: sha256(shapesText),
      sourceFacts: sha256(sourceFactsText),
      xtea: sha256(policyText),
    },
  });
  if (
    policy.schemaVersion !== 1 ||
    policy.policyVersion !== "xtea-span-v4" ||
    policy.family !== "in-place-keyed-transform" ||
    policy.recipe?.data !== "borrowed-mutable-counted-bytes" ||
    policy.recipe?.key !== "borrowed-counted-bytes" ||
    policy.recipe?.requireSingleAlgorithm !== true ||
    policy.recipe?.ownership !== "synchronous-noescape" ||
    policy.recipe?.fallback !== "universal-recipe"
  ) {
    throw new Error("Unsupported XTEA-span semantic policy");
  }

  const declarations = new Map(ir.declarations.map((declaration) => [declaration.id, declaration]));
  const { entries, blocked, structurallyEligible, patterns } = createEntries(
    shapes.rows,
    declarations,
    planById,
  );
  const keyMaximums = [...new Set(entries.map(({ maximumKeyBytes }) => maximumKeyBytes))].sort(
    (left, right) => left - right,
  );
  if (keyMaximums.length > 1) {
    throw new Error(`XTEA transforms disagree on the implementation-derived key maximum: ${keyMaximums.join(", ")}`);
  }
  const maximumKeyBytes = keyMaximums[0] ?? 0;
  const artifacts = renderArtifacts(entries, maximumKeyBytes);
  const report = createReport(
    contents,
    ir,
    shapes,
    policy,
    entries,
    blocked,
    structurallyEligible,
    patterns,
    artifacts,
    maximumKeyBytes,
  );
  artifacts.set(
    "packages/bindings/generated/defold-dmsdk-xtea-span-bindings.json",
    `${JSON.stringify(report, null, 2)}\n`,
  );

  for (const [path, content] of artifacts) {
    await writeOrCheck(options, path, content);
  }
  process.stdout.write(
    `${options.check ? "Verified" : "Generated"} ${report.coverage.emitted}/${report.coverage.discovered} XTEA-span dmSDK bindings.\n`,
  );
  return report;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  await run();
}
