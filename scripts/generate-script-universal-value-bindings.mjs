function renderSource(rows) {
  const operations = rows.map((row) =>
    `  {0x${row.stableId.toString(16).padStart(8, "0")}u, ${quote(row.id)}, ${quote(row.modulePath.join("."))}, ${quote(row.member)}, ${row.minimumArgumentCount}, ${row.maximumArgumentCount}, ${row.resultCount}},`
  ).join("\n");
  return `// Generated by scripts/generate-script-universal-value-bindings.mjs. Do not edit.
#include <defold_hermes/generated_script_universal_value_bindings.hpp>

#include <cstdio>

namespace defold_hermes::universal_value {
namespace {
constexpr Operation kOperations[] = {
${operations}
};

void fail(char* error, size_t capacity, const char* message) noexcept {
  if (error && capacity) std::snprintf(error, capacity, "%s", message);
}
}  // namespace

const Operation* operations() noexcept { return kOperations; }

const Operation* find(uint32_t stableId) noexcept {
  size_t first = 0;
  size_t count = kOperationCount;
  while (count) {
    const size_t step = count / 2;
    const size_t index = first + step;
    if (kOperations[index].stableId < stableId) {
      first = index + 1;
      count -= step + 1;
    } else {
      count = step;
    }
  }
  return first < kOperationCount && kOperations[first].stableId == stableId
      ? &kOperations[first] : nullptr;
}

DispatchStatus dispatch(
    ScriptCallFrame* frame,
    char* error,
    size_t errorCapacity,
    const LuaApi* api) noexcept {
  if (!frame) {
    fail(error, errorCapacity, "Universal-value call frame is null");
    return DispatchStatus::kError;
  }
  const Operation* operation = find(frame->stableId);
  if (!operation) return DispatchStatus::kMissing;
  frame->resultCount = 0;
  if (frame->argumentCount < operation->minimumArgumentCount ||
      frame->argumentCount > operation->maximumArgumentCount ||
      (frame->argumentCount && !frame->arguments)) {
    fail(error, errorCapacity, "Universal-value argument count does not match descriptor");
    return DispatchStatus::kError;
  }
  if (operation->resultCount &&
      (!frame->results || frame->resultCapacity < operation->resultCount)) {
    fail(error, errorCapacity, "Universal-value result storage is exhausted");
    return DispatchStatus::kError;
  }
  if (!api || !api->invoke) {
    fail(error, errorCapacity, "Universal-value captured Lua backend is unavailable");
    return DispatchStatus::kError;
  }
  const DispatchStatus status = api->invoke(
      api->context, *operation, frame, error, errorCapacity);
  if (status != DispatchStatus::kSuccess) {
    frame->resultCount = 0;
    if (status == DispatchStatus::kMissing) {
      fail(error, errorCapacity, "Universal-value backend rejected a generated operation");
      return DispatchStatus::kError;
    }
    return status;
  }
  if (frame->resultCount != operation->resultCount) {
    frame->resultCount = 0;
    fail(error, errorCapacity, "Universal-value Lua result count does not match descriptor");
    return DispatchStatus::kError;
  }
  return DispatchStatus::kSuccess;
}

}  // namespace defold_hermes::universal_value
`;
}

