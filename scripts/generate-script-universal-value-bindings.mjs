function chunk(items, size) {
  const output = [];
  for (let index = 0; index < items.length; index += size) output.push(items.slice(index, index + size));
  return output;
}

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

/**
 * Transparent Defold value records reach the sound-typed transport as exact
 * element lanes. The counts come from the pinned dmSDK layout report, never
 * from a literal here, so a Defold layout change fails generation instead of
 * silently reshaping the typed frame ABI.
 */
function layoutOf(layouts, name, transport) {
  const layout = layouts.transparent[name];
  assert(layout, `Defold value layout report declares no transparent ${name}`);
  assert(layout.transport === transport,
    `Defold value ${name} changed transport to ${layout.transport}`);
  return layout;
}

function matrix4Elements(layouts) {
  const layout = layoutOf(layouts, "matrix4", "float-arena");
  assert(layout.element === "f32" && layout.ordering === "column-major",
    "Defold Matrix4 is no longer a column-major float32 record");
  return Array.from({ length: layout.storageElements }, (_, index) => `e${index}`);
}

function urlLanes(layouts) {
  const layout = layoutOf(layouts, "url", "u64-lane-quad");
  assert(layout.element === "uint64_t", "Defold URL lanes are no longer exact 64-bit values");
  return layout.fields.map(({ name }) => name.replace(/^_?m?_?/, "").toLowerCase());
}

