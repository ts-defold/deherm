import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { semanticDeclarationId, semanticEntryMap } from "./lib/dmsdk-semantic-id.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const defaults = {
  ir: "packages/bindings/generated/defold-sdk-ir.json",
  shapes: "packages/bindings/generated/defold-dmsdk-abi-shapes.json",
  policy: "packages/bindings/overrides/dmsdk-base64-span-bindings.json",
};

const sha256 = (value) => createHash("sha256").update(value).digest("hex");
const snake = (value) => value
  .replace(/::/g, "_")
  .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
  .toLowerCase();

function parseArgs(argv) {
  const options = { ...defaults, outRoot: root, check: false };

  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === "--check") {
      options.check = true;
    } else if (["--ir", "--shapes", "--policy", "--out-root"].includes(argument)) {
      const key = argument.slice(2).replace(/-([a-z])/g, (_, character) => character.toUpperCase());
      options[key] = resolve(argv[++index]);
    } else {
      throw new Error(`Unknown argument ${argument}`);
    }
  }

  for (const key of ["ir", "shapes", "policy"]) {
    options[key] = resolve(root, options[key]);
  }
  return options;
}

function candidates(shapes, selector) {
  return shapes.rows
    .filter((row) => row.tranche === "arena-backed-spans"
      && row.header === selector.header
      && row.symbol.startsWith(selector.symbolPrefix)
      && row.shape === selector.shape)
    .sort((left, right) => left.id.localeCompare(right.id));
}

function renderHeader(entries) {
  const declarations = entries
    .map(({ wrapper }) => `uint8_t ${wrapper}(const uint8_t* input, uint32_t input_length, uint8_t* output, uint32_t* inout_output_length);`)
    .join("\n");

  return `// Generated by scripts/generate-dmsdk-base64-span-bindings.mjs. Do not edit.\n#ifndef DEFOLD_HERMES_GENERATED_DMSDK_BASE64_SPAN_H\n#define DEFOLD_HERMES_GENERATED_DMSDK_BASE64_SPAN_H\n#include <stdint.h>\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n${declarations}\n#ifdef __cplusplus\n}\n#endif\n#endif\n`;
}

function renderSource(entries) {
  const wrappers = entries
    .map(({ wrapper, declaration }) => `uint8_t ${wrapper}(const uint8_t* input, uint32_t input_length, uint8_t* output, uint32_t* inout_output_length)\n{\n  if(inout_output_length==nullptr||(input_length!=0&&input==nullptr)||(*inout_output_length!=0&&output==nullptr))return UINT8_C(0); return ${declaration.name}(input, input_length, output, inout_output_length) ? UINT8_C(1) : UINT8_C(0);\n}`)
    .join("\n");

  return `// Generated by scripts/generate-dmsdk-base64-span-bindings.mjs. Do not edit.\n#include <defold_hermes/generated_dmsdk_base64_span.h>\n#include <dmsdk/dlib/crypt.h>\nextern \"C\" {\n${wrappers} }\n`;
}

function renderRuntimeHeader() {
  return `// Generated by scripts/generate-dmsdk-base64-span-bindings.mjs. Do not edit.\n#ifndef DEFOLD_HERMES_GENERATED_DMSDK_BASE64_SPAN_RUNTIME_H\n#define DEFOLD_HERMES_GENERATED_DMSDK_BASE64_SPAN_RUNTIME_H\n#include <stdint.h>\ntypedef enum DehermDmSdkBase64SpanStatus { DEHERM_DMSDK_BASE64_SPAN_OK=0, DEHERM_DMSDK_BASE64_SPAN_UNKNOWN_ID=1, DEHERM_DMSDK_BASE64_SPAN_NULL_STORAGE=2, DEHERM_DMSDK_BASE64_SPAN_QUERY=3, DEHERM_DMSDK_BASE64_SPAN_NONCANONICAL_INPUT=4, DEHERM_DMSDK_BASE64_SPAN_NATIVE_FAILURE=5 } DehermDmSdkBase64SpanStatus;\ntypedef struct DehermDmSdkBase64SpanDescriptor { uint16_t id; uint8_t requires_padded_input; const char* declaration_id; } DehermDmSdkBase64SpanDescriptor;\n#ifdef __cplusplus\nextern \"C\" {\n#endif\nuint32_t deherm_dmsdk_base64_span_count(void);\nconst DehermDmSdkBase64SpanDescriptor* deherm_dmsdk_base64_span_descriptors(void);\nDehermDmSdkBase64SpanStatus deherm_dmsdk_base64_span_dispatch(uint16_t id, const uint8_t* input, uint32_t input_length, uint8_t* output, uint32_t output_capacity, uint32_t* out_written);\n#ifdef __cplusplus\n}\n#endif\n#endif\n`;
}

function renderRuntime(entries) {
  const descriptors = entries
    .map(({ id, declaration, requirePaddedInput }) => `  { UINT16_C(${id}), UINT8_C(${requirePaddedInput ? 1 : 0}), ${JSON.stringify(declaration.id)} }`)
    .join(",\n");
  const cases = entries
    .map(({ id, wrapper }) => `    case ${id}: success=${wrapper}(input,input_length,output,&written); break;`)
    .join("\n");

  return `// Generated by scripts/generate-dmsdk-base64-span-bindings.mjs. Do not edit.\n#include <defold_hermes/generated_dmsdk_base64_span.h>\n#include <defold_hermes/generated_dmsdk_base64_span_runtime.h>\nnamespace {\nuint8_t sextet(uint8_t value) {\n  if (value >= 'A' && value <= 'Z') return value - 'A';\n  if (value >= 'a' && value <= 'z') return value - 'a' + UINT8_C(26);\n  if (value >= '0' && value <= '9') return value - '0' + UINT8_C(52);\n  if (value == '+') return UINT8_C(62);\n  if (value == '/') return UINT8_C(63);\n  return UINT8_MAX;\n}\nbool canonical(const uint8_t* input, uint32_t length) {\n  if ((length & UINT32_C(3)) != 0) return false;\n  uint32_t padding = 0;\n  if (length && input[length - 1] == '=') ++padding;\n  if (length > 1 && input[length - 2] == '=') ++padding;\n  if (padding > 2) return false;\n  for (uint32_t index = 0; index < length - padding; ++index) {\n    if (sextet(input[index]) == UINT8_MAX) return false;\n  }\n  for (uint32_t index = length - padding; index < length; ++index) {\n    if (input[index] != '=') return false;\n  }\n  if (padding == 2 && (sextet(input[length - 3]) & UINT8_C(0x0f)) != 0) return false;\n  if (padding == 1 && (sextet(input[length - 2]) & UINT8_C(0x03)) != 0) return false;\n  return true;\n}\nconst DehermDmSdkBase64SpanDescriptor kDescriptors[] = {\n${descriptors}\n};\n}\nextern \"C\" {\nuint32_t deherm_dmsdk_base64_span_count(void) { return UINT32_C(${entries.length}); }\nconst DehermDmSdkBase64SpanDescriptor* deherm_dmsdk_base64_span_descriptors(void) { return kDescriptors; }\nDehermDmSdkBase64SpanStatus deherm_dmsdk_base64_span_dispatch(uint16_t id, const uint8_t* input, uint32_t input_length, uint8_t* output, uint32_t output_capacity, uint32_t* out_written) {\n  if (id >= deherm_dmsdk_base64_span_count()) return DEHERM_DMSDK_BASE64_SPAN_UNKNOWN_ID;\n  if (out_written == nullptr || (input_length != 0 && input == nullptr) || (output_capacity != 0 && output == nullptr)) return DEHERM_DMSDK_BASE64_SPAN_NULL_STORAGE;\n  if (kDescriptors[id].requires_padded_input && !canonical(input,input_length)) return DEHERM_DMSDK_BASE64_SPAN_NONCANONICAL_INPUT;\n  uint32_t written=output_capacity; uint8_t success=0;\n  switch (id) {\n${cases}\n    default: return DEHERM_DMSDK_BASE64_SPAN_UNKNOWN_ID;\n  }\n  *out_written=written;\n  if (output_capacity == 0) return DEHERM_DMSDK_BASE64_SPAN_QUERY;\n  return success ? DEHERM_DMSDK_BASE64_SPAN_OK : DEHERM_DMSDK_BASE64_SPAN_NATIVE_FAILURE;\n}\n}\n`;
}

async function readInputs(options) {
  return Object.fromEntries(await Promise.all(
    Object.keys(defaults).map(async (key) => [key, await readFile(options[key], "utf8")]),
  ));
}

function validateProvenance(ir, shapes, contents) {
  if (ir.defoldRevision !== shapes.defoldRevision) {
    throw new Error("Defold revisions differ between IR and ABI-shape census");
  }
  if (sha256(contents.ir) !== shapes.sourceHashes.ir) {
    throw new Error("IR hash does not match ABI-shape census provenance");
  }

  const declarationIds = ir.declarations.map(({ id }) => id);
  const shapeIds = shapes.rows.map(({ id }) => id);
  if (new Set(declarationIds).size !== declarationIds.length
      || new Set(shapeIds).size !== shapeIds.length) {
    throw new Error("IR or ABI-shape census contains duplicate declaration ids");
  }
}

async function validateEvidence(candidate, declaration, entry, headers) {
  for (const evidence of entry.evidence) {
    if (evidence.header !== declaration.header
        || typeof evidence.text !== "string") {
      throw new Error(`Base64-span evidence does not match census header for ${candidate.id}`);
    }

    let header = headers.get(evidence.header);
    if (!header) {
      header = await readFile(resolve(root, evidence.header), "utf8");
      headers.set(evidence.header, header);
    }
    const matches = header.split("\n")
      .map((line, index) => line.trim() === evidence.text.trim() ? index + 1 : 0)
      .filter(Boolean)
      .sort((left, right) => Math.abs(left - declaration.line) - Math.abs(right - declaration.line));
    if (matches.length === 0) {
      throw new Error(`Base64-span evidence drifted for ${candidate.id}`);
    }
    evidence.line = matches[0];
  }

  const documentsCapacity = entry.evidence.some(({ text }) => text.includes("dst_len[in,out]"));
  const documentsFailure = entry.evidence.some(({ text }) => text.includes("*dst_len = 0"));
  if (!documentsCapacity || !documentsFailure) {
    throw new Error(`Base64-span policy lacks bounded-capacity evidence for ${candidate.id}`);
  }
}

async function createEntries(selected, declarations, policy, headers) {
  const policiesBySemanticId = semanticEntryMap(policy.entries, "base64-span policy");
  const entries = [];
  const blocked = [];
  for (const candidate of selected) {
    const declaration = declarations.get(candidate.id);
    if (!declaration) throw new Error(`Base64-span candidate is absent from dmSDK IR: ${candidate.id}`);
    const entry = policiesBySemanticId.get(semanticDeclarationId(candidate.id));
    if (!entry) {
      blocked.push({ ...candidate, emitted: false, blocker: "unreviewed-base64-span-optimization" });
      continue;
    }
    if (entry.status !== "emit"
        || !["encode", "decode"].includes(entry.mode)
        || !Array.isArray(entry.evidence)
        || entry.evidence.length < 2) {
      throw new Error(`Invalid base64-span policy for ${candidate.id}`);
    }

    try {
      await validateEvidence(candidate, declaration, entry, headers);
    } catch (error) {
      blocked.push({ ...candidate, emitted: false, blocker: "base64-span-evidence-withdrawn", detail: error.message });
      continue;
    }
    entries.push({
      id: entries.length,
      candidate,
      declaration,
      mode: entry.mode,
      requirePaddedInput: entry.requirePaddedInput === true,
      evidence: entry.evidence,
      wrapper: `deherm_dmsdk_base64_span_${snake(declaration.name)}`,
    });
  }
  return { entries, blocked };
}

function createReport(contents, ir, shapes, policy, headers, entries, blocked, artifacts, selected) {
  return {
    schemaVersion: 1,
    policyVersion: policy.policyVersion,
    defoldRevision: ir.defoldRevision,
    sources: { ir: defaults.ir, shapes: defaults.shapes, policy: defaults.policy },
    sourceHashes: {
      ...Object.fromEntries(Object.entries(contents).map(([key, value]) => [key, sha256(value)])),
      headers: Object.fromEntries(
        [...headers]
          .sort(([left], [right]) => left.localeCompare(right))
          .map(([path, content]) => [path, sha256(content)]),
      ),
    },
    policy: {
      candidateSelector: policy.candidateSelector,
      cAbi: "const uint8_t* plus uint32_t input length; caller-owned uint8_t* plus explicit uint32_t capacity/output length",
      ownership: "both spans are borrowed only for the synchronous call; no pointer escapes",
      decode: "strict padded Base64 syntax is validated before calling the platform decoder",
      query: "zero output capacity preserves the documented size-query protocol but does not claim input validity",
      allocation: "generated glue has no heap primitive; the warmed harness observes zero C++ operator new calls, while native and Objective-C allocations are unmeasured",
      jsi: "not-generated pending typed-array lifetime and installer policy",
      html5: "not-claimed pending target compile/link matrix",
    },
    coverage: {
      baselineRuntimePending: shapes.coverage.runtimePending,
      discovered: selected.length,
      emitted: entries.length,
      policyBlocked: blocked.length,
      hostBehaviorVerified: entries.length,
      remainingWithoutGeneratedAdapters: shapes.coverage.runtimePending - 26 - 7 - 4 - entries.length,
    },
    artifactHashes: Object.fromEntries(
      [...artifacts]
        .sort(([left], [right]) => left.localeCompare(right))
        .map(([path, content]) => [path, sha256(content)]),
    ),
    artifacts: [...artifacts.keys()].sort(),
    declarations: [...entries.map(({
      id, candidate, mode, requirePaddedInput, evidence, wrapper,
    }) => ({
      ...candidate,
      bindingId: id,
      mode,
      requirePaddedInput,
      evidence,
      wrapper,
      stages: {
        generated: "complete",
        compiled: "packaged-sdk-object-test",
        linked: "packaged-sdk-host-link-test",
        runtime: "packaged-sdk-host-behavior-test",
        allocation: "100000-warmed-canonical-dispatch-zero-cpp-operator-new",
      },
    })), ...blocked],
  };
}

async function build(options) {
  const contents = await readInputs(options);
  const ir = JSON.parse(contents.ir);
  const shapes = JSON.parse(contents.shapes);
  const policy = JSON.parse(contents.policy);
  validateProvenance(ir, shapes, contents);

  const declarations = new Map(ir.declarations.map((declaration) => [declaration.id, declaration]));
  const selected = candidates(shapes, policy.candidateSelector);
  const headers = new Map();
  const { entries, blocked } = await createEntries(selected, declarations, policy, headers);
  const artifacts = new Map([
    ["defold/defold_hermes/include/defold_hermes/generated_dmsdk_base64_span.h", renderHeader(entries)],
    ["defold/defold_hermes/include/defold_hermes/generated_dmsdk_base64_span_runtime.h", renderRuntimeHeader()],
    ["defold/defold_hermes/src/generated_dmsdk_base64_span_crypt.cpp", renderSource(entries)],
    ["defold/defold_hermes/src/generated_dmsdk_base64_span_runtime.cpp", renderRuntime(entries)],
  ]);
  const report = createReport(contents, ir, shapes, policy, headers, entries, blocked, artifacts, selected);
  artifacts.set(
    "packages/bindings/generated/defold-dmsdk-base64-span-bindings.json",
    `${JSON.stringify(report, null, 2)}\n`,
  );
  return { artifacts, report };
}

async function writeOrCheck(outRoot, relative, content, check) {
  const path = resolve(outRoot, relative);
  if (check) {
    if (await readFile(path, "utf8") !== content) {
      throw new Error(`${relative} is stale`);
    }
    return;
  }

  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, content);
}

export async function run(argv = process.argv.slice(2)) {
  const options = parseArgs(argv);
  const { artifacts, report } = await build(options);
  for (const [path, content] of artifacts) {
    await writeOrCheck(options.outRoot, path, content, options.check);
  }
  process.stdout.write(`${options.check ? "Verified" : "Generated"} ${report.coverage.emitted}/${report.coverage.discovered} base64-span dmSDK bindings.\n`);
  return report;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  await run();
}
