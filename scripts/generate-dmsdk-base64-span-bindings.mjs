const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const defaults = {
  ir: "packages/bindings/generated/defold-sdk-ir.json",
  shapes: "packages/bindings/generated/defold-dmsdk-abi-shapes.json",
  sourceFacts: "packages/bindings/generated/defold-dmsdk-source-semantic-facts.json",
  plan: "packages/bindings/generated/defold-dmsdk-bounded-span-plan.json",
  policy: "packages/bindings/overrides/dmsdk-base64-span-bindings.json",
};

const sha256 = (value) => createHash("sha256").update(value).digest("hex");
const snake = (value) =>
  value
    .replace(/::/g, "_")
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .toLowerCase();

function parseArgs(argv) {
  const options = { ...defaults, outRoot: root, check: false };

  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === "--check") {
      options.check = true;
    } else if (["--ir", "--shapes", "--source-facts", "--plan", "--policy", "--out-root"].includes(argument)) {
      const key = argument.slice(2).replace(/-([a-z])/g, (_, character) => character.toUpperCase());
      options[key] = resolve(argv[++index]);
    } else {
      throw new Error(`Unknown argument ${argument}`);
    }
  }

  for (const key of Object.keys(defaults)) {
    options[key] = resolve(root, options[key]);
  }
  return options;
}

function renderHeader(entries) {
  const declarations = entries
    .map(
      ({ wrapper }) =>
        `uint8_t ${wrapper}(const uint8_t* input, uint32_t input_length, uint8_t* output, uint32_t* inout_output_length);`,
    )
    .join("\n");

  return `// Generated by scripts/generate-dmsdk-base64-span-bindings.mjs. Do not edit.\n#ifndef DEFOLD_HERMES_GENERATED_DMSDK_BASE64_SPAN_H\n#define DEFOLD_HERMES_GENERATED_DMSDK_BASE64_SPAN_H\n#include <stdint.h>\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n${declarations}\n#ifdef __cplusplus\n}\n#endif\n#endif\n`;
}

function renderSource(entries) {
  const includes = [...new Set(entries.map(({ declaration }) => publicDmSdkHeader(declaration.header)))]
    .sort()
    .map((header) => `#include <${header}>`)
    .join("\n");
  const wrappers = entries
    .map(
      ({ wrapper, declaration }) =>
        `uint8_t ${wrapper}(const uint8_t* input, uint32_t input_length, uint8_t* output, uint32_t* inout_output_length)\n{\n  if(inout_output_length==nullptr||(input_length!=0&&input==nullptr)||(*inout_output_length!=0&&output==nullptr))return UINT8_C(0); return ${declaration.name}(input, input_length, output, inout_output_length) ? UINT8_C(1) : UINT8_C(0);\n}`,
    )
    .join("\n");

  return `// Generated by scripts/generate-dmsdk-base64-span-bindings.mjs. Do not edit.\n#include <defold_hermes/generated_dmsdk_base64_span.h>\n${includes}\nextern \"C\" {\n${wrappers} }\n`;
}

function renderRuntimeHeader() {
  return `// Generated by scripts/generate-dmsdk-base64-span-bindings.mjs. Do not edit.\n#ifndef DEFOLD_HERMES_GENERATED_DMSDK_BASE64_SPAN_RUNTIME_H\n#define DEFOLD_HERMES_GENERATED_DMSDK_BASE64_SPAN_RUNTIME_H\n#include <stdint.h>\ntypedef enum DehermDmSdkBase64SpanStatus { DEHERM_DMSDK_BASE64_SPAN_OK=0, DEHERM_DMSDK_BASE64_SPAN_UNKNOWN_ID=1, DEHERM_DMSDK_BASE64_SPAN_NULL_STORAGE=2, DEHERM_DMSDK_BASE64_SPAN_QUERY=3, DEHERM_DMSDK_BASE64_SPAN_NONCANONICAL_INPUT=4, DEHERM_DMSDK_BASE64_SPAN_NATIVE_FAILURE=5 } DehermDmSdkBase64SpanStatus;\ntypedef struct DehermDmSdkBase64SpanDescriptor { uint16_t id; uint8_t requires_padded_input; const char* declaration_id; } DehermDmSdkBase64SpanDescriptor;\n#ifdef __cplusplus\nextern \"C\" {\n#endif\nuint32_t deherm_dmsdk_base64_span_count(void);\nconst DehermDmSdkBase64SpanDescriptor* deherm_dmsdk_base64_span_descriptors(void);\nDehermDmSdkBase64SpanStatus deherm_dmsdk_base64_span_dispatch(uint16_t id, const uint8_t* input, uint32_t input_length, uint8_t* output, uint32_t output_capacity, uint32_t* out_written);\n#ifdef __cplusplus\n}\n#endif\n#endif\n`;
}

function renderRuntime(entries) {
  const hasPaddedInputRequirement = entries.some(({ requirePaddedInput }) => requirePaddedInput);
  const validators = hasPaddedInputRequirement
    ? `uint8_t sextet(uint8_t value) {
  if (value >= 'A' && value <= 'Z') return value - 'A';
  if (value >= 'a' && value <= 'z') return value - 'a' + UINT8_C(26);
  if (value >= '0' && value <= '9') return value - '0' + UINT8_C(52);
  if (value == '+') return UINT8_C(62);
  if (value == '/') return UINT8_C(63);
  return UINT8_MAX;
}
bool canonical(const uint8_t* input, uint32_t length) {
  if ((length & UINT32_C(3)) != 0) return false;
  uint32_t padding = 0;
  if (length && input[length - 1] == '=') ++padding;
  if (length > 1 && input[length - 2] == '=') ++padding;
  if (padding > 2) return false;
  for (uint32_t index = 0; index < length - padding; ++index) {
    if (sextet(input[index]) == UINT8_MAX) return false;
  }
  for (uint32_t index = length - padding; index < length; ++index) {
    if (input[index] != '=') return false;
  }
  if (padding == 2 && (sextet(input[length - 3]) & UINT8_C(0x0f)) != 0) return false;
  if (padding == 1 && (sextet(input[length - 2]) & UINT8_C(0x03)) != 0) return false;
  return true;
}
`
    : "";
  const paddedInputGate = hasPaddedInputRequirement
    ? "  if (kDescriptors[id].requires_padded_input && !canonical(input,input_length)) return DEHERM_DMSDK_BASE64_SPAN_NONCANONICAL_INPUT;\n"
    : "";
  const descriptors = entries
    .map(
      ({ id, declaration, requirePaddedInput }) =>
        `  { UINT16_C(${id}), UINT8_C(${requirePaddedInput ? 1 : 0}), ${JSON.stringify(declaration.id)} }`,
    )
    .join(",\n");
  const cases = entries
    .map(({ id, wrapper }) => `    case ${id}: success=${wrapper}(input,input_length,output,&written); break;`)
    .join("\n");

  return `// Generated by scripts/generate-dmsdk-base64-span-bindings.mjs. Do not edit.\n#include <defold_hermes/generated_dmsdk_base64_span.h>\n#include <defold_hermes/generated_dmsdk_base64_span_runtime.h>\nnamespace {\n${validators}const DehermDmSdkBase64SpanDescriptor kDescriptors[] = {\n${descriptors}\n};\n}\nextern \"C\" {\nuint32_t deherm_dmsdk_base64_span_count(void) { return UINT32_C(${entries.length}); }\nconst DehermDmSdkBase64SpanDescriptor* deherm_dmsdk_base64_span_descriptors(void) { return kDescriptors; }\nDehermDmSdkBase64SpanStatus deherm_dmsdk_base64_span_dispatch(uint16_t id, const uint8_t* input, uint32_t input_length, uint8_t* output, uint32_t output_capacity, uint32_t* out_written) {\n  if (id >= deherm_dmsdk_base64_span_count()) return DEHERM_DMSDK_BASE64_SPAN_UNKNOWN_ID;\n  if (out_written == nullptr || (input_length != 0 && input == nullptr) || (output_capacity != 0 && output == nullptr)) return DEHERM_DMSDK_BASE64_SPAN_NULL_STORAGE;\n${paddedInputGate}  uint32_t written=output_capacity; uint8_t success=0;\n  switch (id) {\n${cases}\n    default: return DEHERM_DMSDK_BASE64_SPAN_UNKNOWN_ID;\n  }\n  *out_written=written;\n  if (output_capacity == 0) return DEHERM_DMSDK_BASE64_SPAN_QUERY;\n  return success ? DEHERM_DMSDK_BASE64_SPAN_OK : DEHERM_DMSDK_BASE64_SPAN_NATIVE_FAILURE;\n}\n}\n`;
}

async function readInputs(options) {
  return Object.fromEntries(
    await Promise.all(Object.keys(defaults).map(async (key) => [key, await readFile(options[key], "utf8")])),
  );
}

function validateProvenance(ir, shapes, contents) {
  if (ir.defoldRevision !== shapes.defoldRevision) {
    throw new Error("Defold revisions differ between IR and ABI-shape census");
  }
  if (sha256(contents.ir) !== shapes.sourceHashes.ir) {
    throw new Error("IR hash does not match ABI-shape census provenance");
  }

  const declarationIds = ir.declarations.map(({ id }) => id);
  const shapeIds = shapes.rows.map(({ id }) => id);
  if (new Set(declarationIds).size !== declarationIds.length || new Set(shapeIds).size !== shapeIds.length) {
    throw new Error("IR or ABI-shape census contains duplicate declaration ids");
  }
}

export function extractBase64SpanSemantics(declaration, candidate, recipe, sourceFacts) {
  return analyzeBase64SpanRecipe(declaration, candidate, recipe, sourceFacts).semantics;
}

function createEntries(rows, declarations, planById) {
  const patterns = [base64SpanPattern(), DMSDK_UNIVERSAL_FALLBACK_PATTERN];
  const entries = [];
  const blocked = [];
  let structurallyEligible = 0;
  for (const candidate of [...rows].sort((left, right) => left.id.localeCompare(right.id))) {
    const decision = planById.get(candidate.id);
    if (!decision?.structuralCandidates.includes("span.bounded-byte-transform")) continue;
    structurallyEligible += 1;
    const declaration = declarations.get(candidate.id);
    if (!declaration) throw new Error(`Base64-span candidate is absent from dmSDK IR: ${candidate.id}`);
    const semantics = decision.patternId === "span.bounded-byte-transform" ? decision.semantics : null;
    if (decision.patternId !== "span.bounded-byte-transform") {
      blocked.push({
        ...candidate,
        emitted: false,
        blocker: "base64-span-evidence-withdrawn",
        patternDecision: decision.patternId,
        fallbackAudit: createDmSdkFallbackAudit({
          candidate,
          family: "base64-span",
          patternId: "span.bounded-byte-transform",
          emitter: "scripts/generate-dmsdk-base64-span-bindings.mjs",
          missingFacts: decision.missingFacts,
        }),
      });
      continue;
    }
    entries.push({
      id: entries.length,
      candidate,
      declaration,
      mode: semantics.mode,
      requirePaddedInput: semantics.requirePaddedInput,
      evidence: semantics.evidence,
      patternDecision: decision.patternId,
      wrapper: `deherm_dmsdk_base64_span_${snake(declaration.name)}`,
    });
  }
  return { entries, blocked, structurallyEligible, patterns };
}

function createReport(contents, ir, shapes, policy, entries, blocked, structurallyEligible, patterns, artifacts) {
  return {
    schemaVersion: 1,
    policyVersion: policy.policyVersion,
    defoldRevision: ir.defoldRevision,
    sources: defaults,
    sourceHashes: {
      ...Object.fromEntries(Object.entries(contents).map(([key, value]) => [key, sha256(value)])),
    },
    policy: {
      recipe: policy.recipe,
      patternRegistry: patterns.map(({ id, family, emitter, priority, cost, fallback, when }) => ({
        id,
        family,
        emitter,
        priority,
        cost,
        fallback,
        when,
      })),
      cAbi: "const uint8_t* plus uint32_t input length; caller-owned uint8_t* plus explicit uint32_t capacity/output length",
      ownership: "both spans are borrowed only for the synchronous call; no pointer escapes",
      decode: "unpadded-input support is derived from the revision implementation; otherwise glue conservatively requires canonical padding",
      query: "zero output capacity preserves the documented size-query protocol but does not claim input validity",
      allocation:
        "generated glue has no heap primitive; the warmed harness observes zero C++ operator new calls, while native and Objective-C allocations are unmeasured",
      jsi: "not-generated pending typed-array lifetime and installer policy",
      html5: "not-claimed pending target compile/link matrix",
    },
    coverage: {
      baselineRuntimePending: shapes.coverage.runtimePending,
      discovered: structurallyEligible,
      structurallyEligible,
      emitted: entries.length,
      policyBlocked: blocked.length,
      hostBehaviorVerified: entries.length,
      remainingWithoutGeneratedAdapters: shapes.coverage.runtimePending - 26 - 7 - 4 - entries.length,
    },
    artifactHashes: Object.fromEntries(
      [...artifacts]
        .sort(([left], [right]) => left.localeCompare(right))
        .map(([path, content]) => [path, sha256(content)]),
    ),
    artifacts: [...artifacts.keys()].sort(),
    fallbackAudit: {
      retainedImplementation: "@deherm/compiler/dmsdk-universal-materializer",
      count: blocked.length,
      entries: blocked.map(({ fallbackAudit }) => fallbackAudit),
    },
    declarations: [
      ...entries.map(({ id, candidate, mode, requirePaddedInput, evidence, patternDecision, wrapper }) => ({
        ...candidate,
        bindingId: id,
        mode,
        requirePaddedInput,
        evidence,
        patternDecision,
        wrapper,
        stages: {
          generated: "complete",
          compiled: "packaged-sdk-object-test",
          linked: "packaged-sdk-host-link-test",
          runtime: "packaged-sdk-host-behavior-test",
          allocation: "100000-warmed-canonical-dispatch-zero-cpp-operator-new",
        },
      })),
      ...blocked,
    ],
  };
}

async function build(options) {
  const contents = await readInputs(options);
  const ir = JSON.parse(contents.ir);
  const shapes = JSON.parse(contents.shapes);
  const plan = JSON.parse(contents.plan);
  const policy = JSON.parse(contents.policy);
  validateProvenance(ir, shapes, contents);
  const planById = indexDmSdkBoundedSpanPlan(plan, {
    revision: ir.defoldRevision,
    sourceHashes: {
      ir: sha256(contents.ir),
      shapes: sha256(contents.shapes),
      sourceFacts: sha256(contents.sourceFacts),
      base64: sha256(contents.policy),
    },
  });

  const declarations = new Map(ir.declarations.map((declaration) => [declaration.id, declaration]));
  if (
    policy.schemaVersion !== 1 ||
    policy.policyVersion !== "base64-span-v5" ||
    policy.family !== "bounded-byte-transform" ||
    policy.recipe?.input !== "borrowed-counted-bytes" ||
    policy.recipe?.output !== "caller-owned-capacity-inout" ||
    policy.recipe?.decodeInput !== "derive-from-implementation" ||
    policy.recipe?.sizeQuery !== "zero-output-capacity" ||
    policy.recipe?.ownership !== "synchronous-noescape" ||
    policy.recipe?.fallback !== "universal-recipe"
  ) {
    throw new Error("Unsupported base64-span semantic policy");
  }
  const { entries, blocked, structurallyEligible, patterns } = createEntries(
    shapes.rows,
    declarations,
    planById,
  );
  const artifacts = new Map([
    ["defold/defold_hermes/include/defold_hermes/generated_dmsdk_base64_span.h", renderHeader(entries)],
    ["defold/defold_hermes/include/defold_hermes/generated_dmsdk_base64_span_runtime.h", renderRuntimeHeader()],
    ["defold/defold_hermes/src/generated_dmsdk_base64_span_crypt.cpp", renderSource(entries)],
    ["defold/defold_hermes/src/generated_dmsdk_base64_span_runtime.cpp", renderRuntime(entries)],
  ]);
  const report = createReport(
    contents,
    ir,
    shapes,
    policy,
    entries,
    blocked,
    structurallyEligible,
    patterns,
    artifacts,
  );
  artifacts.set(
    "packages/bindings/generated/defold-dmsdk-base64-span-bindings.json",
    `${JSON.stringify(report, null, 2)}\n`,
  );
  return { artifacts, report };
}

async function writeOrCheck(outRoot, relative, content, check) {
  const path = resolve(outRoot, relative);
  if (check) {
    if ((await readFile(path, "utf8")) !== content) {
      throw new Error(`${relative} is stale`);
    }
    return;
  }

  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, content);
}

export async function run(argv = process.argv.slice(2)) {
  const options = parseArgs(argv);
  const { artifacts, report } = await build(options);
  for (const [path, content] of artifacts) {
    await writeOrCheck(options.outRoot, path, content, options.check);
  }
  process.stdout.write(
    `${options.check ? "Verified" : "Generated"} ${report.coverage.emitted}/${report.coverage.discovered} base64-span dmSDK bindings.\n`,
  );
  return report;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  await run();
}
