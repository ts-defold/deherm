#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const integrationDirectory = dirname(fileURLToPath(import.meta.url));
const exampleDirectory = resolve(integrationDirectory, "..");
const repositoryDirectory = resolve(exampleDirectory, "../..");
const outputPath = resolve(exampleDirectory, "defold/src/capability-snapshot.ts");
const manifestPath = resolve(exampleDirectory, "defold/.deherm/generated/components/manifest.json");
const gatePath = resolve(repositoryDirectory, ".agents/docs/data/war-battles-runtime-gate.json");

const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
const gate = JSON.parse(await readFile(gatePath, "utf8"));
const proxy = manifest.proxyRuntimeCapability ?? {};
const requirementsEngineVerified = Array.isArray(gate.requirements) &&
  gate.requirements.every((requirement) => requirement.engineContextVerified === true);
const generated = `// @generated by integration/generate-capability-snapshot.mjs; DO NOT EDIT.\n` +
  `// This checked source consumes the current generated reports without loading JSON in Defold.\n` +
  `export const COMPONENT_PROXY_CAPABILITY = Object.freeze({\n` +
  `  source: "examples/war-battles-online/defold/.deherm/generated/components/manifest.json",\n` +
  `  state: ${JSON.stringify(proxy.state ?? "unknown")},\n` +
  `  runtimeConformant: ${proxy.runtimeConformant === true},\n` +
  `});\n\n` +
  `export const WAR_BATTLES_ENGINE_CAPABILITY = Object.freeze({\n` +
  `  source: ".agents/docs/data/war-battles-runtime-gate.json",\n` +
  `  status: ${JSON.stringify(gate.status ?? "unknown")},\n` +
  `  gameplayExecutionObserved: ${gate.gameplayExecutionObserved === true},\n` +
  `  requirementsEngineVerified: ${requirementsEngineVerified},\n` +
  `  meaning: "generated routes and proxy conformance do not imply packaged-engine gameplay proof",\n` +
  `});\n\n` +
  `export const DEFOLD_ATTACHMENT_ALLOWED =\n` +
  `  COMPONENT_PROXY_CAPABILITY.runtimeConformant &&\n` +
  `  WAR_BATTLES_ENGINE_CAPABILITY.gameplayExecutionObserved &&\n` +
  `  WAR_BATTLES_ENGINE_CAPABILITY.requirementsEngineVerified;\n`;

if (process.argv.includes("--check")) {
  const checked = await readFile(outputPath, "utf8");
  if (checked !== generated) throw new Error("capability snapshot is stale; rerun without --check");
  process.stdout.write("Capability snapshot fresh\n");
} else {
  await writeFile(outputPath, generated);
  process.stdout.write("Capability snapshot generated\n");
}
