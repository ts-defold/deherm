import { mkdir, readFile, readdir, rename, unlink, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const exampleRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputRoot = resolve(exampleRoot, "defold/src/generated-war-battles");
const check = process.argv.includes("--check");

const sources = [
  ["core/arena.ts", "arena.ts"],
  ["core/arena-visual.ts", "arena-visual.ts"],
  ["core/bots.ts", "bots.ts"],
  ["core/camera-framing.ts", "camera-framing.ts"],
  ["core/browser-webtransport.ts", "browser-webtransport.ts"],
  ["core/browser-websocket.ts", "browser-websocket.ts"],
  ["core/client.ts", "client.ts"],
  ["core/constants.ts", "constants.ts"],
  ["core/content.ts", "content.ts"],
  ["core/events.ts", "events.ts"],
  ["core/fixed.ts", "fixed.ts"],
  ["core/hex-cliffs.ts", "hex-cliffs.ts"],
  ["core/hex-landscape.ts", "hex-landscape.ts"],
  ["core/isometric-direction.ts", "isometric-direction.ts"],
  ["core/isometric-projection.ts", "isometric-projection.ts"],
  ["core/playable.ts", "playable.ts"],
  ["core/protocol.ts", "protocol.ts"],
  ["core/remote-lifecycle.ts", "remote-lifecycle.ts"],
  ["core/snapshot.ts", "snapshot.ts"],
  ["core/ticks.ts", "ticks.ts"],
  ["core/transport.ts", "transport.ts"],
  ["core/virtual-controls.ts", "virtual-controls.ts"],
  ["core/webtransport-framing.ts", "webtransport-framing.ts"],
  ["core/world.ts", "world.ts"],
  ["core/world-plan.ts", "world-plan.ts"],
  ["core/world-visual-footprints.ts", "world-visual-footprints.ts"],
  ["integration/transport-selection.ts", "transport-selection.ts"],
];

const generated = new Map();
for (const [sourceRelative, outputRelative] of sources) {
  const source = await readFile(resolve(exampleRoot, sourceRelative), "utf8");
  generated.set(
    outputRelative,
    `// Generated by integration/sync-defold-sources.mjs from ${sourceRelative}. Do not edit.\n` +
      source.replace(/(from\s+["']\.\/[^"']+)\.ts(["'])/g, "$1$2"),
  );
}

generated.set(
  "index.ts",
  [
    "// Generated by integration/sync-defold-sources.mjs. Do not edit.",
    'export * from "./arena";',
    'export * from "./arena-visual";',
    'export * from "./bots";',
    'export * from "./camera-framing";',
    'export * from "./browser-webtransport";',
    'export * from "./browser-websocket";',
    'export * from "./client";',
    'export * from "./constants";',
    'export * from "./content";',
    'export * from "./events";',
    'export * from "./fixed";',
    'export * from "./hex-cliffs";',
    'export * from "./hex-landscape";',
    'export * from "./isometric-direction";',
    'export * from "./isometric-projection";',
    'export * from "./playable";',
    'export * from "./protocol";',
    'export * from "./remote-lifecycle";',
    'export * from "./ticks";',
    'export * from "./transport";',
    'export * from "./virtual-controls";',
    'export * from "./webtransport-framing";',
    'export * from "./world";',
    'export * from "./world-plan";',
    "",
  ].join("\n"),
);

// This directory belongs entirely to this mirror. Prune only files with our
// exact generated header, so a removed source cannot leave stale imports in
// Defold while an unexpected hand-authored file still fails closed.
for (const relative of await readdir(outputRoot)) {
  if (!relative.endsWith(".ts") || generated.has(relative)) continue;
  const target = resolve(outputRoot, relative);
  const actual = await readFile(target, "utf8");
  if (!actual.startsWith("// Generated by integration/sync-defold-sources.mjs")) {
    throw new Error(`${relative}: unexpected hand-authored file in generated source directory`);
  }
  if (check) throw new Error(`${relative}: obsolete generated Defold source remains`);
  await unlink(target);
}

for (const [relative, expected] of generated) {
  const target = resolve(outputRoot, relative);
  let actual;
  try {
    actual = await readFile(target, "utf8");
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
  if (check) {
    if (actual === undefined) throw new Error(`${relative}: generated Defold source is missing`);
    if (actual !== expected) throw new Error(`${relative}: generated Defold source is stale`);
  } else if (actual !== expected) {
    await mkdir(dirname(target), { recursive: true });
    // Atomic replacement means the dev compiler sees either the complete old
    // module or the complete new one. A no-op source never touches mtime, so
    // watch mode does not rebuild the entire mirror after one core edit.
    const temporary = `${target}.tmp-${process.pid}`;
    await writeFile(temporary, expected);
    await rename(temporary, target);
  }
}

console.log(
  check ? `${generated.size} generated Defold sources are fresh` : `wrote ${generated.size} generated Defold sources`,
);
