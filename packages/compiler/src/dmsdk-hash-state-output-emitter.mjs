export const DMSDK_HASH_STATE_RECIPE_FACTS_KIND = "deherm.dmsdk-hash-state-recipe-facts";
export const DMSDK_HASH_STATE_RECIPE_FACTS_SCHEMA_VERSION = 1;
export const DMSDK_HASH_STATE_OUTPUTS = Object.freeze({
  header: "defold/defold_hermes/include/defold_hermes/generated_dmsdk_hash_state.h",
  source: "defold/defold_hermes/src/generated_dmsdk_hash_state.cpp",
  exact: "tests/fixtures/generated_dmsdk_hash_state_exact.cpp",
});

const compare = (left, right) => (left < right ? -1 : left > right ? 1 : 0);
function publicHeader(source) {
  const marker = "/src/dmsdk/";
  const position = source.indexOf(marker);
  if (position < 0) throw new Error(`hash-state header is outside the dmSDK projection: ${source}`);
  return `dmsdk/${source.slice(position + marker.length)}`;
}
function normalize(facts) {
  if (facts?.schemaVersion !== 1 || facts?.kind !== DMSDK_HASH_STATE_RECIPE_FACTS_KIND || !Array.isArray(facts.entries))
    throw new Error("invalid dmSDK hash-state recipe facts");
  return facts;
}
export function createDmSdkHashStateRecipeFacts({ defoldRevision, entries, capacityPerWidth }) {
  return normalize({
    schemaVersion: 1,
    kind: DMSDK_HASH_STATE_RECIPE_FACTS_KIND,
    defoldRevision,
    capacityPerWidth,
    entries: entries.map(({ denseId, operation, width, stateType, symbol, id, evidence }) => ({
      denseId,
      operation,
      width,
      stateType,
      symbol,
      declarationId: id,
      include: publicHeader(evidence.header),
    })),
  });
}
const renderedIncludes = (entries) =>
  [...new Set(entries.map(({ include }) => include))]
    .sort(compare)
    .map((header) => `#include <${header}>`)
    .join("\n");
function renderHeader(entries, capacity) {
  const rows = entries
    .map(
      (entry) =>
        `  DEHERM_DMSDK_HASH_STATE_${entry.operation.replace(/([a-z])([A-Z])/g, "$1_$2").toUpperCase()}_${entry.width} = ${entry.denseId},`,
    )
    .join("\n");
  return `// Generated by scripts/generate-dmsdk-hash-state-bindings.mjs. Do not edit.\n#ifndef DEFOLD_HERMES_GENERATED_DMSDK_HASH_STATE_H\n#define DEFOLD_HERMES_GENERATED_DMSDK_HASH_STATE_H\n#include <stdint.h>\n#define DEHERM_DMSDK_HASH_STATE_CAPACITY_PER_WIDTH UINT32_C(${capacity})\ntypedef enum DehermDmSdkHashStateStatus { DEHERM_DMSDK_HASH_STATE_OK=0, DEHERM_DMSDK_HASH_STATE_UNKNOWN_ID=1, DEHERM_DMSDK_HASH_STATE_NULL_STORAGE=2, DEHERM_DMSDK_HASH_STATE_INVALID_HANDLE=3, DEHERM_DMSDK_HASH_STATE_CAPACITY_EXHAUSTED=4, DEHERM_DMSDK_HASH_STATE_INVALID_ARGUMENT=5, DEHERM_DMSDK_HASH_STATE_REENTRANT=6 } DehermDmSdkHashStateStatus;\ntypedef enum DehermDmSdkHashStateId {\n${rows}\n} DehermDmSdkHashStateId;\ntypedef struct DehermDmSdkHashStateDescriptor { uint16_t id; uint8_t width; uint8_t consumes; const char* operation; const char* declaration_id; } DehermDmSdkHashStateDescriptor;\n#ifdef __cplusplus\nextern "C" {\n#endif\nuint32_t deherm_dmsdk_hash_state_count(void);\nconst DehermDmSdkHashStateDescriptor* deherm_dmsdk_hash_state_descriptors(void);\nDehermDmSdkHashStateStatus deherm_dmsdk_hash_state_dispatch(uint16_t id, uint64_t handle, const uint8_t* input, uint32_t input_length, uint8_t reverse_hash, uint64_t* out_value);\n#ifdef __cplusplus\n}\n#endif\n#endif\n`;
}
function renderSource(entries, capacity) {
  const stateTypes = new Map(entries.map(({ width, stateType }) => [width, stateType]));
  const stateSlots = [...stateTypes]
    .sort(([a], [b]) => a - b)
    .map(([width, state]) => `Slot<${state}> g${width}[kCapacity];`)
    .join("");
  const descriptors = entries
    .map(
      (e) =>
        `  {UINT16_C(${e.denseId}),UINT8_C(${e.width}),UINT8_C(${["Final", "Release"].includes(e.operation) ? 1 : 0}),${JSON.stringify(e.operation)},${JSON.stringify(e.declarationId)}}`,
    )
    .join(",\n");
  const cases = entries
    .map((e) => {
      const p = e.width === 32 ? "g32" : "g64";
      const type = e.stateType;
      if (e.operation === "Init")
        return `case ${e.denseId}:{if(handle||input||input_length||reverse_hash>UINT8_C(1))return DEHERM_DMSDK_HASH_STATE_INVALID_ARGUMENT;Slot<${type}>* slot=allocate(${p},${e.width});if(!slot)return DEHERM_DMSDK_HASH_STATE_CAPACITY_EXHAUSTED;${e.symbol}(&slot->state,reverse_hash!=0);*out_value=token(*slot,${e.width});return DEHERM_DMSDK_HASH_STATE_OK;}`;
      if (e.operation === "Clone")
        return `case ${e.denseId}:{if(input||input_length||reverse_hash>UINT8_C(1))return DEHERM_DMSDK_HASH_STATE_INVALID_ARGUMENT;Slot<${type}>* source=find(${p},handle,${e.width});if(!source)return DEHERM_DMSDK_HASH_STATE_INVALID_HANDLE;Slot<${type}>* destination=allocate(${p},${e.width});if(!destination)return DEHERM_DMSDK_HASH_STATE_CAPACITY_EXHAUSTED;${e.symbol}(&destination->state,&source->state,reverse_hash!=0);*out_value=token(*destination,${e.width});return DEHERM_DMSDK_HASH_STATE_OK;}`;
      if (e.operation === "UpdateBuffer")
        return `case ${e.denseId}:{if(reverse_hash)return DEHERM_DMSDK_HASH_STATE_INVALID_ARGUMENT;Slot<${type}>* slot=find(${p},handle,${e.width});if(!slot)return DEHERM_DMSDK_HASH_STATE_INVALID_HANDLE;if(input_length>UINT32_C(0x7fffffff)||(input_length&&input==nullptr))return DEHERM_DMSDK_HASH_STATE_INVALID_ARGUMENT;${e.symbol}(&slot->state,input,input_length);return DEHERM_DMSDK_HASH_STATE_OK;}`;
      if (e.operation === "Final")
        return `case ${e.denseId}:{if(input||input_length||reverse_hash)return DEHERM_DMSDK_HASH_STATE_INVALID_ARGUMENT;Slot<${type}>* slot=find(${p},handle,${e.width});if(!slot)return DEHERM_DMSDK_HASH_STATE_INVALID_HANDLE;*out_value=${e.symbol}(&slot->state);consume(*slot);return DEHERM_DMSDK_HASH_STATE_OK;}`;
      return `case ${e.denseId}:{if(input||input_length||reverse_hash)return DEHERM_DMSDK_HASH_STATE_INVALID_ARGUMENT;Slot<${type}>* slot=find(${p},handle,${e.width});if(!slot)return DEHERM_DMSDK_HASH_STATE_INVALID_HANDLE;${e.symbol}(&slot->state);consume(*slot);return DEHERM_DMSDK_HASH_STATE_OK;}`;
    })
    .join("\n");
  return `// Generated by scripts/generate-dmsdk-hash-state-bindings.mjs. Do not edit.\n#include <defold_hermes/generated_dmsdk_hash_state.h>\n${renderedIncludes(entries)}\n#include <atomic>\n#include <stddef.h>\nnamespace {\nconstexpr uint64_t kMagic=UINT64_C(0xd348);constexpr uint32_t kCapacity=${capacity};constexpr uint32_t kMaxGeneration=UINT32_C(0x7fffffff);\ntemplate<class T> struct Slot{T state;uint32_t generation=1;uint16_t index=0;bool live=false;bool retired=false;};\n${stateSlots}std::atomic_flag g_lock=ATOMIC_FLAG_INIT;thread_local bool g_active=false;\nstruct Guard{bool locked=false;Guard(){if(g_active)return;g_active=true;while(g_lock.test_and_set(std::memory_order_acquire)){}locked=true;}~Guard(){if(locked){g_lock.clear(std::memory_order_release);g_active=false;}}};\ntemplate<class T> Slot<T>* allocate(Slot<T>(&slots)[kCapacity],uint32_t){for(uint16_t i=0;i<kCapacity;++i){auto& s=slots[i];s.index=i;if(!s.live&&!s.retired){s.live=true;return &s;}}return nullptr;}\ntemplate<class T> uint64_t token(const Slot<T>& slot,uint32_t width){return (kMagic<<48)|(uint64_t(width==64)<<47)|(uint64_t(slot.generation)<<16)|slot.index;}\ntemplate<class T> Slot<T>* find(Slot<T>(&slots)[kCapacity],uint64_t value,uint32_t width){if((value>>48)!=kMagic||((value>>47)&1)!=(width==64))return nullptr;const uint16_t index=uint16_t(value);const uint32_t generation=uint32_t((value>>16)&kMaxGeneration);if(index>=kCapacity)return nullptr;auto& slot=slots[index];return slot.live&&!slot.retired&&slot.generation==generation?&slot:nullptr;}\ntemplate<class T> void consume(Slot<T>& slot){slot.live=false;if(slot.generation==kMaxGeneration)slot.retired=true;else ++slot.generation;}\nconst DehermDmSdkHashStateDescriptor kDescriptors[]={\n${descriptors}\n};}\nextern "C" {\nuint32_t deherm_dmsdk_hash_state_count(void){return UINT32_C(${entries.length});}\nconst DehermDmSdkHashStateDescriptor* deherm_dmsdk_hash_state_descriptors(void){return kDescriptors;}\nDehermDmSdkHashStateStatus deherm_dmsdk_hash_state_dispatch(uint16_t id,uint64_t handle,const uint8_t* input,uint32_t input_length,uint8_t reverse_hash,uint64_t* out_value){if(out_value==nullptr)return DEHERM_DMSDK_HASH_STATE_NULL_STORAGE;*out_value=0;if(id>=deherm_dmsdk_hash_state_count())return DEHERM_DMSDK_HASH_STATE_UNKNOWN_ID;Guard guard;if(!guard.locked)return DEHERM_DMSDK_HASH_STATE_REENTRANT;switch(id){${cases}default:return DEHERM_DMSDK_HASH_STATE_UNKNOWN_ID;}}}\n`;
}
function renderExact(entries) {
  const bodies = entries
    .map((entry) => {
      const { denseId: id, operation: op, width, stateType: state } = entry;
      if (op === "Init")
        return `void ${entry.symbol}(${state}* s,bool r){++calls[${id}];uint${width}_t value=r?${width}:${width === 32 ? 3 : 6};std::memset(static_cast<void*>(s),0,sizeof(*s));std::memcpy(static_cast<void*>(s),&value,sizeof(value));}`;
      if (op === "Clone")
        return `void ${entry.symbol}(${state}* d,const ${state}* s,bool r){++calls[${id}];uint${width}_t value=0;std::memcpy(&value,static_cast<const void*>(s),sizeof(value));value+=r?${width === 32 ? 7 : 9}:1;std::memset(static_cast<void*>(d),0,sizeof(*d));std::memcpy(static_cast<void*>(d),&value,sizeof(value));}`;
      if (op === "UpdateBuffer")
        return `void ${entry.symbol}(${state}* s,const void* p,uint32_t n){++calls[${id}];uint${width}_t value=0;std::memcpy(&value,static_cast<const void*>(s),sizeof(value));const auto* b=(const uint8_t*)p;for(uint32_t i=0;i<n;++i)value+=b[i];std::memcpy(static_cast<void*>(s),&value,sizeof(value));}`;
      if (op === "Final")
        return `uint${width}_t ${entry.symbol}(${state}* s){++calls[${id}];uint${width}_t value=0;std::memcpy(&value,static_cast<const void*>(s),sizeof(value));return value;}`;
      return `void ${entry.symbol}(${state}*){++calls[${id}];}`;
    })
    .join("\n");
  return `// Generated exact ABI twin for the dmHash state family. Do not edit.\n${renderedIncludes(entries)}\n#include <cstring>\n#include <stdint.h>\nnamespace {uint32_t calls[${Math.max(1, entries.length)}]{};}\n${bodies}\nextern "C" uint32_t deherm_dmsdk_hash_state_exact_calls(uint16_t id){return id<${entries.length}?calls[id]:0;}\n`;
}
export function renderDmSdkHashStateOutputs(recipeFacts) {
  const facts = normalize(recipeFacts);
  return new Map([
    [DMSDK_HASH_STATE_OUTPUTS.header, renderHeader(facts.entries, facts.capacityPerWidth)],
    [DMSDK_HASH_STATE_OUTPUTS.source, renderSource(facts.entries, facts.capacityPerWidth)],
    [DMSDK_HASH_STATE_OUTPUTS.exact, renderExact(facts.entries)],
  ]);
}
