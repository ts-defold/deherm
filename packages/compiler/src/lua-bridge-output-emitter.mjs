/** Package-owned renderer for the deterministic Lua stack compatibility bridge. */
export const LUA_BRIDGE_FACTS = "defold-lua-bridge-recipe-facts.json";

const TYPES = Object.freeze({
  bool: { cpp: "bool", push: "pushBoolean", read: "readBoolean" },
  u32: { cpp: "uint32_t", push: "pushU32", read: "readU32" },
  f64: { cpp: "double", push: "pushF64", read: "readF64" },
  void: { cpp: "void" },
  callback: { cpp: "Handle", push: "pushTimerCallback" },
});
const IDENTIFIER = /^[A-Za-z_][A-Za-z0-9_]*$/u;
const BANNER = "Generated by scripts/generate-lua-bridge.mjs. Do not edit.";

function fail(path, message) {
  throw new Error(`${path}: ${message}`);
}

function pascal(value) {
  return value.replace(/(^|[^A-Za-z0-9])([A-Za-z0-9])/gu, (_, __, character) => character.toUpperCase());
}

function enumName(module, fn) {
  return `${pascal(module.name)}${pascal(fn.name)}`;
}

function thunkName(module, fn) {
  return `${module.name[0].toLowerCase()}${module.name.slice(1)}${pascal(fn.name)}`;
}

export function projectLuaBridgeFacts(input) {
  const schema = structuredClone(input);
  if (!schema || schema.schemaVersion !== 1) fail("schemaVersion", "expected version 1");
  if (!Number.isInteger(schema.stackReserve) || schema.stackReserve < 8) {
    fail("stackReserve", "expected an integer of at least 8");
  }
  if (!Array.isArray(schema.modules)) fail("modules", "expected an array");
  const ids = new Set();
  const modules = schema.modules.map((module, moduleIndex) => {
    const path = `modules[${moduleIndex}]`;
    if (!IDENTIFIER.test(module.name)) fail(`${path}.name`, "expected an identifier");
    if (typeof module.luaModule !== "string" || !module.luaModule) {
      fail(`${path}.luaModule`, "expected a Lua module name");
    }
    if (!Array.isArray(module.functions)) fail(`${path}.functions`, "expected an array");
    const functions = module.functions.map((fn, functionIndex) => {
      const functionPath = `${path}.functions[${functionIndex}]`;
      if (!IDENTIFIER.test(fn.name)) fail(`${functionPath}.name`, "expected an identifier");
      if (typeof fn.luaFunction !== "string" || !fn.luaFunction) {
        fail(`${functionPath}.luaFunction`, "expected a Lua function name");
      }
      if (!Array.isArray(fn.parameters)) fail(`${functionPath}.parameters`, "expected an array");
      if (!TYPES[fn.returns]) fail(`${functionPath}.returns`, `unsupported type ${fn.returns}`);
      const id = `${module.name}.${fn.name}`;
      if (ids.has(id)) fail(functionPath, `duplicate function ${id}`);
      ids.add(id);
      const parameters = fn.parameters.map((parameter, parameterIndex) => {
        if (!IDENTIFIER.test(parameter.name)) {
          fail(`${functionPath}.parameters[${parameterIndex}].name`, "expected an identifier");
        }
        if (!TYPES[parameter.type] || parameter.type === "void") {
          fail(`${functionPath}.parameters[${parameterIndex}].type`, `unsupported type ${parameter.type}`);
        }
        if (parameter.type === "callback") {
          const repeating = fn.parameters.find(({ name }) => name === parameter.repeatingParameter);
          if (!repeating || repeating.type !== "bool") {
            fail(
              `${functionPath}.parameters[${parameterIndex}].repeatingParameter`,
              "expected the name of a boolean parameter",
            );
          }
        }
        return {
          name: parameter.name,
          type: parameter.type,
          ...(parameter.repeatingParameter === undefined ? {} : { repeatingParameter: parameter.repeatingParameter }),
        };
      });
      if (fn.timerOperation === "delay" && fn.returns !== "u32") {
        fail(`${functionPath}.returns`, "timer delay must return u32");
      }
      if (fn.timerOperation === "cancel" && fn.returns !== "bool") {
        fail(`${functionPath}.returns`, "timer cancel must return bool");
      }
      return {
        name: fn.name,
        luaFunction: fn.luaFunction,
        parameters,
        returns: fn.returns,
        ...(fn.timerOperation === undefined ? {} : { timerOperation: fn.timerOperation }),
      };
    });
    return { name: module.name, luaModule: module.luaModule, functions };
  });
  return { schemaVersion: 1, stackReserve: schema.stackReserve, modules };
}

export function validateLuaBridgeFacts(facts) {
  if (!facts || facts.schemaVersion !== 1 || !Number.isInteger(facts.stackReserve) || facts.stackReserve < 8) {
    fail("facts", "expected Lua bridge recipe facts v1");
  }
  if (!Array.isArray(facts.modules)) fail("modules", "expected an array");
  const names = new Set();
  for (const [moduleIndex, module] of facts.modules.entries()) {
    const path = `modules[${moduleIndex}]`;
    if (!IDENTIFIER.test(module.name) || names.has(module.name)) fail(`${path}.name`, "expected unique identifier");
    names.add(module.name);
    if (typeof module.luaModule !== "string" || !module.luaModule || !Array.isArray(module.functions)) {
      fail(path, "invalid Lua module facts");
    }
    const functions = new Set();
    for (const [functionIndex, fn] of module.functions.entries()) {
      const functionPath = `${path}.functions[${functionIndex}]`;
      if (
        !IDENTIFIER.test(fn.name) ||
        functions.has(fn.name) ||
        typeof fn.luaFunction !== "string" ||
        !fn.luaFunction
      ) {
        fail(functionPath, "invalid or duplicate function facts");
      }
      functions.add(fn.name);
      if (!Array.isArray(fn.parameters) || !TYPES[fn.returns]) fail(functionPath, "invalid signature facts");
      for (const [parameterIndex, parameter] of fn.parameters.entries()) {
        if (!IDENTIFIER.test(parameter.name) || !TYPES[parameter.type] || parameter.type === "void") {
          fail(`${functionPath}.parameters[${parameterIndex}]`, "invalid parameter fact");
        }
        if (parameter.type === "callback" && typeof parameter.repeatingParameter !== "string") {
          fail(`${functionPath}.parameters[${parameterIndex}]`, "callback requires its repeating flag parameter");
        }
      }
      if (fn.timerOperation === "delay" && fn.returns !== "u32")
        fail(`${functionPath}.returns`, "delay must return u32");
      if (fn.timerOperation === "cancel" && fn.returns !== "bool")
        fail(`${functionPath}.returns`, "cancel must return bool");
    }
  }
  return facts;
}

function allFunctions(schema) {
  return schema.modules.flatMap((module) => module.functions.map((fn) => ({ module, fn })));
}

export function renderLuaBridgeHeader(inputFacts) {
  const schema = validateLuaBridgeFacts(inputFacts);
  const lines = [
    `// ${BANNER}`,
    "#pragma once",
    "",
    "#include <defold_hermes/lua_bridge.hpp>",
    "",
    "namespace defold_hermes::lua_bridge::generated {",
    "",
    "enum class Binding : uint32_t {",
  ];
  const entries = allFunctions(schema);
  entries.forEach(({ module, fn }, index) => lines.push(`  ${enumName(module, fn)} = ${index},`));
  lines.push(`  Count = ${entries.length}`, "};", "");
  lines.push(
    "bool initialize(LuaBridge& bridge, lua_State* state, RegistryApi registryApi, InstanceApi instanceApi = {});",
    "",
  );
  for (const { module, fn } of entries) {
    const parameters = [
      "LuaBridge& bridge",
      ...fn.parameters.map((parameter) => `${TYPES[parameter.type].cpp} ${parameter.name}`),
    ];
    if (fn.returns !== "void") parameters.push(`${TYPES[fn.returns].cpp}* out`);
    lines.push(`bool ${thunkName(module, fn)}(${parameters.join(", ")});`);
  }
  lines.push("", "}  // namespace defold_hermes::lua_bridge::generated", "");
  return lines.join("\n");
}

export function renderLuaBridgeSource(inputFacts) {
  const schema = validateLuaBridgeFacts(inputFacts);
  const entries = allFunctions(schema);
  const lines = [
    `// ${BANNER}`,
    "#include <defold_hermes/generated_lua_bridge.hpp>",
    "",
    "namespace defold_hermes::lua_bridge::generated {",
    "namespace {",
    "constexpr BindingDescriptor kBindings[] = {",
  ];
  for (const { module, fn } of entries) lines.push(`  {"${module.luaModule}", "${fn.luaFunction}"},`);
  lines.push("};", "}  // namespace", "");
  lines.push(
    "bool initialize(LuaBridge& bridge, lua_State* state, RegistryApi registryApi, InstanceApi instanceApi) {",
  );
  lines.push(
    `  return bridge.initialize(state, kBindings, ${entries.length}, ${schema.stackReserve}, registryApi, instanceApi);`,
  );
  lines.push("}", "");
  for (const { module, fn } of entries) {
    const parameters = [
      "LuaBridge& bridge",
      ...fn.parameters.map((parameter) => `${TYPES[parameter.type].cpp} ${parameter.name}`),
    ];
    if (fn.returns !== "void") parameters.push(`${TYPES[fn.returns].cpp}* out`);
    lines.push(`bool ${thunkName(module, fn)}(${parameters.join(", ")}) {`);
    lines.push(`  LuaCall call = bridge.beginCall(static_cast<uint32_t>(Binding::${enumName(module, fn)}));`);
    lines.push("  if (!call) return false;");
    for (const parameter of fn.parameters) {
      const argument =
        parameter.type === "callback" ? `${parameter.name}, ${parameter.repeatingParameter}` : parameter.name;
      lines.push(`  call.${TYPES[parameter.type].push}(${argument});`);
    }
    lines.push(`  if (!call.invoke(${fn.parameters.length}, ${fn.returns === "void" ? 0 : 1})) return false;`);
    if (fn.returns === "void") {
      lines.push("  return true;");
    } else {
      lines.push(`  if (!call.${TYPES[fn.returns].read}(0, out)) return false;`);
      if (fn.timerOperation === "delay") {
        const callback = fn.parameters.find(({ type }) => type === "callback");
        lines.push(`  return bridge.trackTimerCallback(*out, ${callback.name}, ${callback.repeatingParameter});`);
      } else if (fn.timerOperation === "cancel") {
        const handle = fn.parameters.find(({ name }) => name === "handle") ?? fn.parameters[0];
        lines.push(`  if (*out) bridge.releaseTimerCallback(${handle.name});`);
        lines.push("  return true;");
      } else {
        lines.push("  return true;");
      }
    }
    lines.push("}", "");
  }
  lines.push("}  // namespace defold_hermes::lua_bridge::generated", "");
  return lines.join("\n");
}

export function renderLuaBridgeOutputs(inputFacts) {
  const facts = validateLuaBridgeFacts(inputFacts);
  return new Map([
    ["defold/defold_hermes/include/defold_hermes/generated_lua_bridge.hpp", renderLuaBridgeHeader(facts)],
    ["defold/defold_hermes/src/generated_lua_bridge.cpp", renderLuaBridgeSource(facts)],
  ]);
}
