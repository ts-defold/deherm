// Stable renderers for revision-specific dmSDK universal outputs. The policy
// carries the source-derived recipe catalog; the installed compiler owns how
// that catalog becomes native and browser glue.

const banner = "Generated by scripts/generate-dmsdk-universal-bindings.mjs. Do not edit.";
const kindCode = Object.freeze({ function: 1, method: 2, constructor: 3, destructor: 4, "function-template": 5 });

function validateReport(report) {
  if (!report || !Array.isArray(report.recipes)) throw new Error("dmSDK universal output recipe has no recipes");
  if (!Number.isSafeInteger(report.abi?.maxArguments) || report.abi.maxArguments < 0)
    throw new Error("dmSDK universal output recipe has no bounded maximum argument count");
  if (!/^[0-9a-f]{64}$/u.test(report.sourceHashes?.catalog ?? ""))
    throw new Error("dmSDK universal output recipe has no authenticated catalog identity");
  for (const recipe of report.recipes) {
    if (
      !Number.isSafeInteger(recipe?.numericId) ||
      !Number.isSafeInteger(recipe?.abi?.argumentCount) ||
      !(recipe.declarationKind in kindCode) ||
      typeof recipe.declarationId !== "string" ||
      typeof recipe.symbol !== "string" ||
      typeof recipe.projectionId !== "string" ||
      typeof recipe.abi?.resultKind !== "string" ||
      !["generated-adapter", "universal-fallback"].includes(recipe.preferredLowering?.state)
    ) {
      throw new Error(`dmSDK universal output recipe is malformed at ${JSON.stringify(recipe?.declarationId)}`);
    }
  }
  return report;
}

export function generateDmSdkUniversalRuntimeSource(input) {
  const report = validateReport(input);
  const rows = report.recipes
    .map(
      (recipe) =>
        `  {UINT32_C(${recipe.numericId}), UINT16_C(${recipe.abi.argumentCount}), UINT8_C(${kindCode[recipe.declarationKind]}), UINT8_C(${recipe.preferredLowering.state === "generated-adapter" ? 1 : 0})}`,
    )
    .join(",\n");
  return `// ${banner}\n#include <defold_hermes/generated_dmsdk_universal.h>\n\n#include <stddef.h>\n\nnamespace {\nconst DehermDmSdkUniversalDescriptor kDescriptors[] = {\n${rows}\n};\nDehermDmSdkUniversalProvider g_provider = nullptr;\nvoid* g_context = nullptr;\n}\n\nextern "C" {\nuint32_t deherm_dmsdk_universal_count(void) { return UINT32_C(${report.recipes.length}); }\nconst char* deherm_dmsdk_universal_catalog_sha256(void) { return ${JSON.stringify(report.sourceHashes.catalog)}; }\nconst DehermDmSdkUniversalDescriptor* deherm_dmsdk_universal_descriptors(void) { return kDescriptors; }\nconst DehermDmSdkUniversalDescriptor* deherm_dmsdk_universal_find(uint32_t id) {\n  return id < deherm_dmsdk_universal_count() && kDescriptors[id].id == id ? &kDescriptors[id] : nullptr;\n}\nvoid deherm_dmsdk_universal_install_provider(DehermDmSdkUniversalProvider provider, void* context) {\n  g_provider = provider; g_context = context;\n}\nDehermDmSdkUniversalStatus deherm_dmsdk_universal_dispatch(\n    uint32_t id, const DehermDmSdkUniversalValue* arguments, uint32_t argument_count,\n    DehermDmSdkUniversalValue* result) {\n  const DehermDmSdkUniversalDescriptor* descriptor = deherm_dmsdk_universal_find(id);\n  if (!descriptor) return DEHERM_DMSDK_UNIVERSAL_UNKNOWN_ID;\n  if (descriptor->declaration_kind != UINT8_C(5) && argument_count != descriptor->argument_count) return DEHERM_DMSDK_UNIVERSAL_WRONG_ARITY;\n  if (argument_count && !arguments) return DEHERM_DMSDK_UNIVERSAL_INVALID_STORAGE;\n  if (!result) return DEHERM_DMSDK_UNIVERSAL_INVALID_STORAGE;\n  if (!g_provider) return DEHERM_DMSDK_UNIVERSAL_NO_PROVIDER;\n  return g_provider(g_context, descriptor, arguments, argument_count, result);\n}\n}\n`;
}

export function generateDmSdkUniversalBrowserLibrary(input) {
  const report = validateReport(input);
  const metadata = report.recipes.map(({ numericId, declarationId, symbol, declarationKind, abi, projectionId }) => ({
    id: numericId,
    declarationId,
    symbol,
    declarationKind,
    argumentCount: abi.argumentCount,
    resultKind: abi.resultKind,
    recipeId: projectionId,
  }));
  return `// ${banner}\nvar LibraryDefoldHermesDmSdkUniversal={\n  $DEFOLD_HERMES_DMSDK_UNIVERSAL__deps:["deherm_dmsdk_universal_dispatch","deherm_dmsdk_universal_catalog_sha256"],\n  $DEFOLD_HERMES_DMSDK_UNIVERSAL:{\n    catalogSha256:${JSON.stringify(report.sourceHashes.catalog)},\n    abi:Object.freeze({valueBytes:24,maxArguments:${report.abi.maxArguments},dispatch:'direct-memory',embind:false}),\n    recipes:Object.freeze(${JSON.stringify(metadata)}),\n    callRaw:function(id,argumentsPointer,argumentCount,resultPointer){return _deherm_dmsdk_universal_dispatch(id,argumentsPointer,argumentCount,resultPointer);}\n  }\n};\nautoAddDeps(LibraryDefoldHermesDmSdkUniversal,'$DEFOLD_HERMES_DMSDK_UNIVERSAL');\naddToLibrary(LibraryDefoldHermesDmSdkUniversal);\n`;
}
