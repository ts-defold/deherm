import { reservedParameterSynonyms, safeParameterIdentifier } from "../names.mjs";
import { hexBindingId } from "../binding-identity.mjs";
import { publicScriptModulePath, rawScriptRootName } from "../script-public-api-policy.mjs";

const banner = "// Generated by packages/compiler/src/sdk/script-sdk.mjs. Do not edit.";

function splitTopLevel(value, delimiter) {
  const parts = [];
  let start = 0;
  let depth = 0;
  let quote = "";
  for (let index = 0; index < value.length; index += 1) {
    const character = value[index];
    if (quote) {
      if (character === quote && value[index - 1] !== "\\") quote = "";
      continue;
    }
    if (character === '"' || character === "'") quote = character;
    else if ("<({[".includes(character)) depth += 1;
    else if (">)}]".includes(character)) depth -= 1;
    else if (character === delimiter && depth === 0) {
      parts.push(value.slice(start, index).trim());
      start = index + 1;
    }
  }
  parts.push(value.slice(start).trim());
  return parts.filter(Boolean);
}
function documentation(value, indent = "") {
  if (!value) return [];
  return [
    `${indent}/**`,
    ...value.split("\n").map((line) => `${indent} *${line ? ` ${line}` : ""}`),
    `${indent} */`
  ];
}

function balancedOuter(value, open, close) {
  if (!value.startsWith(open) || !value.endsWith(close)) return false;
  let depth = 0;
  for (let index = 0; index < value.length; index += 1) {
    if (value[index] === open) depth += 1;
    if (value[index] === close) depth -= 1;
    if (depth === 0 && index < value.length - 1) return false;
  }
  return depth === 0;
}

function pascal(value) {
  const words = value.replace(/^defold_(?:api|enum)\./, "").split(/[^A-Za-z0-9]+/).filter(Boolean);
  const joined = words.map((word) => word[0].toUpperCase() + word.slice(1)).join("") || "Anonymous";
  return /^[A-Za-z_$]/.test(joined) ? joined : `_${joined}`;
}

function camel(value) {
  if (/^[A-Z][A-Z0-9_]*$/.test(value)) return value;
  return value.replace(/_([a-zA-Z0-9])/g, (_, character) => character.toUpperCase());
}

function property(value) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(value) ? value : JSON.stringify(value);
}

function fieldDeclaration(field, renderType) {
  const index = field.rawName.match(/^\[(string|integer|number)\]$/);
  if (index) {
    const keyType = index[1] === "string" ? "string" : "number";
    return `readonly [key: ${keyType}]: ${renderType(field.rawType)};`;
  }
  return `readonly ${property(camel(field.rawName))}${field.optional ? "?" : ""}: ${renderType(field.rawType)};`;
}

function parameterName(value, index) {
  const candidate = camel(value.replace(/\?$/, ""));
  return safeParameterIdentifier(candidate, index);
}

export function createTypeRenderer(model) {
  const named = new Map();
  const used = new Set();
  const unresolved = new Set();
  const allocate = (item, suffix = "") => {
    if (item.name.startsWith("defold_api.")) return;
    const base = `${pascal(item.name)}${suffix}`;
    let name = base;
    let index = 2;
    while (used.has(name)) name = `${base}${index++}`;
    used.add(name);
    named.set(item.name, name);
  };
  for (const item of model.classes) allocate(item);
  for (const item of model.aliases) allocate(item, named.has(item.name) ? "Alias" : "");
  for (const item of model.enums) allocate(item, "Enum");
  for (const primitive of ["vector3", "vector4", "quaternion", "matrix4"]) {
    named.delete(primitive);
  }
  const primitives = new Map([
    ["nil", "null"], ["any", "unknown"], ["boolean", "boolean"], ["bool", "boolean"],
    ["number", "number"], ["integer", "number"], ["string", "string"], ["void", "void"],
    ["hash", "DefoldHash"], ["url", "DefoldUrl"], ["table", "Readonly<Record<PropertyKey, unknown>>"],
    ["function", "(...args: readonly unknown[]) => unknown"], ["userdata", "DefoldOpaque<\"userdata\">"],
    ["...", "readonly unknown[]"],
    ["vector3", "Vector3"], ["vector4", "Vector4"], ["quaternion", "Quaternion"], ["matrix4", "Matrix4"]
  ]);

  function renderObject(value, localNames) {
    const contents = value.slice(1, -1).trim();
    if (!contents) return "Readonly<Record<string, never>>";
    const fields = [];
    const records = [];
    for (const part of splitTopLevel(contents, ",")) {
      const separator = splitAtTopLevelColon(part);
      if (!separator) return "Readonly<Record<PropertyKey, unknown>>";
      const [rawKey, rawValue] = separator;
      if (rawKey.startsWith("[") && rawKey.endsWith("]")) {
        records.push(`Readonly<Record<${render(rawKey.slice(1, -1), localNames)}, ${render(rawValue, localNames)}>>`);
      } else {
        const optional = rawKey.endsWith("?");
        fields.push(`${property(rawKey.replace(/\?$/, ""))}${optional ? "?" : ""}: ${render(rawValue, localNames)}`);
      }
    }
    const object = fields.length ? `Readonly<{ ${fields.join("; ")} }>` : "";
    return [object, ...records].filter(Boolean).join(" & ");
  }

  function splitAtTopLevelColon(value) {
    let depth = 0;
    for (let index = 0; index < value.length; index += 1) {
      const character = value[index];
      if ("<({[".includes(character)) depth += 1;
      else if (">)}]".includes(character)) depth -= 1;
      else if (character === ":" && depth === 0) return [value.slice(0, index).trim(), value.slice(index + 1).trim()];
    }
    return undefined;
  }

  function functionCloseIndex(value) {
    let depth = 0;
    for (let index = 3; index < value.length; index += 1) {
      if (value[index] === "(") depth += 1;
      else if (value[index] === ")") {
        depth -= 1;
        if (depth === 0) return index;
      }
    }
    return -1;
  }

  function renderFunction(value, localNames) {
    if (!value.startsWith("fun(")) return "(...args: readonly unknown[]) => unknown";
    const close = functionCloseIndex(value);
    if (close < 0) return "(...args: readonly unknown[]) => unknown";
    const rawParameters = value.slice(4, close);
    const rawResult = value.slice(close + 1).replace(/^:/, "");
    const params = splitTopLevel(rawParameters, ",").map((item, index) => {
      const pair = splitAtTopLevelColon(item);
      if (!pair) return `arg${index + 1}: unknown`;
      const rawName = pair[0];
      if (rawName === "...") return `...args: ${render(pair[1], localNames)}[]`;
      return `${parameterName(rawName, index)}${rawName.endsWith("?") ? "?" : ""}: ${render(pair[1], localNames)}`;
    });
    const result = rawResult ? render(rawResult, localNames) : "void";
    return `(${params.join(", ")}) => ${result}`;
  }

  function render(rawValue, localNames) {
    let value = rawValue.trim();
    if (!value) return "unknown";
    if (value.startsWith("fun(")) {
      const close = functionCloseIndex(value);
      const suffix = close < 0 ? "" : value.slice(close + 1);
      if (!suffix || suffix.startsWith(":")) return renderFunction(value, localNames);
    }
    const union = splitTopLevel(value, "|");
    if (union.length > 1) {
      const rendered = [...new Set(union.map((item) => render(item, localNames)))];
      return rendered.map((item) => item.includes("=>") ? `(${item})` : item).join(" | ");
    }
    if (value.endsWith("[]")) return `ReadonlyArray<${render(value.slice(0, -2), localNames)}>`;
    if (balancedOuter(value, "(", ")")) {
      const inner = value.slice(1, -1);
      const tuple = splitTopLevel(inner, ",");
      return tuple.length > 1 ? `readonly [${tuple.map((item) => render(item, localNames)).join(", ")}]` : render(inner, localNames);
    }
    if (value.startsWith("table<") && value.endsWith(">")) {
      const args = splitTopLevel(value.slice(6, -1), ",");
      if (args.length === 1) return `readonly ${render(args[0], localNames)}[]`;
      if (args.length === 2) {
        const renderedValue = render(args[1], localNames);
        if (args[0] === "string") return `Readonly<Record<string, ${renderedValue}>>`;
        if (args[0] === "integer" || args[0] === "number") return `Readonly<Record<number, ${renderedValue}>>`;
        if (args[0] === "any") return `Readonly<Record<PropertyKey, ${renderedValue}>>`;
        return `ReadonlyMap<${render(args[0], localNames)}, ${renderedValue}>`;
      }
    }
    if (value.startsWith("{") && value.endsWith("}")) return renderObject(value, localNames);
    if (localNames?.has(value)) return localNames.get(value);
    if (primitives.has(value)) return primitives.get(value);
    if (/^-?\d+(?:\.\d+)?$/.test(value) || /^(?:true|false)$/.test(value)) return value;
    if (/^(['"]).*\1$/.test(value)) return JSON.stringify(value.slice(1, -1));
    if (named.has(value)) return named.get(value);
    unresolved.add(value);
    return `DefoldOpaque<${JSON.stringify(value)}>`;
  }
  return { render, named, unresolved };
}

function treeNode() {
  return { fields: [], functions: [], children: new Map(), description: "" };
}

export function buildApiTrees(model) {
  const roots = new Map();
  const nodeAt = (segments) => {
    const [rootName, ...rest] = publicScriptModulePath(segments);
    if (!roots.has(rootName)) roots.set(rootName, treeNode());
    let node = roots.get(rootName);
    for (const segment of rest) {
      if (!node.children.has(segment)) node.children.set(segment, treeNode());
      node = node.children.get(segment);
    }
    return node;
  };
  for (const fn of model.functions) nodeAt(fn.modulePath).functions.push(fn);
  for (const classItem of model.classes) {
    if (!classItem.name.startsWith("defold_api.")) continue;
    const segments = classItem.name.slice("defold_api.".length).split(".");
    const node = nodeAt(segments);
    node.description ||= classItem.description;
    node.fields.push(...classItem.fields);
  }
  const normalize = (node) => {
    const children = new Set([...node.children.keys()].map(camel));
    const fields = new Map();
    for (const field of node.fields) {
      const jsName = camel(field.rawName);
      if (!children.has(jsName) && !fields.has(jsName)) fields.set(jsName, field);
    }
    node.fields = [...fields.values()];
    for (const child of node.children.values()) normalize(child);
  };
  for (const node of roots.values()) normalize(node);
  return roots;
}

function renderParameters(fn, renderType) {
  return fn.parameters.map((param, index) => {
    if (param.rawName === "...") return `...args: ${renderType(param.rawType)}[]`;
    const laterRequired = fn.parameters.slice(index + 1).some((later) => !later.optional && later.rawName !== "...");
    const optional = param.optional && !laterRequired;
    const rawUnion = new Set(splitTopLevel(param.rawType, "|"));
    const rendered = rawUnion.has("string") && rawUnion.has("url") ? "DefoldAddress" : renderType(param.rawType);
    const type = `${rendered}${param.optional && laterRequired ? " | undefined" : ""}`;
    return `${parameterName(param.rawName, index)}${optional ? "?" : ""}: ${type}`;
  }).join(", ");
}

function renderReturns(fn, renderType) {
  if (!fn.returns.length) return "void";
  if (fn.returns.length === 1) return renderType(fn.returns[0]);
  return `readonly [${fn.returns.map(renderType).join(", ")}]`;
}

function renderGenerics(fn, renderType) {
  const localNames = new Map();
  const parsed = fn.generics.map((value, index) => {
    const separator = value.indexOf(":");
    const rawName = (separator < 0 ? value : value.slice(0, separator)).trim();
    const constraint = separator < 0 ? "unknown" : value.slice(separator + 1).trim();
    const name = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(rawName) && !reservedParameterSynonyms.has(rawName)
      ? rawName
      : `T${index + 1}`;
    localNames.set(rawName, name);
    return { name, constraint };
  });
  const declaration = parsed.length
    ? `<${parsed.map(({ name, constraint }) => `${name} extends ${renderType(constraint, localNames)}`).join(", ")}>`
    : "";
  return { declaration, localNames };
}

function renderNodeInterface(node, renderType, indent = "  ") {
  const lines = ["{"];
  for (const field of node.fields.sort((a, b) => a.rawName.localeCompare(b.rawName))) {
    lines.push(...documentation(field.description, indent));
    lines.push(`${indent}${fieldDeclaration(field, renderType)}`);
  }
  for (const fn of node.functions.sort((a, b) => a.jsName.localeCompare(b.jsName))) {
    const tags = [fn.description];
    if (fn.deprecated) tags.push(`@deprecated ${fn.deprecated}`);
    for (const [index, param] of fn.parameters.entries()) if (param.description) tags.push(`@param ${parameterName(param.rawName, index)} ${param.description}`);
    if (fn.returnDescriptions.some(Boolean)) tags.push(`@returns ${fn.returnDescriptions.filter(Boolean).join("; ")}`);
    lines.push(...documentation(tags.filter(Boolean).join("\n\n"), indent));
    lines.push(`${indent}readonly ${property(fn.jsName)}: {`);
    for (const overload of fn.overloads) {
      const overloadType = renderType(overload);
      const callable = overloadType.match(/^(\(.*\)) => (.+)$/)?.slice(1);
      lines.push(`${indent}  ${callable ? `${callable[0]}: ${callable[1]}` : `(...args: readonly unknown[]): ${overloadType}`};`);
    }
    const generics = renderGenerics(fn, renderType);
    const localRender = (value) => renderType(value, generics.localNames);
    lines.push(`${indent}  ${generics.declaration}(${renderParameters(fn, localRender)}): ${renderReturns(fn, localRender)};`);
    lines.push(`${indent}};`);
  }
  for (const [name, child] of [...node.children].sort(([left], [right]) => left.localeCompare(right))) {
    const rendered = renderNodeInterface(child, renderType, `${indent}  `);
    lines.push(`${indent}readonly ${property(camel(name))}: ${rendered[0]}`);
    lines.push(...rendered.slice(1).map((line) => `${indent}${line}`));
  }
  lines.push(`${indent.slice(2)}}`);
  return lines;
}

function constantLiteral(entry) {
  if (entry.valueKind === "number" && typeof entry.value === "number" && Number.isFinite(entry.value)) {
    return Object.is(entry.value, -0) ? "-0" : String(entry.value);
  }
  if (entry.valueKind === "string" && typeof entry.value === "string") return JSON.stringify(entry.value);
  // Hash values are represented as hexadecimal strings in policy so that JSON
  // does not round a uint64. BigInt is available in all three generated
  // targets, and this path emits a literal rather than a bridge lookup.
  if (entry.valueKind === "hash" && typeof entry.value === "string" && /^(?:0x[0-9a-f]+|[0-9]+)$/iu.test(entry.value)) {
    return `${entry.value}n`;
  }
  return null;
}

// Registration scope is derived from the pinned source path of the SETCONSTANT
// expression.  Only the known core registration sources are safe to treat as
// unconditional.  An unfamiliar source is deliberately conservative: equal
// literals from a future optional module must stay on the executable route until
// its profile scope is identified by the generator.
function renderNodeValue(rootName, pathSegments, node, interfaceAccess, constantValues, indent = "  ") {
  const lines = ["{"];
  for (const field of node.fields.sort((a, b) => a.rawName.localeCompare(b.rawName))) {
    const jsName = camel(field.rawName);
    const fullName = `${pathSegments.join(".")}.${field.rawName}`;
    const entry = constantValues.get(fullName);
    const literal = entry && (entry.state === undefined || entry.state === "inlined") &&
      entry.profileAvailability?.kind !== "runtime-profile-gated" && constantLiteral(entry);
    const value = literal
      ? `return ${literal} as unknown as ${interfaceAccess}[${JSON.stringify(jsName)}];`
      : entry?.state === "runtime-backed" || entry?.state === "profile-unavailable"
        ? `return callScriptApi(${entry.stableId}, [] as const) as ${interfaceAccess}[${JSON.stringify(jsName)}];`
        : `return failScriptApiConstant(${JSON.stringify(pathSegments.join("."))}, ${JSON.stringify(field.rawName)}, ${JSON.stringify(entry?.blocker?.reason ?? "not-registered-in-selected-runtime-profile")}) as never;`;
    lines.push(`${indent}get ${property(jsName)}() { ${value} },`);
  }
  for (const fn of node.functions.sort((a, b) => a.jsName.localeCompare(b.jsName))) {
    lines.push(`${indent}${property(fn.jsName)}: ((...args: readonly unknown[]) => callScriptApi(${hexBindingId(fn.stableId).replace(/u$/, "")}, args)) as ${interfaceAccess}[${JSON.stringify(fn.jsName)}],`);
  }
  for (const [name, child] of [...node.children].sort(([left], [right]) => left.localeCompare(right))) {
    const jsName = camel(name);
    const childLines = renderNodeValue(rootName, [...pathSegments, name], child, `${interfaceAccess}[${JSON.stringify(jsName)}]`, constantValues, `${indent}  `);
    lines.push(`${indent}${property(jsName)}: ${childLines[0]}`);
    lines.push(...childLines.slice(1).map((line) => `${indent}${line}`));
    lines[lines.length - 1] += ",";
  }
  lines.push(`${indent.slice(2)}}`);
  return lines;
}

export function generateTypes(model, renderer, trees, semanticHandleTypes) {
  const lines = [
    banner,
    'import type { DefoldAddress, DefoldHash, DefoldUrl } from "../../address";',
    'import type { DefoldHandle } from "./handle-lowering";',
    "",
    "declare const opaqueBrand: unique symbol;",
    "declare const defoldValueBrand: unique symbol;",
    "export type DefoldOpaque<Name extends string> = { readonly [opaqueBrand]: Name };",
    "export type Vector3 = Readonly<{ x: number; y: number; z: number; readonly [defoldValueBrand]: \"vector3\" }>;",
    "export type Vector4 = Readonly<{ x: number; y: number; z: number; w: number; readonly [defoldValueBrand]: \"vector4\" }>;",
    "export type Quaternion = Readonly<{ x: number; y: number; z: number; w: number; readonly [defoldValueBrand]: \"quaternion\" }>;",
    "export type Matrix4 = readonly [number, number, number, number, number, number, number, number, number, number, number, number, number, number, number, number];",
    ""
  ];
  for (const item of [...model.enums].sort((a, b) => a.name.localeCompare(b.name))) {
    const name = renderer.named.get(item.name);
    if (name) lines.push(...documentation(item.description), `export type ${name} = ${renderer.render(item.rawType)} & DefoldOpaque<${JSON.stringify(item.name)}>;`);
  }
  for (const item of [...model.aliases].sort((a, b) => a.name.localeCompare(b.name))) {
    const name = renderer.named.get(item.name);
    const semanticKind = semanticHandleTypes.get(item.name);
    if (name) lines.push(...documentation(item.description), `export type ${name} = ${semanticKind ? `DefoldHandle<${JSON.stringify(semanticKind)}>` : renderer.render(item.rawType)};`);
  }
  for (const item of model.classes.filter((value) => !value.name.startsWith("defold_api.")).sort((a, b) => a.name.localeCompare(b.name))) {
    const name = renderer.named.get(item.name);
    if (!name) continue;
    lines.push(...documentation(item.description), `export interface ${name} {`);
    if (!item.fields.length) lines.push(`  readonly __type?: ${JSON.stringify(item.name)};`);
    const fields = new Map();
    for (const field of item.fields) fields.set(camel(field.rawName), field);
    for (const field of fields.values()) lines.push(...documentation(field.description, "  "), `  ${fieldDeclaration(field, renderer.render)}`);
    lines.push("}");
  }
  lines.push("");
  for (const [rootName, node] of [...trees].sort(([left], [right]) => left.localeCompare(right))) {
    const interfaceName = `${pascal(rootName)}Api`;
    const rendered = renderNodeInterface(node, renderer.render);
    lines.push(...documentation(node.description), `export interface ${interfaceName} ${rendered[0]}`, ...rendered.slice(1), "");
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

export function generateModules(trees, constantValues = new Map()) {
  const lines = [banner, 'import { callScriptApi, failScriptApiConstant } from "./runtime";', 'import type * as Types from "./types";', ""];
  for (const [rootName, node] of [...trees].sort(([left], [right]) => left.localeCompare(right))) {
    const interfaceName = `${pascal(rootName)}Api`;
    const rawRootName = rawScriptRootName(rootName);
    const rendered = renderNodeValue(rootName, [rawRootName], node, `Types.${interfaceName}`, constantValues);
    lines.push(`export const ${property(camel(rootName))}: Types.${interfaceName} = ${rendered[0]}`, ...rendered.slice(1));
    lines[lines.length - 1] += ";";
    lines.push("");
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

export function generateRuntime() {
  return `${banner}
import { assertValueRouteTargetSupport } from "./value-target-support";
import { assertFixedTupleTargetSupport } from "./fixed-tuple-target-support";
import { assertBrowserRouteTargetSupport } from "./browser-target-support";

export interface DefoldScriptBridge {
  /** Stable-ID universal call surface. Primitive scalar values are the first executable lane. */
  call(stableId: number, args: readonly unknown[]): unknown;
  /** Generated execution target used to fail closed before unsupported host codecs run. */
  readonly target?: "native-hermes" | "html5-browser-host";
  /** Legacy name-addressed constant lookup, retained for host integrations. Generated constants do not use it. */
  get?(modulePath: string, memberName: string): unknown;
}

declare global {
  var __defoldScriptBridgeV1: DefoldScriptBridge | undefined;
}

let activeBridge: DefoldScriptBridge | undefined;

export function installDefoldScriptBridge(bridge: DefoldScriptBridge): void {
  activeBridge = bridge;
}

function bridge(): DefoldScriptBridge {
  const installed = activeBridge ?? globalThis.__defoldScriptBridgeV1;
  if (!installed) throw new Error("Defold script bridge has not been installed");
  return installed;
}

export function callScriptApi(stableId: number, args: readonly unknown[]): unknown {
  const installed = bridge();
  assertValueRouteTargetSupport(stableId, installed.target);
  assertFixedTupleTargetSupport(installed.target, stableId);
  assertBrowserRouteTargetSupport(stableId, installed.target);
  return installed.call(stableId, args);
}

export function failScriptApiConstant(modulePath: string, memberName: string, reason: string): never {
  const error = new Error("Defold script constant " + modulePath + "." + memberName + " is not executable: " + reason) as Error & {
    code?: string;
    modulePath?: string;
    memberName?: string;
    reason?: string;
  };
  error.code = "DEHERM_SCRIPT_CONSTANT_NOT_INLINED";
  error.modulePath = modulePath;
  error.memberName = memberName;
  error.reason = reason;
  throw error;
}
`;
}

export function generateIndex(trees) {
  const names = [...trees.keys()].sort().map(camel);
  return `${banner}\nexport { ${names.join(", ")} } from "./modules";\nexport { installDefoldScriptBridge, type DefoldScriptBridge } from "./runtime";\nexport * from "./handle-lowering";\nexport type * from "./types";\n`;
}
