function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function compareCodeUnits(left, right) {
  return left < right ? -1 : left > right ? 1 : 0;
}

const callableKinds = new Set(["function", "method", "constructor", "destructor", "function-template"]);

function property(value) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(value) ? value : JSON.stringify(value);
}

function parameter(value, index) {
  const cleaned = String(value || `arg${index + 1}`).replace(/[^A-Za-z0-9_$]/g, "_");
  return safeParameterIdentifier(cleaned, index);
}

function pascalIdentifier(value) {
  const result = String(value).split(/[^A-Za-z0-9]+/).filter(Boolean)
    .map((part) => `${part[0].toUpperCase()}${part.slice(1)}`).join("");
  return /^[A-Za-z_$]/.test(result) ? result : `Dm${result}`;
}

function normalizeType(raw) {
  return String(raw || "void").replace(/\b(?:const|volatile|restrict)\b/g, "").replace(/\s+/g, " ").trim();
}

export function createTypeRenderer(ir) {
  const declarations = new Map();
  for (const declaration of [...ir.declarations, ...(ir.typeSupportDeclarations ?? [])]) {
    if (["record", "enum", "type-alias"].includes(declaration.kind) && !declarations.has(declaration.name)) {
      declarations.set(declaration.name, declaration);
    }
  }
  const suffixes = new Map();
  for (const name of declarations.keys()) {
    const suffix = name.split("::").at(-1);
    const values = suffixes.get(suffix) ?? [];
    values.push(name);
    suffixes.set(suffix, values);
  }
  const unresolved = new Map();
  const opaque = new Map();
  const scalar = new Map([
    ["void", "void"], ["bool", "boolean"], ["float", "number"], ["double", "number"],
    ["char", "number"], ["signed char", "number"], ["unsigned char", "number"],
    ["int8_t", "number"], ["uint8_t", "number"], ["int16_t", "number"], ["uint16_t", "number"],
    ["int32_t", "number"], ["uint32_t", "number"], ["int", "number"], ["unsigned int", "number"],
    ["short", "number"], ["unsigned short", "number"], ["size_t", "number"], ["ptrdiff_t", "number"],
    ["int64_t", "bigint"], ["uint64_t", "bigint"], ["intptr_t", "bigint"], ["uintptr_t", "bigint"],
    ["long", "bigint"], ["unsigned long", "bigint"],
    ["long long", "bigint"], ["unsigned long long", "bigint"]
  ]);

  function cleanName(value) {
    return value.replace(/^(?:struct|class|enum)\s+/, "").replace(/^::/, "").trim();
  }

  function resolveName(value, contextName) {
    const name = cleanName(value);
    if (declarations.has(name)) return name;
    if (!name.includes("::") && contextName) {
      const context = contextName.split("::").slice(0, -1);
      for (let length = context.length; length > 0; length -= 1) {
        const candidate = `${context.slice(0, length).join("::")}::${name}`;
        if (declarations.has(candidate)) return candidate;
      }
    }
    const matches = suffixes.get(name) ?? [];
    return matches.length === 1 ? matches[0] : undefined;
  }

  function noteUnresolved(value, contextName) {
    const name = cleanName(value);
    const contexts = unresolved.get(name) ?? new Set();
    if (contextName) contexts.add(contextName);
    unresolved.set(name, contexts);
  }

  function opaqueReason(value) {
    if (value === "T" || value === "KEY") return "template-parameter";
    if (value === "id") return "objective-c-object";
    if (value === "va_list") return "platform-variadic-list";
    if (value.startsWith("Vectormath::Aos::")) return "external-vectormath-type";
    if (/^(?:(?:struct|union) )?\(unnamed (?:struct|union) at /.test(value)) return "anonymous-native-record";
    if (value.includes("<") || value.includes(">")) return "template-specialization";
    return undefined;
  }

  function noteOpaque(value, contextName, reason) {
    const name = cleanName(value);
    const item = opaque.get(name) ?? { reason, contexts: new Set() };
    if (contextName) item.contexts.add(contextName);
    opaque.set(name, item);
  }

  function renderType(raw, contextName) {
    const original = String(raw || "void").trim();
    const value = normalizeType(original);
    if (/\(\s*[*&^]\s*\)/.test(value) || /\(\s*[*&^]\w+\s*\)/.test(value)) return "DmNativeCallback";
    const array = value.match(/^(.*)\[([^\]]*)\]$/);
    if (array) return `DmSpan<${renderType(array[1], contextName)}>`;
    if (value.endsWith("&&") || value.endsWith("&")) return `DmReference<${renderType(value.replace(/&&?$/, ""), contextName)}>`;
    if (value.endsWith("*")) {
      const pointee = cleanName(value.replace(/\*+$/, "").trim()) || "void";
      const canonical = resolveName(pointee, contextName) ?? pointee;
      const pointer = /\bconst\b/.test(original.replace(/\*+$/, "")) ? "DmReadonlyPointer" : "DmPointer";
      return `${pointer}<${JSON.stringify(canonical)}>`;
    }
    if (scalar.has(value)) return scalar.get(value);
    const canonical = resolveName(value, contextName);
    if (canonical) return `DmSdkTypes[${JSON.stringify(canonical)}]`;
    const reason = opaqueReason(value);
    if (reason) {
      noteOpaque(value, contextName, reason);
      return `DmNativeType<${JSON.stringify(cleanName(value))}>`;
    }
    noteUnresolved(value, contextName);
    return `DmNativeType<${JSON.stringify(cleanName(value))}>`;
  }

  return { renderType, unresolved, opaque, resolveName };
}

function strategies(declaration) {
  if (!callableKinds.has(declaration.kind)) return ["type-metadata"];
  const reasons = new Set(declaration.policyReasons ?? []);
  const result = [];
  if (reasons.has("callback")) result.push("callback-registry");
  if (reasons.has("pointer/ownership")) result.push("explicit-pointer-ownership");
  if (reasons.has("reference/lifetime")) result.push("borrowed-reference-lifetime");
  if (reasons.has("array/span")) result.push("generated-span-layout");
  if (reasons.has("template") || declaration.kind.includes("template")) result.push("template-specialization-adapter");
  if (reasons.has("named-or-wide-type")) result.push("named-type-or-wide-integer-adapter");
  if (declaration.kind === "method") result.push("opaque-this-handle");
  if (declaration.kind === "constructor") result.push("owned-handle-constructor");
  if (declaration.kind === "destructor") result.push("owned-handle-finalizer");
  if (!result.length) result.push("direct-c-abi");
  return result;
}

function documentation(value, indent = "") {
  if (!value) return [];
  const clean = value.replace(/<[^>]+>/g, " ").replace(/\s+\n/g, "\n").replaceAll("*/", "* /").trim();
  if (!clean) return [];
  return [`${indent}/**`, ...clean.split(/\r?\n/).map((line) => `${indent} * ${line.trim()}`), `${indent} */`];
}

function deprecationNotice(...values) {
  for (const value of values.flat(Infinity)) {
    if (typeof value !== "string") continue;
    const line = value.split(/\r?\n/u).map((item) => item.trim()).find((item) => /\bdeprecated\b/iu.test(item));
    if (line) return line;
  }
  return undefined;
}

function declarationDocumentation(declaration, { includeDescription = true } = {}) {
  const notes = (declaration.notes ?? []).filter((note) => note !== declaration.deprecated);
  return [
    includeDescription ? declaration.description : "",
    notes.length ? `@remarks ${notes.join("\n\n")}` : "",
    declaration.deprecated ? `@deprecated ${declaration.deprecated}` : ""
  ].filter(Boolean).join("\n\n");
}

function docsByHeader(archive) {
  const decoder = new TextDecoder();
  const result = new Map();
  for (const [name, bytes] of Object.entries(archive)) {
    if (!name.startsWith("doc/dmsdk-") || !name.endsWith("_doc.json")) continue;
    let parsed;
    try { parsed = JSON.parse(decoder.decode(bytes)); } catch { continue; }
    const elements = new Map();
    for (const element of parsed.elements ?? []) {
      if (!element?.name) continue;
      const list = elements.get(element.name) ?? [];
      list.push(element);
      elements.set(element.name, list);
    }
    result.set(name, elements);
  }
  return result;
}

function headerDocName(header) {
  const marker = "/dmsdk/";
  const index = header.lastIndexOf(marker);
  if (index < 0) return undefined;
  return `doc/dmsdk-${header.slice(index + marker.length).replaceAll("/", "-")}_doc.json`;
}

function attachDocumentation(inventory, docs) {
  return inventory.declarations.map((declaration) => {
    const headerDocs = docs.get(headerDocName(declaration.header));
    if (!headerDocs) return declaration;
    const shortName = declaration.name.split("::").at(-1).replace(/^~/, "").replace(/<.*>$/, "");
    const element = headerDocs.get(declaration.name)?.[0] ?? headerDocs.get(shortName)?.[0];
    if (!element) return declaration;
    const parameterDocs = new Map((element.parameters ?? []).map((item) => [item.name, item.doc ?? ""]));
    const deprecated = deprecationNotice(element.description, element.brief, element.notes ?? []);
    return {
      ...declaration,
      description: element.description || element.brief || "",
      ...((element.notes ?? []).length ? { notes: [...element.notes] } : {}),
      ...(deprecated ? { deprecated } : {}),
      parameters: (declaration.parameters ?? []).map((item) => ({ ...item, description: parameterDocs.get(item.name) ?? "" })),
      returnDescription: (element.returnvalues ?? []).map((item) => item.doc).filter(Boolean).join("; ")
    };
  });
}

function enrich(inventory) {
  const declarations = inventory.declarations.map((declaration, index) => {
    const normalized = declaration.kind === "enum"
      ? { ...declaration, members: resolvedEnumMembers(declaration) }
      : declaration;
    return {
      ...normalized,
      id: `dmsdk:${normalized.name}@${normalized.header}:${normalized.line ?? 0}:${index}`,
      disposition: normalized.access === "private" || normalized.access === "protected"
        ? "intentionally-hidden-non-public"
        : callableKinds.has(normalized.kind) ? "generated-raw-call" : "generated-type-metadata",
      abiStrategies: strategies(normalized)
    };
  });
  const typeSupportDeclarations = (inventory.typeSupportDeclarations ?? []).map((declaration, index) => ({
    ...declaration,
    id: `dmsdk-support:${declaration.name}@${declaration.header}:${declaration.line ?? 0}:${index}`,
    disposition: "signature-type-support",
    abiStrategies: ["type-metadata"],
  }));
  return {
    schemaVersion: 1,
    defoldRevision: inventory.defoldRevision,
    parseEnvironment: inventory.parseEnvironment,
    headerCount: inventory.headerCount,
    parsedHeaderCount: inventory.parsedHeaderCount,
    failedHeaderCount: inventory.failedHeaderCount,
    diagnosticHeaderCount: inventory.diagnosticHeaderCount,
    declarationCount: declarations.length,
    typeSurfaceUnresolvedCount: undefined,
    runtimeImplementedCount: 0,
    runtimeUnimplementedCount: declarations.filter((item) => callableKinds.has(item.kind) && item.disposition === "generated-raw-call").length,
    declarations,
    typeSupportDeclarations,
  };
}

function signature(declaration, renderType) {
  const parameters = (declaration.parameters ?? []).map((item, index) => `${parameter(item.name, index)}: ${renderType(item.type, declaration.name)}`).join(", ");
  return `(${parameters}): ${renderType(declaration.returns ?? "void", declaration.name)}`;
}

function overloadIdentity(declaration, renderType) {
  return JSON.stringify((declaration.parameters ?? []).map((item) => renderType(item.type, declaration.name)));
}

function functionType(declaration, renderType) {
  const parameters = (declaration.parameters ?? []).map((item, index) => `${parameter(item.name, index)}: ${renderType(item.type, declaration.name)}`).join(", ");
  return `(${parameters}) => ${renderType(declaration.returns ?? "void", declaration.name)}`;
}

/**
 * The exact overload declarations emitted by the runtime facade.
 *
 * The marker is deliberately carried by the first parameter name. Parameter
 * names do not affect the public call syntax, but TypeScript's resolved
 * signature retains them. The ttsc pass can therefore recover the precise
 * generator-owned overload without re-rendering TypeScript types in Go.
 */
export function dmSdkRuntimeOverloads(ir, renderer) {
  const groups = new Map();
  for (const declaration of ir.declarations.filter((item) => callableKinds.has(item.kind) && item.disposition === "generated-raw-call")) {
    const declarations = groups.get(declaration.name) ?? [];
    declarations.push(declaration);
    groups.set(declaration.name, declarations);
  }
  const overloads = [];
  for (const [name, declarations] of [...groups].sort(([left], [right]) => compareCodeUnits(left, right))) {
    const bySignature = new Map();
    for (const declaration of declarations) {
      // Parameter names and return types do not participate in TypeScript
      // overload selection. Group by the checker-visible parameter types so a
      // marker never pretends to identify declarations the checker cannot
      // distinguish.
      const identity = overloadIdentity(declaration, renderer.renderType);
      const matching = bySignature.get(identity) ?? [];
      matching.push(declaration);
      bySignature.set(identity, matching);
    }
    for (const matching of bySignature.values()) {
      const declarationIds = matching.map(({ id }) => id).sort(compareCodeUnits);
      overloads.push({
        name,
        signature: signature(matching[0], renderer.renderType),
        marker: `__deherm_dmsdk_${sha256(declarationIds.join("\n")).slice(0, 20)}`,
        declarationIds
      });
    }
  }
  return overloads;
}

function signatureDocumentation(declaration) {
  const lines = [];
  const notes = (declaration.notes ?? []).filter((note) => note !== declaration.deprecated);
  if (notes.length) lines.push(`@remarks ${notes.join("\n\n")}`);
  if (declaration.deprecated) lines.push(`@deprecated ${declaration.deprecated}`);
  for (const [index, item] of (declaration.parameters ?? []).entries()) {
    if (item.description) lines.push(`@param ${parameter(item.name, index)} ${item.description}`);
  }
  if (declaration.returnDescription) lines.push(`@returns ${declaration.returnDescription}`);
  return lines.join("\n");
}

function publicRecordType(declaration, renderType) {
  const members = (declaration.members ?? []).filter(({ access }) => access === "public");
  if (!declaration.completeDefinition || !members.length) return `DmNativeType<${JSON.stringify(declaration.name)}>`;
  return `Readonly<{ ${members.map((member) => `${property(member.name)}: ${renderType(member.type, declaration.name)}`).join("; ")} }>`;
}

function resolvedEnumMembers(declaration) {
  let previous = -1;
  return (declaration.members ?? []).map((member) => {
    const value = member.value === undefined ? previous + 1 : member.value;
    assert.ok(Number.isSafeInteger(value), `${declaration.name}.${member.name} has no exact integer enum value`);
    previous = value;
    return { name: member.name, value };
  });
}

function enumExportName(declaration) {
  return pascalIdentifier(declaration.name);
}

function enumType(declaration) {
  return resolvedEnumMembers(declaration).length
    ? enumExportName(declaration)
    : `DmNativeType<${JSON.stringify(declaration.name)}>`;
}

export function generateTypes(ir, renderer) {
  const { renderType } = renderer;
  const groups = new Map();
  for (const declaration of ir.declarations.filter((item) => callableKinds.has(item.kind) && item.disposition === "generated-raw-call")) {
    const list = groups.get(declaration.name) ?? [];
    list.push(declaration);
    groups.set(declaration.name, list);
  }
  const lines = [
    banner,
    "declare const nativeTypeBrand: unique symbol;",
    "declare const nativePointerBrand: unique symbol;",
    "declare const nativeMutablePointerBrand: unique symbol;",
    "declare const nativeReferenceBrand: unique symbol;",
    "declare const nativeCallbackBrand: unique symbol;",
    "export type DmNativeType<Name extends string> = { readonly [nativeTypeBrand]: Name };",
    "export type DmReadonlyPointer<Pointee extends string = string> = number & { readonly [nativePointerBrand]: Pointee };",
    "export type DmPointer<Pointee extends string = string> = DmReadonlyPointer<Pointee> & { readonly [nativeMutablePointerBrand]: true };",
    "export type DmReference<Value = unknown> = DmPointer<\"reference\"> & { readonly value?: Value; readonly [nativeReferenceBrand]: true };",
    "export type DmNativeCallback = DmPointer<\"callback\"> & { readonly [nativeCallbackBrand]: true };",
    "export interface DmSpan<Value> { readonly data: DmPointer; readonly length: number; readonly __value?: Value; }",
    "",
    "export interface DmSdkCalls {"
  ];
  for (const [name, declarations] of [...groups].sort(([left], [right]) => compareCodeUnits(left, right))) {
    lines.push(...documentation(declarations.find(({ description }) => description)?.description, "  "));
    lines.push(`  readonly ${property(name)}: {`);
    const signatures = new Map();
    for (const declaration of declarations) {
      const identity = overloadIdentity(declaration, renderType);
      if (!signatures.has(identity)) signatures.set(identity, declaration);
    }
    for (const declaration of signatures.values()) {
      const item = signature(declaration, renderType);
      lines.push(...documentation(signatureDocumentation(declaration), "    "));
      lines.push(`    ${item};`);
    }
    lines.push("  };");
  }
  lines.push("}", "", "export type DmSdkSymbol = keyof DmSdkCalls;", "");
  lines.push("export interface DmSdkDeclarationCalls {");
  for (const declaration of ir.declarations.filter((item) => callableKinds.has(item.kind) && item.disposition === "generated-raw-call")) {
    lines.push(`  readonly ${JSON.stringify(declaration.id)}: ${functionType(declaration, renderType)};`);
  }
  lines.push("}", "");
  const typeGroups = new Map();
  for (const declaration of [...ir.declarations, ...(ir.typeSupportDeclarations ?? [])]
    .filter((item) => ["record", "enum", "type-alias"].includes(item.kind))) {
    const current = typeGroups.get(declaration.name);
    if (!current || (declaration.members?.length ?? 0) > (current.members?.length ?? 0)) typeGroups.set(declaration.name, declaration);
  }
  for (const declaration of [...typeGroups.values()].filter(({ kind }) => kind === "enum").sort((left, right) => compareCodeUnits(left.name, right.name))) {
    const members = resolvedEnumMembers(declaration);
    if (!members.length) continue;
    const name = enumExportName(declaration);
    lines.push(...documentation(declarationDocumentation({
      ...declaration,
      description: declaration.description || `Native enum ${declaration.name}.`
    }), ""));
    lines.push(`export const ${name} = {`);
    for (const member of members) lines.push(`  ${property(member.name)}: ${member.value},`);
    lines.push(`} as const;`, `export type ${name} = (typeof ${name})[keyof typeof ${name}];`, "");
  }
  lines.push("export interface DmSdkTypes {");
  for (const [name, declaration] of [...typeGroups].sort(([left], [right]) => compareCodeUnits(left, right))) {
    const type = declaration.kind === "record"
      ? publicRecordType(declaration, renderType)
      : declaration.kind === "enum"
        ? enumType(declaration)
        : renderType(declaration.type, declaration.name);
    lines.push(...documentation(declarationDocumentation(declaration), "  "));
    lines.push(`  readonly ${property(name)}: ${type};`);
  }
  lines.push("}", "");
  lines.push("export interface DmSdkVariables {");
  const variables = new Map();
  for (const declaration of ir.declarations.filter((item) => item.kind === "variable")) variables.set(declaration.name, declaration);
  for (const [name, declaration] of [...variables].sort(([left], [right]) => compareCodeUnits(left, right))) {
    lines.push(...documentation(declarationDocumentation(declaration), "  "));
    lines.push(`  readonly ${property(name)}: ${renderType(declaration.type, declaration.name)};`);
  }
  lines.push("}", "");
  lines.push("export interface DmSdkDeclarationMap {");
  for (const declaration of ir.declarations) {
    lines.push(`  readonly ${JSON.stringify(declaration.id)}: { readonly name: ${JSON.stringify(declaration.name)}; readonly kind: ${JSON.stringify(declaration.kind)}; readonly header: ${JSON.stringify(declaration.header)}; readonly disposition: ${JSON.stringify(declaration.disposition)} };`);
  }
  lines.push("}", "");
  return lines.join("\n");
}

export function generateRuntime(ir, renderer) {
  const lines = [
    banner,
    'import type { DmNativeCallback, DmNativeType, DmPointer, DmReadonlyPointer, DmReference, DmSdkDeclarationCalls, DmSdkTypes, DmSpan } from "./types";',
    "",
    "export interface DmSdkBridge {",
    "  call(symbol: string, args: readonly unknown[]): unknown;",
    "  callDeclaration(declarationId: string, symbol: string, args: readonly unknown[]): unknown;",
    "}",
    "",
    "let activeBridge: DmSdkBridge | undefined;",
    "",
    "export function installDmSdkBridge(bridge: DmSdkBridge): void {",
    "  activeBridge = bridge;",
    "}",
    ""
  ];
  for (const overload of dmSdkRuntimeOverloads(ir, renderer)) {
    const declaration = ir.declarations.find(({ id }) => id === overload.declarationIds[0]);
    const parameters = (declaration.parameters ?? []).map((item, index) => `${parameter(item.name, index)}: ${renderer.renderType(item.type, declaration.name)}`).join(", ");
    const result = renderer.renderType(declaration.returns ?? "void", declaration.name);
    lines.push(`export function callDmSdk(${overload.marker}: ${JSON.stringify(overload.name)}${parameters ? `, ${parameters}` : ""}): ${result};`);
  }
  lines.push(
    "export function callDmSdk(symbol: string, ...args: readonly unknown[]): unknown {",
    '  if (!activeBridge) throw new Error("dmSDK bridge has not been installed");',
    "  return activeBridge.call(symbol, args);",
    "}",
    "",
    "function dmSdkSymbolFromDeclarationId(declarationId: string): string {",
    '  const prefix = "dmsdk:";',
    "  const separator = declarationId.indexOf(\"@\", prefix.length);",
    '  if (declarationId.slice(0, prefix.length) !== prefix || separator < 0) throw new Error("invalid dmSDK declaration ID");',
    "  return declarationId.slice(prefix.length, separator);",
    "}",
    "",
    "export function callDmSdkDeclaration<Id extends keyof DmSdkDeclarationCalls>(",
    "  __deherm_dmsdk_exact: Id,",
    "  ...args: Parameters<DmSdkDeclarationCalls[Id]>",
    "): ReturnType<DmSdkDeclarationCalls[Id]> {",
    '  if (!activeBridge) throw new Error("dmSDK bridge has not been installed");',
    "  return activeBridge.callDeclaration(",
    "    __deherm_dmsdk_exact,",
    "    dmSdkSymbolFromDeclarationId(__deherm_dmsdk_exact),",
    "    args,",
    "  ) as ReturnType<DmSdkDeclarationCalls[Id]>;",
    "}",
    ""
  );
  return lines.join("\n");
}

async function output(file, contents) {
  const normalized = contents.endsWith("\n") ? contents : `${contents}\n`;
  if (check) {
    let current;
    try { current = await readFile(file, "utf8"); } catch { current = undefined; }
    assert.equal(current, normalized, `${path.relative(root, file)} is stale; run npm run generate:dmsdk-sdk`);
    return;
  }
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, normalized);
}

export async function runDmSdkGenerator() {
  const { unzipSync } = await import("fflate");
  const inventory = JSON.parse(await readFile(inventoryPath, "utf8"));
  const referenceArchive = unzipSync(new Uint8Array(await readFile(path.join(root, "upstream", "ref-doc.zip"))));
  const ir = enrich({ ...inventory, declarations: attachDocumentation(inventory, docsByHeader(referenceArchive)) });
  const renderer = createTypeRenderer(ir);
  const typesSource = generateTypes(ir, renderer);
  const runtimeSource = generateRuntime(ir, renderer);
  ir.unresolvedTypes = [...renderer.unresolved]
    .sort(([left], [right]) => compareCodeUnits(left, right))
    .map(([name, contexts]) => ({ name, contexts: [...contexts].sort() }));
  ir.opaqueTypes = [...renderer.opaque]
    .sort(([left], [right]) => compareCodeUnits(left, right))
    .map(([name, item]) => ({ name, reason: item.reason, contexts: [...item.contexts].sort() }));
  ir.typeSurfaceUnresolvedCount = ir.unresolvedTypes.length;
  // Notes and deprecation tags are documentation inputs for generated
  // TypeScript. They are deliberately excluded from the runtime IR so prose
  // changes do not invalidate ABI classifications or executable evidence.
  const runtimeIr = {
    ...ir,
    declarations: ir.declarations.map(({ deprecated: _deprecated, notes: _notes, ...declaration }) => declaration)
  };
  await output(irPath, JSON.stringify(runtimeIr, null, 2));
  await output(path.join(generatedRoot, "types.ts"), typesSource);
  await output(path.join(generatedRoot, "runtime.ts"), runtimeSource);
  await output(
    path.join(generatedRoot, "index.ts"),
    `${banner}\nexport * from "./types";\nexport * from "./runtime";\nexport * from "./scalar";\nexport * from "./enum-value";\nexport * from "./universal";\n`,
  );
  console.log(
    `${check ? "checked" : "generated"} ${ir.declarationCount} dmSDK declarations, ` +
    `${Object.keys(inventory.countsByKind).length} kinds, ${ir.typeSurfaceUnresolvedCount} type-surface unresolved, ` +
    `${ir.runtimeUnimplementedCount} runtime bindings pending`,
  );
}

