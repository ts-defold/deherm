export const SCRIPT_CALLBACK_LIFECYCLE_FACTS = "defold-script-callback-lifecycle-recipe-facts.json";

const LIFETIMES = Object.freeze({
  "one-shot": "kOneShot",
  "terminal-event": "kTerminalEvent",
  "persistent-replaceable": "kPersistentReplaceable",
  "higher-order-closure": "kHigherOrderClosure",
});

function assertFacts(facts) {
  if (
    facts?.schemaVersion !== 1 ||
    facts.kind !== "deherm.recipe.script-callback-lifecycle-output" ||
    !Array.isArray(facts.routes) ||
    facts.routes.some(
      (row) =>
        typeof row.id !== "string" ||
        !Number.isInteger(row.stableId) ||
        !LIFETIMES[row.lifetime] ||
        typeof row.callbackParameter !== "string" ||
        typeof row.owner !== "string" ||
        typeof row.invocationContext !== "string" ||
        typeof row.threadAffinity !== "string" ||
        typeof row.registryEligible !== "boolean" ||
        !Array.isArray(row.payloadBlockers),
    ) ||
    !facts.targetSupport
  ) {
    throw new Error("Unsupported script callback-lifecycle recipe facts");
  }
  return facts.routes;
}

function quote(value) {
  return JSON.stringify(value).replaceAll("\u2028", "\\u2028").replaceAll("\u2029", "\\u2029");
}

export function createScriptCallbackLifecycleRecipeFacts(report) {
  return {
    schemaVersion: 1,
    kind: "deherm.recipe.script-callback-lifecycle-output",
    targetSupport: report.targetSupport,
    routes: report.routes.map(
      ({
        id,
        stableId,
        callbackParameter,
        lifetime,
        owner,
        invocationContext,
        threadAffinity,
        registryEligible,
        payloadBlockers,
      }) => ({
        id,
        stableId,
        callbackParameter,
        lifetime,
        owner,
        invocationContext,
        threadAffinity,
        registryEligible,
        payloadBlockers,
      }),
    ),
  };
}

export function renderScriptCallbackLifecycleOutputs(facts) {
  const rows = assertFacts(facts);
  const targetSupport = {
    nativeDynamicHermes: facts.targetSupport.nativeDynamicHermes,
    nativeStaticHermes: facts.targetSupport.nativeStaticHermes,
    html5BrowserHost: facts.targetSupport.html5BrowserHost,
  };
  const header = `// Generated by scripts/generate-script-callback-lifecycle.mjs. Do not edit.\n#pragma once\n\n#include <cstddef>\n#include <cstdint>\n#include <defold_hermes/callback_lifecycle_registry.hpp>\n\nnamespace defold_hermes::callback_lifecycle {\nstruct Route { uint16_t index; uint32_t stableId; const char* canonicalId; const char* callbackParameter; Lifetime lifetime; const char* owner; const char* invocationContext; const char* threadAffinity; bool registryEligible; };\ninline constexpr size_t kRouteCount = ${rows.length};\nconst Route* routes() noexcept;\nconst Route* find(uint32_t stableId) noexcept;\n}  // namespace defold_hermes::callback_lifecycle\n`;
  const entries = rows.length
    ? rows
        .map(
          (row, index) =>
            `  {${index}, ${row.stableId}u, ${quote(row.id)}, ${quote(row.callbackParameter)}, Lifetime::${LIFETIMES[row.lifetime]}, ${quote(row.owner)}, ${quote(row.invocationContext)}, ${quote(row.threadAffinity)}, ${row.registryEligible ? "true" : "false"}},`,
        )
        .join("\n")
    : "  {},  // sentinel storage; kRouteCount remains zero";
  const source = `// Generated by scripts/generate-script-callback-lifecycle.mjs. Do not edit.\n#include <defold_hermes/generated_script_callback_lifecycle.hpp>\n\nnamespace defold_hermes::callback_lifecycle {\nnamespace {\nconstexpr Route kRoutes[] = {\n${entries}\n};\n}  // namespace\nconst Route* routes() noexcept { return kRoutes; }\nconst Route* find(uint32_t stableId) noexcept { size_t first=0,count=kRouteCount; while(count){const size_t step=count/2;const size_t index=first+step;if(kRoutes[index].stableId<stableId){first=index+1;count-=step+1;}else count=step;} return first<kRouteCount&&kRoutes[first].stableId==stableId?&kRoutes[first]:nullptr; }\n}  // namespace defold_hermes::callback_lifecycle\n`;
  const targetRows = rows.map(
    ({
      id,
      stableId,
      callbackParameter,
      lifetime,
      owner,
      invocationContext,
      threadAffinity,
      registryEligible,
      payloadBlockers,
    }) => ({
      id,
      stableId: `0x${stableId.toString(16).padStart(8, "0")}`,
      callbackParameter,
      lifetime,
      owner,
      invocationContext,
      threadAffinity,
      registryEligible,
      payloadBlockers,
    }),
  );
  const target = `// Generated by scripts/generate-script-callback-lifecycle.mjs. Do not edit.\nexport type ScriptCallbackLifetime = "one-shot" | "terminal-event" | "persistent-replaceable" | "higher-order-closure";\nexport const scriptCallbackLifecycleRoutes = ${JSON.stringify(targetRows, null, 2)} as const;\nexport const scriptCallbackLifecycleRouteCount = ${targetRows.length} as const;\n/** Metadata only: engine-specific route adapters and payload codecs are intentionally not exposed here. */\nexport const scriptCallbackLifecycleTargetSupport = ${JSON.stringify(targetSupport, null, 2)} as const;\n`;
  return { header, source, target };
}
