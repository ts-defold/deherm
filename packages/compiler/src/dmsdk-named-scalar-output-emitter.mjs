export const DMSDK_NAMED_SCALAR_RECIPE_FACTS_NAME = "defold-dmsdk-named-scalar-recipe-facts.json";

export function createDmSdkNamedScalarRecipeFacts(entries) {
  return {
    schemaVersion: 1,
    kind: "deherm.recipe.dmsdk-named-scalar-output",
    entries: entries.map((entry) => ({
      bindingId: entry.bindingId,
      declarationId: entry.declarationId,
      symbol: entry.symbol,
      wrapper: entry.wrapper,
      include: entry.include,
      result: entry.result,
      parameters: entry.parameters,
    })),
  };
}

function entriesFrom(facts) {
  if (
    facts?.schemaVersion !== 1 ||
    facts?.kind !== "deherm.recipe.dmsdk-named-scalar-output" ||
    !Array.isArray(facts.entries)
  )
    throw new Error("Unsupported dmSDK named-scalar output recipe facts");
  for (const [index, entry] of facts.entries.entries()) {
    if (
      entry.bindingId !== index ||
      typeof entry.declarationId !== "string" ||
      typeof entry.symbol !== "string" ||
      typeof entry.wrapper !== "string" ||
      typeof entry.include !== "string" ||
      !entry.result ||
      !Array.isArray(entry.parameters)
    )
      throw new Error(`Invalid dmSDK named-scalar recipe entry ${index}`);
  }
  return facts.entries;
}
function publicDeclaration(entry) {
  const p = entry.parameters.map((x) => `${x.c} ${x.name}`).join(", ");
  return `${entry.result.c} ${entry.wrapper}(${p || "void"});`;
}
function nativeArgument(p) {
  return p.native === p.c ? p.name : `static_cast<${p.native}>(${p.name})`;
}
function wrapperDefinition(entry) {
  const p = entry.parameters.map((x) => `${x.c} ${x.name}`).join(", ");
  const call = `${entry.symbol}(${entry.parameters.map(nativeArgument).join(", ")})`;
  const statement =
    entry.result.lane === "void"
      ? `${call};`
      : entry.result.lane === "bool"
        ? `return ${call} ? UINT8_C(1) : UINT8_C(0);`
        : entry.result.native !== entry.result.c
          ? `return static_cast<${entry.result.c}>(${call});`
          : `return ${call};`;
  return `${entry.result.c} ${entry.wrapper}(${p || "void"})\n{\n  ${statement}\n}`;
}
function nativePrototype(entry) {
  const p = entry.parameters.map((x) => `${x.native} ${x.name}`).join(", ");
  return `${entry.result.native} ${entry.symbol}(${p || "void"});`;
}
function rawArgument(p, i) {
  const raw = `arguments[${i}]`;
  if (p.lane === "f32") return `unpack_f32(${raw})`;
  if (p.lane === "f64") return `unpack_f64(${raw})`;
  if (p.lane === "i32") return `unpack_i32(${raw})`;
  if (p.lane === "i64") return `unpack_i64(${raw})`;
  return `static_cast<${p.c}>(${raw})`;
}
function rawResult(entry) {
  const call = `${entry.wrapper}(${entry.parameters.map(rawArgument).join(", ")})`;
  if (entry.result.lane === "void") return `${call};\n      *result = UINT64_C(0);`;
  if (entry.result.lane === "f32") return `*result = pack_f32(${call});`;
  if (entry.result.lane === "f64") return `*result = pack_f64(${call});`;
  if (entry.result.lane === "i32" || entry.result.lane === "i64")
    return `*result = static_cast<uint64_t>(static_cast<int64_t>(${call}));`;
  return `*result = static_cast<uint64_t>(${call});`;
}
function rawGuard(p, i) {
  const raw = `arguments[${i}]`;
  if (p.lane === "bool") return `${raw} > UINT64_C(1)`;
  if (p.lane === "i32") return `${raw} != static_cast<uint64_t>(static_cast<int64_t>(static_cast<int32_t>(${raw})))`;
  if (p.lane === "u32" || p.lane === "f32") return `${raw} > UINT32_MAX`;
  if (p.lane === "usize") return `${raw} > static_cast<uint64_t>(UINTPTR_MAX)`;
  return null;
}
function renderHeader(entries) {
  return `// Generated by scripts/generate-dmsdk-named-scalar-bindings.mjs. Do not edit.
#ifndef DEFOLD_HERMES_GENERATED_DMSDK_NAMED_SCALAR_H
#define DEFOLD_HERMES_GENERATED_DMSDK_NAMED_SCALAR_H

#include <stdint.h>

#ifdef __cplusplus
extern "C" {
#endif

${entries.map(publicDeclaration).join("\n")}

#ifdef __cplusplus
} // extern "C"
#endif

#endif // DEFOLD_HERMES_GENERATED_DMSDK_NAMED_SCALAR_H
`;
}
