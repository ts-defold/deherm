export const DMSDK_SCALAR_RECIPE_FACTS_NAME = "defold-dmsdk-scalar-recipe-facts.json";

const ABI_TYPES = Object.freeze({
  void: { c: "void" },
  bool: { c: "uint8_t" },
  uint16_t: { c: "uint16_t" },
  uint32_t: { c: "uint32_t" },
  uint64_t: { c: "uint64_t" },
  float: { c: "float" },
});
const VALUE_KINDS = Object.freeze({
  void: "DEHERM_DMSDK_SCALAR_VOID",
  bool: "DEHERM_DMSDK_SCALAR_BOOL",
  uint16_t: "DEHERM_DMSDK_SCALAR_U16",
  uint32_t: "DEHERM_DMSDK_SCALAR_U32",
  uint64_t: "DEHERM_DMSDK_SCALAR_U64",
  float: "DEHERM_DMSDK_SCALAR_F32",
});
const FLAG_NATIVE_JS = 1;
const FLAG_BROWSER_JS = 2;
const FLAG_MAY_BLOCK = 4;

export function createDmSdkScalarRecipeFacts(entries) {
  return {
    schemaVersion: 1,
    kind: "deherm.recipe.dmsdk-scalar-output",
    entries: entries.map(({ bindingId, wrapper, declaration, semantics }) => ({
      bindingId,
      wrapper,
      declaration: {
        id: declaration.id,
        name: declaration.name,
        type: declaration.type,
        header: declaration.header,
        returns: declaration.returns,
        parameters: declaration.parameters.map(({ name, type }) => ({ name, type })),
      },
      semantics: { pureValueTransform: semantics.pureValueTransform, mayBlock: semantics.mayBlock },
    })),
  };
}

function validateFacts(facts) {
  if (
    facts?.schemaVersion !== 1 ||
    facts?.kind !== "deherm.recipe.dmsdk-scalar-output" ||
    !Array.isArray(facts.entries)
  )
    throw new Error("Unsupported dmSDK scalar output recipe facts");
  for (const [index, entry] of facts.entries.entries()) {
    if (entry.bindingId !== index || typeof entry.wrapper !== "string" || !entry.declaration || !entry.semantics)
      throw new Error(`Invalid dmSDK scalar output recipe entry ${index}`);
    if (
      !ABI_TYPES[entry.declaration.returns] ||
      !Array.isArray(entry.declaration.parameters) ||
      entry.declaration.parameters.some(({ type }) => !ABI_TYPES[type])
    )
      throw new Error(`${entry.declaration.id}: unsupported scalar recipe ABI`);
  }
  return facts.entries;
}

function tsName(entry) {
  const words = entry.wrapper.replace(/^deherm_dmsdk_/, "").split("_");
  return (
    words[0] +
    words
      .slice(1)
      .map((word) => word[0].toUpperCase() + word.slice(1))
      .join("")
  );
}
function publicInclude(header) {
  const marker = "/dmsdk/";
  const index = header.indexOf(marker);
  if (index < 0) throw new Error(`No public dmSDK include path in ${header}`);
  return `dmsdk/${header.slice(index + marker.length)}`;
}
function abiDeclaration(declaration, name) {
  const parameters = declaration.parameters.map((p) => `${ABI_TYPES[p.type].c} ${p.name}`).join(", ");
  return `${ABI_TYPES[declaration.returns].c} ${name}(${parameters || "void"});`;
}
function abiDefinition(declaration, name) {
  const parameters = declaration.parameters.map((p) => `${ABI_TYPES[p.type].c} ${p.name}`).join(", ");
  const call = `${declaration.name}(${declaration.parameters.map(({ name: n }) => n).join(", ")})`;
  const body =
    declaration.returns === "void"
      ? `    ${call};`
      : declaration.returns === "bool"
        ? `    return ${call} ? UINT8_C(1) : UINT8_C(0);`
        : `    return ${call};`;
  return `${ABI_TYPES[declaration.returns].c} ${name}(${parameters || "void"})\n{\n${body}\n}`;
}
function isBrowserSafe(entry) {
  return (
    ![entry.declaration.returns, ...entry.declaration.parameters.map(({ type }) => type)].includes("uint64_t") &&
    entry.semantics.pureValueTransform &&
    !entry.semantics.mayBlock
  );
}

function renderHeader(entries) {
  return `// Generated by scripts/generate-dmsdk-scalar-thunks.mjs. Do not edit.\n#ifndef DEFOLD_HERMES_GENERATED_DMSDK_SCALAR_H\n#define DEFOLD_HERMES_GENERATED_DMSDK_SCALAR_H\n\n#include <stdint.h>\n\n#ifdef __cplusplus\nextern "C" {\n#endif\n\n${entries.map((e) => abiDeclaration(e.declaration, e.wrapper)).join("\n")}\n\n#ifdef __cplusplus\n} // extern "C"\n#endif\n\n#endif // DEFOLD_HERMES_GENERATED_DMSDK_SCALAR_H\n`;
}
function renderSource(entries) {
  const includes = [...new Set(entries.map(({ declaration }) => publicInclude(declaration.header)))]
    .sort()
    .map((x) => `#include <${x}>`)
    .join("\n");
  return `// Generated by scripts/generate-dmsdk-scalar-thunks.mjs. Do not edit.\n#include <defold_hermes/generated_dmsdk_scalar.h>\n\n#ifndef DLIB_LOG_DOMAIN\n#define DLIB_LOG_DOMAIN "defold_hermes"\n#endif\n${includes}\n\nextern "C" {\n\n${entries.map((e) => abiDefinition(e.declaration, e.wrapper)).join("\n\n")}\n\n} // extern "C"\n`;
}
function renderRuntimeHeader(entries) {
  const max = Math.max(1, ...entries.map(({ declaration }) => declaration.parameters.length));
  return `// Generated by scripts/generate-dmsdk-scalar-thunks.mjs. Do not edit.\n#ifndef DEFOLD_HERMES_GENERATED_DMSDK_SCALAR_RUNTIME_H\n#define DEFOLD_HERMES_GENERATED_DMSDK_SCALAR_RUNTIME_H\n\n#include <stdint.h>\n\n#define DEHERM_DMSDK_SCALAR_MAX_ARGUMENTS ${max}\n\ntypedef enum DehermDmSdkScalarValueKind {\n  DEHERM_DMSDK_SCALAR_VOID = 0,\n  DEHERM_DMSDK_SCALAR_BOOL = 1,\n  DEHERM_DMSDK_SCALAR_U16 = 2,\n  DEHERM_DMSDK_SCALAR_U32 = 3,\n  DEHERM_DMSDK_SCALAR_U64 = 4,\n  DEHERM_DMSDK_SCALAR_F32 = 5\n} DehermDmSdkScalarValueKind;\n\ntypedef enum DehermDmSdkScalarStatus {\n  DEHERM_DMSDK_SCALAR_OK = 0,\n  DEHERM_DMSDK_SCALAR_UNKNOWN_ID = 1,\n  DEHERM_DMSDK_SCALAR_WRONG_ARITY = 2,\n  DEHERM_DMSDK_SCALAR_NULL_STORAGE = 3\n} DehermDmSdkScalarStatus;\n\ntypedef enum DehermDmSdkScalarFlags {\n  DEHERM_DMSDK_SCALAR_NATIVE_JS = ${FLAG_NATIVE_JS},\n  DEHERM_DMSDK_SCALAR_BROWSER_JS = ${FLAG_BROWSER_JS},\n  DEHERM_DMSDK_SCALAR_MAY_BLOCK = ${FLAG_MAY_BLOCK}\n} DehermDmSdkScalarFlags;\n\ntypedef struct DehermDmSdkScalarDescriptor {\n  uint16_t id;\n  uint8_t argument_count;\n  uint8_t return_kind;\n  uint8_t argument_kinds[DEHERM_DMSDK_SCALAR_MAX_ARGUMENTS];\n  uint8_t flags;\n  const char* declaration_id;\n  const char* symbol;\n} DehermDmSdkScalarDescriptor;\n\n#ifdef __cplusplus\nextern "C" {\n#endif\n\nuint32_t deherm_dmsdk_scalar_count(void);\nconst DehermDmSdkScalarDescriptor* deherm_dmsdk_scalar_descriptors(void);\nDehermDmSdkScalarStatus deherm_dmsdk_scalar_dispatch(\n    uint16_t id, const uint64_t* arguments, uint32_t argument_count, uint64_t* result);\n\n#ifdef __cplusplus\n} // extern "C"\n#endif\n\n#endif // DEFOLD_HERMES_GENERATED_DMSDK_SCALAR_RUNTIME_H\n`;
}
function rawArgument(parameter, index) {
  return parameter.type === "float"
    ? `unpack_f32(arguments[${index}])`
    : `static_cast<${ABI_TYPES[parameter.type].c}>(arguments[${index}])`;
}
function rawResult(entry) {
  const call = `${entry.wrapper}(${entry.declaration.parameters.map(rawArgument).join(", ")})`;
  if (entry.declaration.returns === "void") return `      ${call};\n      *result = UINT64_C(0);`;
  if (entry.declaration.returns === "float") return `      *result = pack_f32(${call});`;
  return `      *result = static_cast<uint64_t>(${call});`;
}
function renderRuntimeSource(entries) {
  const max = Math.max(1, ...entries.map(({ declaration }) => declaration.parameters.length));
  const descriptors = entries
    .map((entry) => {
      const kinds = entry.declaration.parameters.map(({ type }) => VALUE_KINDS[type]);
      while (kinds.length < max) kinds.push("DEHERM_DMSDK_SCALAR_VOID");
      let flags = FLAG_NATIVE_JS;
      if (isBrowserSafe(entry)) flags |= FLAG_BROWSER_JS;
      if (entry.semantics.mayBlock) flags |= FLAG_MAY_BLOCK;
      return `  { UINT16_C(${entry.bindingId}), UINT8_C(${entry.declaration.parameters.length}), ${VALUE_KINDS[entry.declaration.returns]}, { ${kinds.join(", ")} }, UINT8_C(${flags}), ${JSON.stringify(entry.declaration.id)}, ${JSON.stringify(entry.declaration.name)} }`;
    })
    .join(",\n");
  const cases = entries
    .map((entry) => `    case ${entry.bindingId}:\n${rawResult(entry)}\n      return DEHERM_DMSDK_SCALAR_OK;`)
    .join("\n");
  return `// Generated by scripts/generate-dmsdk-scalar-thunks.mjs. Do not edit.\n#include <defold_hermes/generated_dmsdk_scalar.h>\n#include <defold_hermes/generated_dmsdk_scalar_runtime.h>\n\n#include <cstring>\n\nnamespace {\nconst DehermDmSdkScalarDescriptor kDescriptors[] = {\n${descriptors}\n};\n\nuint64_t pack_f32(float value)\n{\n  uint32_t bits = 0;\n  static_assert(sizeof(bits) == sizeof(value), "float must be 32-bit");\n  std::memcpy(&bits, &value, sizeof(bits));\n  return bits;\n}\n\nfloat unpack_f32(uint64_t value)\n{\n  const uint32_t bits = static_cast<uint32_t>(value);\n  float result = 0.0f;\n  std::memcpy(&result, &bits, sizeof(result));\n  return result;\n}\n} // namespace\n\nextern "C" {\n\nuint32_t deherm_dmsdk_scalar_count(void)\n{\n  return UINT32_C(${entries.length});\n}\n\nconst DehermDmSdkScalarDescriptor* deherm_dmsdk_scalar_descriptors(void)\n{\n  return kDescriptors;\n}\n\nDehermDmSdkScalarStatus deherm_dmsdk_scalar_dispatch(\n    uint16_t id, const uint64_t* arguments, uint32_t argument_count, uint64_t* result)\n{\n  if (id >= deherm_dmsdk_scalar_count()) return DEHERM_DMSDK_SCALAR_UNKNOWN_ID;\n  const DehermDmSdkScalarDescriptor& descriptor = kDescriptors[id];\n  if (argument_count != descriptor.argument_count) return DEHERM_DMSDK_SCALAR_WRONG_ARITY;\n  if (result == nullptr || (argument_count != 0 && arguments == nullptr)) return DEHERM_DMSDK_SCALAR_NULL_STORAGE;\n  switch (id) {\n${cases}\n    default:\n      return DEHERM_DMSDK_SCALAR_UNKNOWN_ID;\n  }\n}\n\n} // extern "C"\n`;
}

const JSI_HEADER = `// Generated by scripts/generate-dmsdk-scalar-thunks.mjs. Do not edit.\n#pragma once\n\n#if !defined(DM_PLATFORM_HTML5)\n#include <jsi/jsi.h>\nnamespace defold_hermes {\nvoid installDmSdkScalarModule(facebook::jsi::Runtime& runtime, facebook::jsi::Object& modules);\n}\n#endif\n`;
