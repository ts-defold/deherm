export const SCRIPT_DYNAMIC_VALUES_FACTS = "defold-script-dynamic-values-recipe-facts.json";

function validate(facts) {
  if (
    facts?.schemaVersion !== 1 ||
    facts.kind !== "deherm.recipe.script-dynamic-values-output" ||
    !Number.isInteger(facts.maximumArgumentCount) ||
    !Array.isArray(facts.candidates) ||
    facts.candidates.some(
      (row, index) =>
        row.index !== index ||
        typeof row.id !== "string" ||
        typeof row.stableId !== "string" ||
        !/^0x[0-9a-f]{8}$/.test(row.stableId) ||
        !Array.isArray(row.modulePath) ||
        typeof row.member !== "string" ||
        !["exact-lua-call", "exact-lua-type-query"].includes(row.strategy) ||
        !["number", "boolean", "variable-values"].includes(row.resultMode) ||
        !Number.isInteger(row.minimumArguments) ||
        row.minimumArguments < 0 ||
        row.minimumArguments > facts.maximumArgumentCount ||
        typeof row.optimizationProven !== "boolean",
    )
  ) {
    throw new Error("Unsupported script dynamic-values recipe facts");
  }
  return facts.candidates;
}

function cpp(value) {
  return JSON.stringify(value);
}
function enumName(value) {
  return value
    .split("-")
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");
}

export function createScriptDynamicValuesRecipeFacts(report) {
  return {
    schemaVersion: 1,
    kind: "deherm.recipe.script-dynamic-values-output",
    maximumArgumentCount: report.maximumArgumentCount,
    candidates: report.bindings
      .filter(({ generatedFamilyExecutableCandidate }) => generatedFamilyExecutableCandidate)
      .map((row, index) => ({
        index,
        id: row.id,
        stableId: row.stableId,
        modulePath: row.modulePath,
        member: row.member,
        strategy: row.strategy,
        resultMode: row.resultMode,
        minimumArguments: row.minimumArguments,
        maximumArguments: row.maximumArguments,
        optimizationProven: row.optimizationProven,
      })),
  };
}

