export const SCRIPT_OPAQUE_RECORD_BLOCKERS_FACTS = "defold-script-opaque-record-blockers-recipe-facts.json";

function validate(facts) {
  if (
    facts?.schemaVersion !== 1 ||
    facts.kind !== "deherm.recipe.script-opaque-record-blockers-output" ||
    !Array.isArray(facts.routes)
  ) {
    throw new Error("Unsupported opaque-record blocker recipe facts");
  }
  const ids = new Set();
  const stableIds = new Set();
  let previous = -1;
  for (const route of facts.routes) {
    if (
      typeof route?.id !== "string" ||
      !route.id.startsWith("script:") ||
      !/^0x[0-9a-f]{8}$/.test(route.stableId) ||
      typeof route.blocker !== "string" ||
      !route.blocker
    ) {
      throw new Error("Invalid opaque-record blocker recipe route");
    }
    const stableId = Number.parseInt(route.stableId.slice(2), 16);
    if (ids.has(route.id) || stableIds.has(route.stableId) || stableId < previous) {
      throw new Error("Opaque-record blocker recipe routes are not unique and ordered");
    }
    ids.add(route.id);
    stableIds.add(route.stableId);
    previous = stableId;
  }
  return facts;
}

export function renderScriptOpaqueRecordBlockersOutput(input) {
  const facts = validate(input);
  const routes = facts.routes.map(({ id, stableId, blocker }) => ({ id, stableId, blocker }));
  return `// Generated by scripts/generate-script-opaque-record-blockers.mjs. Do not edit.\nexport const scriptOpaqueRecordBlockers = ${JSON.stringify(
    routes,
    null,
    2,
  )} as const;\nexport function assertScriptOpaqueRecordTargetSupport(_: number): never { throw new Error("Opaque render records have no generated provider: borrowed userdata and command-queue ownership are not represented"); }\n`;
}
