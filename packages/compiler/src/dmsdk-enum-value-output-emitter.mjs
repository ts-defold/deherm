export function renderDmSdkEnumValueOutputs(facts) {
  const entries = entriesFrom(facts);
  const sources = {};
  for (const name of [...new Set(entries.map((e) => e.group.name))].sort()) {
    const selected = entries.filter((e) => e.group.name === name);
    sources[name] = renderSource(selected[0].group, selected);
  }
  return Object.freeze({
    header: renderHeader(entries),
    sources: Object.freeze(sources),
    runtimeHeader: renderRuntimeHeader(entries),
    runtime: renderRuntime(entries),
    jsiHeader: JSI_HEADER,
    jsi: JSI,
    typescript: renderTypeScript(entries),
  });
}
