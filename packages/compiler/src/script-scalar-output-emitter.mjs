// Package-owned renderer for the scalar Lua dispatch family. Classification
// and codec selection remain source-derived; this module projects the
// authenticated semantic report into byte-stable native artifacts.

import { hexBindingId } from "./binding-identity.mjs";

function cppString(value) {
  return JSON.stringify(value);
}

export function renderScriptScalarArtifacts(report) {
  if (report?.schemaVersion !== 1) throw new Error("script scalar report schemaVersion must be 1");
  if (!Array.isArray(report.bindings)) throw new Error("script scalar report has no bindings");
  const bindings = report.bindings;
  const argumentsFlat = bindings.flatMap((binding) => binding.parameters);
  if (report.bindingCount !== bindings.length) throw new Error("script scalar binding count is inconsistent");
  if (report.argumentCodecCount !== argumentsFlat.length)
    throw new Error("script scalar argument codec count is inconsistent");
  if (report.maxArgumentCount !== Math.max(...bindings.map((binding) => binding.maximumArgumentCount)))
    throw new Error("script scalar maximum argument count is inconsistent");

  const header = `// Generated by scripts/generate-scalar-lua-dispatch.mjs. Do not edit.
#pragma once

#include <cstddef>
#include <cstdint>

namespace defold_hermes::lua_bridge::scalar::generated {

inline constexpr size_t kBindingCount = ${bindings.length};
inline constexpr size_t kArgumentCodecCount = ${argumentsFlat.length};
inline constexpr size_t kMaxArgumentCount = ${report.maxArgumentCount};

enum class BindingId : uint32_t {
${bindings.map((binding) => `  ${binding.enumName} = ${hexBindingId(binding.stableId)},`).join("\n")}
};

}  // namespace defold_hermes::lua_bridge::scalar::generated
`;

  let argumentOffset = 0;
  const offsets = [0];
  for (const binding of bindings) {
    argumentOffset += binding.parameters.length;
    offsets.push(argumentOffset);
  }
  const source = `// Generated by scripts/generate-scalar-lua-dispatch.mjs. Do not edit.
#include <defold_hermes/scalar_lua_dispatch.hpp>

namespace defold_hermes::lua_bridge::scalar::generated {
namespace {
constexpr uint32_t kStableIds[] = {
${bindings.map((binding) => `  ${hexBindingId(binding.stableId)},  // ${binding.id}`).join("\n")}
};
constexpr const char* kCanonicalIds[] = {
${bindings.map((binding) => `  ${cppString(binding.id)},`).join("\n")}
};
constexpr const char* kModulePaths[] = {
${bindings.map((binding) => `  ${cppString(binding.modulePath)},`).join("\n")}
};
constexpr const char* kMembers[] = {
${bindings.map((binding) => `  ${cppString(binding.member)},`).join("\n")}
};
constexpr uint16_t kArgumentOffsets[] = {
  ${offsets.join(", ")}
};
constexpr ScalarCodec kArgumentCodecs[] = {
${argumentsFlat.map((argument) => `  ScalarCodec::k${argument.codec},`).join("\n")}
};
constexpr uint8_t kArgumentOptional[] = {
  ${argumentsFlat.map((argument) => (argument.optional ? 1 : 0)).join(", ")}
};
constexpr uint8_t kRequiredArgumentCounts[] = {
  ${bindings.map((binding) => binding.requiredArgumentCount).join(", ")}
};
constexpr uint8_t kMaximumArgumentCounts[] = {
  ${bindings.map((binding) => binding.maximumArgumentCount).join(", ")}
};
constexpr ScalarCodec kResultCodecs[] = {
${bindings.map((binding) => `  ScalarCodec::k${binding.result.codec},`).join("\n")}
};
constexpr uint8_t kResultNullable[] = {
  ${bindings.map((binding) => (binding.result.nullable ? 1 : 0)).join(", ")}
};
constexpr ScalarBindingTables kTables{
  kBindingCount, kArgumentCodecCount, kStableIds, kCanonicalIds, kModulePaths, kMembers,
  kArgumentOffsets, kArgumentCodecs, kArgumentOptional, kRequiredArgumentCounts,
  kMaximumArgumentCounts, kResultCodecs, kResultNullable
};
}  // namespace

const ScalarBindingTables& tables() noexcept { return kTables; }

}  // namespace defold_hermes::lua_bridge::scalar::generated
`;
  return { header, source };
}
