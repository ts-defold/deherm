// Package-owned renderers for the source-selected Static Hermes vmath ABI.
// Recipe facts contain an already-classified binding/shape inventory. This
// module validates and renders it; it does not inspect selectors or reselect.

const banner = "Generated by scripts/generate-static-hermes-vmath.mjs. Do not edit.";
const lanesByCodec = Object.freeze({
  Vector3: ["x", "y", "z"],
  Vector4: ["x", "y", "z", "w"],
  Quaternion: ["x", "y", "z", "w"],
});

function validateFacts(facts) {
  if (!facts || facts.schemaVersion !== 1 || !Array.isArray(facts.bindings)) {
    throw new Error("Static Hermes vmath output facts have an unsupported schema");
  }
  const ids = new Set();
  const stableIds = new Set();
  for (const binding of facts.bindings) {
    if (
      typeof binding.id !== "string" ||
      !Number.isInteger(binding.stableId) ||
      binding.stableId < 0 ||
      binding.stableId > 0xffffffff ||
      !Array.isArray(binding.shapes)
    )
      throw new Error(`Malformed Static Hermes vmath binding: ${JSON.stringify(binding?.id)}`);
    if (ids.has(binding.id) || stableIds.has(binding.stableId)) {
      throw new Error(`Duplicate Static Hermes vmath binding identity '${binding.id}'`);
    }
    ids.add(binding.id);
    stableIds.add(binding.stableId);
    const shapeKeys = new Set();
    for (const shape of binding.shapes) {
      if (
        !Array.isArray(shape.codecs) ||
        shape.codecs.length === 0 ||
        shape.codecs.some((codec) => !(codec in lanesByCodec)) ||
        typeof shape.cFunction !== "string" ||
        !/^deherm_static_vmath_[a-f0-9]{8}_[a-z0-9_]+$/u.test(shape.cFunction) ||
        typeof shape.wrapper !== "string" ||
        !/^vmath[A-Z][A-Za-z0-9]*$/u.test(shape.wrapper)
      )
        throw new Error(`${binding.id}: malformed Static Hermes vmath call shape`);
      const key = shape.codecs.join(",");
      if (shapeKeys.has(key)) throw new Error(`${binding.id}: duplicate Static Hermes vmath call shape ${key}`);
      shapeKeys.add(key);
    }
    if (binding.shapes.length === 0) throw new Error(`${binding.id}: no Static Hermes vmath call shapes`);
  }
  return facts;
}

function flattenedParameters(shape) {
  return shape.flatMap((codec, argumentIndex) =>
    lanesByCodec[codec].map((lane) => ({
      cName: `arg${argumentIndex}_${lane}`,
      tsName: `arg${argumentIndex}${lane.toUpperCase()}`,
    })),
  );
}

function hex32(value) {
  return value.toString(16).padStart(8, "0");
}

function normalize(facts) {
  validateFacts(facts);
  return facts.bindings.map((binding) => ({
    ...binding,
    shapes: binding.shapes.map((shape) => ({ ...shape, codecs: [...shape.codecs] })),
  }));
}

export function renderStaticHermesVmathHeader(input) {
  const selected = normalize(input);
  const declarations = selected
    .flatMap((binding) =>
      binding.shapes.map((shape) => {
        const parameters = flattenedParameters(shape.codecs)
          .map(({ cName }) => `float ${cName}`)
          .join(", ");
        return `double ${shape.cFunction}(${parameters});`;
      }),
    )
    .join("\n");
  return `// ${banner}\n#pragma once\n\n#ifdef __cplusplus\nextern "C" {\n#endif\n\n// A quiet NaN reports a generated-shape or engine dispatch error.\n// Sound-typed wrappers convert this sentinel to a deterministic exception.\n${declarations}\n\n#ifdef __cplusplus\n}\n#endif\n`;
}

export function renderStaticHermesVmathSource(input) {
  const selected = normalize(input);
  const functions = selected
    .flatMap((binding) =>
      binding.shapes.map((shape) => {
        const parameters = flattenedParameters(shape.codecs);
        const signature = parameters.map(({ cName }) => `float ${cName}`).join(", ");
        const argumentsSetup = shape.codecs
          .map((codec, argumentIndex) => {
            const laneValues = lanesByCodec[codec]
              .map((lane) => `arg${argumentIndex}_${lane}`)
              .concat(Array(4 - lanesByCodec[codec].length).fill("0.0f"));
            return `  arguments[${argumentIndex}] = makeDefoldValue(ScriptDefoldValueKind::k${codec}, ${laneValues.join(", ")});`;
          })
          .join("\n");
        return `extern "C" double ${shape.cFunction}(${signature}) {\n  ScriptValue arguments[${shape.codecs.length}]{};\n${argumentsSetup}\n  return dispatchScalar(0x${hex32(binding.stableId)}u, arguments, ${shape.codecs.length});\n}`;
      }),
    )
    .join("\n\n");
  return `// ${banner}\n#include <defold_hermes/generated_static_hermes_vmath.h>\n\n#include <defold_hermes/generated_script_value_bindings.hpp>\n\n#include <limits>\n\nnamespace {\nusing defold_hermes::ScriptCallFrame;\nusing defold_hermes::ScriptDefoldValueKind;\nusing defold_hermes::ScriptValue;\nusing defold_hermes::ScriptValueTag;\n\nScriptValue makeDefoldValue(\n    ScriptDefoldValueKind kind,\n    float x,\n    float y,\n    float z,\n    float w) noexcept {\n  ScriptValue value{};\n  value.tag = ScriptValueTag::kDefoldValue;\n  value.defoldKind = kind;\n  value.defoldValue[0] = x;\n  value.defoldValue[1] = y;\n  value.defoldValue[2] = z;\n  value.defoldValue[3] = w;\n  return value;\n}\n\ndouble dispatchScalar(\n    uint32_t stableId,\n    const ScriptValue* arguments,\n    uint32_t argumentCount) noexcept {\n  ScriptValue result{};\n  ScriptCallFrame frame{};\n  frame.stableId = stableId;\n  frame.arguments = arguments;\n  frame.argumentCount = argumentCount;\n  frame.results = &result;\n  frame.resultCapacity = 1;\n  const auto status = defold_hermes::value_binding::dispatch(&frame, nullptr, 0);\n  if (status != defold_hermes::value_binding::DispatchStatus::kSuccess ||\n      frame.resultCount != 1 || result.tag != ScriptValueTag::kNumber) {\n    return std::numeric_limits<double>::quiet_NaN();\n  }\n  return result.number;\n}\n}  // namespace\n\n${functions}\n`;
}

export function renderStaticHermesVmathTypescript(input) {
  const selected = normalize(input);
  const blocks = selected
    .flatMap((binding) =>
      binding.shapes.map((shape) => {
        const parameters = flattenedParameters(shape.codecs);
        const typed = parameters.map(({ tsName }) => `${tsName}: c_f32`).join(", ");
        const names = parameters.map(({ tsName }) => tsName).join(", ");
        const signature = `${binding.id}(${shape.codecs.join(",")})`;
        return `const __ffi_${shape.wrapper} = $SHBuiltin.extern_c(\n  {include: "defold_hermes/generated_static_hermes_vmath.h"},\n  function ${shape.cFunction}(${typed}): c_f64 { throw 0; }\n);\n\nfunction ${shape.wrapper}(${typed}): number {\n  const result: number = __ffi_${shape.wrapper}(${names});\n  if (result !== result) {\n    throw ${JSON.stringify(`deherm Static Hermes dispatch failed: ${signature}`)};\n  }\n  return result;\n}`;
      }),
    )
    .join("\n\n");
  return `// ${banner}\n// Exact float32 lanes cross the C ABI; wrappers return the scalar Lua number.\n"use strict";\n\n${blocks}\n`;
}
